"""Список с провода — четыре исхода, а не «есть/нет».

# Откуда правило

Ключ, которого нет, и ключ, у которого пустой список, — разные ответы.
Первое значит «контракт разошёлся», второе — «сегодня пусто». Сводный
счётчик их путает, и путаница читается как факт: экран показывает пустоту,
человек читает «этого нет».

Третий исход добавляет разбор: строки **есть**, но ни одна не опознана. Это
не «пусто» и не сбой — день показать можно, нельзя молча утверждать, что
строк нет. Наружу идут имена встреченных полей (не значения), чтобы
следующий читатель узнал форму из ответа, а не из выезда на пилот.

# Почему модуль, а не по копии в каждом виде

Второй набор тех же четырёх слов, написанный рядом, разойдётся с первым
молча — ровно тот случай, ради которого в мини-аппе стоит
``tools/lint/schedule_vocabulary_guard.py``. Здесь та же болезнь лечится тем
же способом: одно имя состояния и один вывод на все салонные виды.

# Чем это отличается от строгости ``schedule_frame``

``master_api.services.schedule_frame`` на нераспознанной строке **бросает**
``SalonUnavailable``, и это верно там: испорченная строка искажает расчёт
доступности, а неверная доступность хуже отсутствующей.

Здесь предмет другой — **показ списка**. Спрятать все исключения салона
из-за одной странной строки хуже, чем показать остальные и назвать
проблему. Разная строгость на разных предметах — не непоследовательность,
а разная цена ошибки.
"""

from __future__ import annotations

from typing import Any, Callable

#: Состояния списка. Порядок — от «контракта нет» к «всё разобрано».
ABSENT = "absent"
NONE = "none"
PARSED = "parsed"
UNREADABLE = "unreadable"

RowParser = Callable[[dict[str, Any]], dict[str, Any] | None]


def read_list(
    container: dict[str, Any] | None,
    key: str,
    parse_row: RowParser,
) -> dict[str, Any]:
    """Один список с провода вместе с состоянием.

    Args:
      container: объект, в котором лежит список; ``None`` — тот же исход,
        что отсутствующий ключ, потому что спрашивать не у чего.
      key: имя ключа.
      parse_row: разбор одной строки. Возвращает нормализованную строку или
        ``None``, если строка не опознана. **Опознание — это и имена полей,
        и разбор значений**: строка с верными именами и мусором внутри так
        же непригодна, как строка с чужими именами, и молчаливо ронять её
        нельзя.

    Returns:
      ``{"state": ..., "rows": [...], "seen_fields": [...]}``.
    """

    if container is None or key not in container:
        return {"state": ABSENT, "rows": [], "seen_fields": []}

    raw = container.get(key)
    if not isinstance(raw, list) or not raw:
        # Пустой список и не-список отвечают одинаково: строк нет. Разница
        # между ними интересна логу, а не экрану — обе значат «показать
        # нечего», и разные слова заставили бы человека различать то, чего
        # он не видит.
        return {"state": NONE, "rows": [], "seen_fields": []}

    rows: list[dict[str, Any]] = []
    seen: set[str] = set()
    for item in raw:
        if not isinstance(item, dict):
            continue
        seen |= set(item)
        parsed = parse_row(item)
        if parsed is not None:
            rows.append(parsed)

    if not rows:
        # Строки БЫЛИ. Молчаливый ноль здесь и есть тот дефект, ради
        # которого состояний четыре.
        return {"state": UNREADABLE, "rows": [], "seen_fields": sorted(seen)}

    return {"state": PARSED, "rows": rows, "seen_fields": sorted(seen)}


def read_rows(rows: Any, parse_row: RowParser) -> dict[str, Any]:
    """То же для списка, пришедшего отдельным ответом, а не полем объекта.

    Клиентские методы вроде ``list_schedule_exceptions`` отдают список сам
    по себе — ключа, которого могло не быть, тут нет вовсе, поэтому исход
    ``absent`` недостижим и не выдумывается: не-список отвечает
    ``unreadable``, потому что это разошедшийся контракт, а не пустота.
    """

    if not isinstance(rows, list):
        return {"state": UNREADABLE, "rows": [], "seen_fields": []}
    return read_list({"rows": rows}, "rows", parse_row)


__all__ = ["ABSENT", "NONE", "PARSED", "UNREADABLE", "read_list", "read_rows"]
