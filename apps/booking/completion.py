"""Кто закрыл визит — один ответ на весь контур (решение владельца 30.08).

### Зачем

``completed_at`` отвечает на вопрос «визит закрыт?». Ни одно последствие
завершения визита не спрашивало этого — все спрашивали «человек пришёл?»
и читали ответ на другой вопрос.

След живого круга на пилоте 26.08::

    15:42:50.796   визит закрыт           completed_by = system
    15:42:51.494   уведомление создано    «Оцените мастера»

698 миллисекунд. Автозакрытие срабатывает через три часа после конца
визита и отработало ровно так, как задумано; сломалось то, что за ним
последовало. Запрос отзыва не дошёл только потому, что все push падают
(DRF-1030) — починка push детонировала бы это.

Владелец решил дословно: «гейтим последствия по completed_by».

### Что здесь есть и чего здесь нет

Здесь — один предикат, :func:`confirmed_by_human`, и одно место, где
записан список системных закрывающих. Здесь **нет** запрета на
автозакрытие: визит закрываться должен, иначе он висит вечно и ломает
расписание. Закрываться он должен тише.

### Default-deny

Пустое, ``None`` и незнакомое-но-похожее-на-автомат значение — не
подтверждение. Событие без имени закрывающего приезжает ровно оттуда,
откуда приезжает автозакрытие: сканер, который не считает нужным
представиться, — это и есть сканер. Читать отсутствие поля как «закрыл
человек» значит выдавать неизвестность за подтверждение, а цена ошибки
несимметрична: пропущенный отзыв — потеря, отзыв за визит, которого не
было, — потеря доверия.

Обратная сторона того же выбора: ``confirmed_by_human`` **не** проверяет,
что значение похоже на идентификатор человека. Ayla вольна назвать
закрывающего ``master:<uuid>``, ``admin``, ``staff:14`` или просто
почтой; белый список форм пришлось бы догонять при каждом изменении на
той стороне, и промах читался бы как «закрыл автомат» — то есть тихо
глушил бы последствия за подтверждённые визиты. Чёрный список автоматов
короток, стабилен и ошибается в ту же сторону, что и всё остальное здесь.
"""

from __future__ import annotations

from typing import Any, Final, Mapping

#: Имена, под которыми закрывается автомат. Сравнение — по нижнему
#: регистру со снятыми пробелами.
#:
#: ``system`` — то, что стоит в логе пилота. Остальные — формы, под
#: которыми та же роль встречается в контуре: имя таска, имя
#: расписания, слово из перечисления ``RemoteBookingProxy.Source``.
#: Список короткий намеренно: он должен быть исчерпаемым глазами.
SYSTEM_COMPLETION_ACTORS: Final[frozenset[str]] = frozenset(
    {
        "",
        "system",
        "auto",
        "autoclose",
        "auto_close",
        "automation",
        "cron",
        "scheduler",
        "beat",
        "timer",
        "none",
        "null",
    }
)

#: Значение, которым локальное автозакрытие подписывает свою работу.
SYSTEM_ACTOR: Final[str] = "system"

#: Ключи, под которыми актор закрытия ездит по шине. ``completed_by`` —
#: имя поля Ayla (видно в полезной нагрузке ``/tenants/me/day/``);
#: ``marked_by`` — имя в таксономии §3.1, под которым локальный
#: производитель эмитил его ещё до этого коммита. Читаем оба, потому что
#: гейт обязан работать на обоих путях, а переименовывать поле в
#: контракте перед пилотом — не то изменение, которое стоит риска.
ACTOR_KEYS: Final[tuple[str, ...]] = ("completed_by", "marked_by")


def normalize_actor(value: Any) -> str:
    """Привести значение актора к сравнимому виду."""

    if value is None:
        return ""
    return str(value).strip().lower()


def confirmed_by_human(value: Any) -> bool:
    """Подтвердил ли живой человек, что визит состоялся.

    ``True`` только когда закрывающий назван и это не автомат. Всё
    остальное — ``False``: см. про default-deny в docstring модуля.
    """

    return normalize_actor(value) not in SYSTEM_COMPLETION_ACTORS


def actor_from_event(data: Mapping[str, Any] | None) -> str:
    """Достать актора закрытия из полезной нагрузки события.

    Возвращает сырое значение (не нормализованное) — его пишут в лог и
    в аудит, и там оно должно выглядеть так, как приехало.
    """

    if not data:
        return ""
    for key in ACTOR_KEYS:
        raw = data.get(key)
        if raw:
            return str(raw)
    return ""
