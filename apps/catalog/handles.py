"""Нормализация MAX-хэндла мастера — одна на обоих писателей (DRF-1507).

``CatalogMaster.max_handle`` пишут два места, и они пишут в разных форматах:

* владелец при создании приглашения — ``apps/admin_api/views_invite.py``,
  дословно то, что он набрал в поле «контакт»: на пилоте это ``@anna_styl``,
  но ничто не мешает набрать ``anna_styl`` или ``@Anna_Styl``;
* приземление в Mini App — ``apps/master_api/views.py``, из
  HMAC-подписанного ``initData``: ``user.username`` MAX отдаёт **без**
  ведущей ``@``.

Пока сравнение шло по сырой строке, «@anna_styl» и «anna_styl» были разными
людьми для идемпотентности повторного приглашения — и повторное приглашение
того же мастера заводило вторую строку не потому, что так задумано, а
потому, что владелец в этот раз не поставил собаку.

Две функции, и обе намеренно маленькие:

* :func:`normalize_handle` — ключ сравнения. Регистр и ведущая ``@``
  значения не имеют: MAX-аккаунт один и тот же.
* :func:`canonical_handle` — форма хранения. Ведущая ``@`` ставится, потому
  что именно её видит владелец в админке и именно её он набирает в
  следующий раз.

Ограничения уникальности на столбце **нет** и в этой задаче не появилось —
см. отчёт DRF-1507 и комментарий в ``apps/catalog/models.py``: столбец
хранит свободный текст, набранный человеком, и уникальность по сырому
значению одновременно и слишком строга (падение на живых данных), и слишком
слаба (``@anna`` и ``anna`` её не нарушают). Гарантию «один человек — одна
строка» здесь держит писатель, а не индекс.
"""

from __future__ import annotations


def normalize_handle(value: str | None) -> str:
    """Ключ сравнения двух хэндлов. ``""`` — «хэндла нет».

    Пустое значение никогда не равно другому пустому: вызывающий обязан
    проверить результат на истинность до сравнения, иначе все строки без
    хэндла склеятся в одного человека.
    """

    if not value:
        return ""
    return value.strip().lstrip("@").strip().casefold()


def canonical_handle(value: str | None) -> str:
    """Форма хранения: ``@`` + то, что набрано, без изменения регистра.

    Регистр сохраняется — он часть того, как человек пишет своё имя, и
    отображается в карточке; для сравнения есть :func:`normalize_handle`.
    """

    if not value:
        return ""
    bare = value.strip().lstrip("@").strip()
    return f"@{bare}" if bare else ""


__all__ = ["canonical_handle", "normalize_handle"]
