"""Одно определение того, где мастер стоит между «приглашена» и «в архиве».

DRF-1506. До этого модуля определений было пять, и каждое игнорировало
свой столбец:

======================================================  ==================
место                                                   игнорировало
======================================================  ==================
``_MasterManager.bookable()``                           ``archived_at``
``apps.master_api.auth.require_master_init_data``       ``invite_status``
``apps.identity.services.role_resolver.resolve_role``   ``is_active``
``apps.admin_api.services.staff_roster._master_state``  ``linked_bot_user``
``apps.admin_api.services.master_deactivation``         ``linked_bot_user``
======================================================  ==================

Расхождение уже стоило одного инцидента (DRF-1080: мастер, принявшая
приглашение, была мастером для ``resolve_role`` и «неактивна» для
``require_master_init_data``), и его залатали двумя точечными починками
в месте потребления, а не в определении.

Здесь определение одно, и оно трёхслойное — потому что вопросов на
самом деле три, и путать их дороже, чем различать. Третий слой добавила
DRF-1521; до неё их было два, и второй молча отвечал за третий.

Продаётся ли она клиенту (:func:`is_available`)
-----------------------------------------------
Каталожный вопрос: административно в порядке (:func:`is_admitted` —
``is_active`` И не в архиве И приглашение принято) И у строки есть
канонический ``ayla_user_id``.

**Про ``linked_bot_user`` он не спрашивает — и это не забывчивость.**
На боевом контуре 05.09.2026 девять активных мастеров, у всех
``linked_bot_user IS NULL``: они приехали синхронизацией, а она
платформенных полей не трогает (см. докстринг ``CatalogMaster``).
Добавить сюда требование бот-аккаунта — значит немедленно снять с
продажи всех девятерых.

**Про ``ayla_user_id`` он спрашивает — DRF-1540, решение владельца
06.09.2026.** Мастер из приглашения и та же мастер из синхронизации
живут двумя строками, и склеить их сегодня не по чему: ``ayla_user_id``
есть только у синхронизированной, ``max_handle`` только у инвайт-строки.
Строка без ``ayla_user_id`` продаётся клиенту, а уведомление о записи
уходит по мосту ``master_user_id`` → и не доходит до человека. Владелец
выбрал видимый отказ вместо молчаливого: **непроданный мастер лучше
проданного, до которого не доходят уведомления.** Настоящая починка —
канонический идентификатор в приглашении, контракт Ayla (DRF-1541).

Приземлилась ли она в боте (:func:`is_landed`)
----------------------------------------------
Вопрос онбординга: административно в порядке И у неё есть привязанный
``BotUser`` И проставлен ``accepted_at``. Это то, чего требует
``docs/design/policies/master-onboarding-m0-m7.md`` §4.1 от состояния M1.

**Приземление про ``ayla_user_id`` НЕ спрашивает,** и это тоже решение,
а не пропуск: мастер, которую не удалось связать с Ayla, в кабинет
входит — она там нужна, чтобы заполнить профиль и увидеть, что с ней
не так. На витрину её не пускает :func:`is_available`. Поэтому базой
для ``LANDED`` служит :data:`ADMITTED`, а не :data:`AVAILABLE`.

Ту же по смыслу границу проводит DRF-1521 («не продаётся до заполнения
профиля, но в кабинет входит»), но одной базой обе не обошлись:
``ADMITTED`` спрашивает ``is_active``, а граница DRF-1521 проходит
ровно по нему. Ей понадобился свой предикат — :data:`ENROLLED`, раздел
ниже.

Пускают ли её в кабинет (:func:`is_enrolled`) — DRF-1521
--------------------------------------------------------
Не в архиве И приглашение принято И есть личность. **Про ``is_active``
не спрашивает, и это третий предикат, а не переопределение второго.**

Задача DRF-1521 написана на утверждении, что развязка уже построена:
``is_landed`` отвечает за кабинет, ``is_available`` — за витрину, и обе
стороны выполнимы одновременно. В коде до неё это было неверно.
:data:`LANDED` строилось поверх :data:`ADMITTED`, а ``ADMITTED``
спрашивает ``is_active`` — значит при снятой активности ложны **оба**
предиката, и состояние «в кабинет входит, но не продаётся» имеющимися
средствами было невыразимо. Двух предикатов на три вопроса не хватило:
они выстроились в цепочку вместо развилки.

Один столбец ``is_active`` кормит теперь ровно те вопросы, на которые
умеет отвечать:

======================================  ==============================
вопрос                                  предикат
======================================  ==============================
продаётся ли она клиенту                :data:`AVAILABLE`
пускается ли она в кабинет              :data:`ENROLLED`
считается ли она мастером               :data:`ENROLLED`
прошла ли она онбординг и на витрине   :data:`LANDED`
======================================  ==============================

:data:`LANDED` осталась ровно тем, чем была, и это осознанно: на неё
опираются тесты онбординга и она означает состояние M1 плюс витрину.
Переопределить её было бы дешевле на одну строку и дороже на одно
молчаливое изменение смысла у всех, кто её уже читает.

Почему кабинет не должен закрываться вместе с витриной: мастер,
которую сняли с продажи, — это человек, которому НУЖНО войти и
починить то, из-за чего её сняли. Закрытая дверь оставляет её без
способа что-либо изменить, и ровно так выглядел инцидент DRF-1080, где
она получала 403 на каждой ручке мастер-приложения. Дверь, которая
закрывается по-настоящему, одна — архив: он означает «ушла», а не
«не на витрине».

Гейты продажи на этот предикат НЕ переводятся и не должны:
``CatalogMaster.objects.bookable()`` и подбор замены при деактивации
спрашивают ``is_available``, потому что их вопрос — про витрину, и
``is_active`` там уместен.

Почему гейт отвечает причиной, а не «да/нет» (:func:`sale_block`)
-----------------------------------------------------------------
У владелицы салона два разных отказа требуют **двух разных действий**:
«приглашение не принято» — она идёт к мастеру, «не удалось связать
профиль с Ayla» — она идёт к нам. Один текст на две причины отправит её
чинить не там, поэтому :func:`sale_block` возвращает **почему**, а
``is_available`` — производное «нет причины».

Порядок проверок в :func:`sale_block` — это ответ на вопрос «какую из
двух одновременных причин показать»: сначала та, где действие владелицы
очевиднее. Архив старше всего, дальше непринятое приглашение, дальше
снятая активность, и только потом связь с Ayla — потому что «не удалось
связать» осмысленно ровно для той, кто уже пришла и выглядит рабочей.

**Сюда встроилась DRF-1521** — четвёртым значением
:data:`SaleBlock` (``profile_incomplete``) и одной веткой внутри
проверки ``is_active``, а не отдельным гейтом рядом: отдельный гейт дал
бы мастера, который не продаётся, и ни одно место не объяснило бы
почему. Тест ``test_role_state_is_active_plus_every_sale_block`` не даёт
добавить причину в одну половину словаря и забыть про вторую.

Ветка встала не в конец, а внутрь ``is_active``, и это не стилистика.
Снятая активность отвечает на два разных вопроса владелицы: «я сама
сняла её с витрины» (действий нет, слово ``revoked`` честное) и «она
приняла приглашение и не дозаполнила профиль» (владелица идёт к
мастеру). Различает их :func:`_profile_is_filled`, потому что колонками
они не различимы — после DRF-1521 п. 4 обе причины будут писать
``is_active=False`` при ACCEPTED. Из трёх условий готовности,
утверждённых владельцем 06.09.2026, выразимы теперь два; какое одно
недостаёт и почему — в докстринге :func:`_profile_is_filled`.

**§83 добавил пятое значение — ``schedule_unconfirmed`` — и оно встало
СВОЕЙ веткой в конец, а не строкой внутри :func:`_profile_is_filled`.**
Это не расхождение с замыслом DRF-1521, а следствие того, что тот
замысел на живых данных не срабатывает. ``_profile_is_filled`` зовётся
только изнутри ветки ``not is_active`` и выбирает СЛОВО для отказа, а не
отказывает; тридцать один продаваемый мастер пилота приехал
синхронизацией с ``is_active=True``, и до этой ветки они не доходят
вовсе. Вдобавок ``is_active`` — зеркальное поле, которое
``upsert_specialists`` перезаписывает каждый прогон, так что удержать
его в ``False`` локально нельзя. Требование владельца «до подтверждения
мастер гейт не проходит» — это ОТКАЗ, и выразить его можно только
собственным конъюнктом в :data:`AVAILABLE` и собственной веткой здесь.

Ветка стоит последней намеренно: отказ, показанный владелице, — это
обещание «почини вот это, и мастер станет продаваться», и показывать
«подтвердите расписание» строке, которая вдобавок не связана с Ayla,
значило бы соврать.

**И она за флагом** (``MASTER_SCHEDULE_CONFIRMATION_REQUIRED``, по
умолчанию выключен) — порядок работ DRF-1521 п. 7: сперва признак и
способ его поставить, потом кампания подтверждения, и только потом гейт.
В момент включения с витрины уходят все мастера без актуального
подтверждения; это верно по правилу 1 решения владельца и это видимое
изменение продукта.

**На живых данных ``profile_incomplete`` сегодня недостижим.** Имя
заполнено у всех строк: ``PATCH`` не принимает пустое, путь приглашения
требует имя, синхронизация кладёт ``dto.name``. Исход готов и покрыт
тестом, но продакшен его пока не создаёт — и не создаст, пока не
приедут пп. 4-6.

Приземление строго сильнее доступности: приземлившийся мастер проходит
все пять ворот, неприземлившийся не проходит ни одних из тех, что
спрашивают про личность. Синхронизированный мастер — третий случай,
названный и защищённый тестом: продаётся, но в мастер-приложение не
входит, потому что входить ей нечем.

Три клиентские поверхности — найдено DRF-1540, переведено DRF-1544
------------------------------------------------------------------
Предикат продажи здесь один, но до DRF-1544 читали его не все. Три
клиентские поверхности набирали ``is_active`` + ``invite_status``
заново и потому НЕ спрашивали ни ``archived_at`` (расхождение старше
DRF-1540), ни ``ayla_user_id``:

======================================================  ==========================
место                                                   что показывает
======================================================  ==========================
``apps/marketplace/discovery.py`` ``_bookable_qs``      подбор мастеров клиенту
``apps/marketplace/discovery.py`` ``_known_cities``     города, где есть мастера
``apps/skills/booking/skill.py``                        ростер имён в промпт
``_load_tenant_master_roster``
======================================================  ==========================

Все три теперь фильтруют по :data:`AVAILABLE`. Смысл перевода не в том,
что сегодня они кого-то лишнего показывали — на пилоте 06.09.2026
несвязанных среди бронируемых не было, и замер до/после сужения не дал.
Смысл в том, что следующее условие (готовность профиля, DRF-1521)
приезжает во все три места само, а не четвёртой копией.

**Новой копии заводить нельзя.** Если новому месту нужен вопрос
«продаётся ли она» — оно читает :data:`AVAILABLE` или
:meth:`CatalogMaster.objects.bookable`, а построчному — :func:`sale_block`.

Последние три места — переведены DRF-1548 и DRF-1549
---------------------------------------------------
Ещё три места набирали условия руками и в DRF-1544 не трогались. Две из
них — построчные перепроверки при записи и при переносе — спрашивают
:func:`sale_block` с DRF-1548:

======================================================  ==========================
место                                                   что спрашивает
======================================================  ==========================
``apps/booking/services/create.py``                     перепроверка мастера
                                                        под локом при записи
``apps/booking/services/transitions.py``                то же при переносе
======================================================  ==========================

Обе идут не напрямую, а через
``apps.booking.services.master_gate.master_sale_refusal``: им нужна
ПРИЧИНА отказа (типизированный слаг), а не булево, и слаг у обеих
обязан быть один — иначе он окажется назван в одной таблице статусов и
забыт в другой.

Третье переведено DRF-1549: ``apps/miniapp_api/views.py``,
``_bookable_master_exists`` — витрина каталога, «есть ли у услуги
бронируемый исполнитель». Оно спрашивает не свой набор столбцов, а
``CatalogMaster.objects.bookable()`` — ту самую выборку, которую отдаёт
подборщик мастеров ``GET /masters?service_id=``. Требование здесь чуть
сильнее, чем «читать AVAILABLE»: витрина обязана обещать РОВНО тех,
кого подборщик покажет, иначе клиент видит услугу доступной и упирается
в пустой экран выбора мастера (DRF-1164). Копия столбцов там уже
разъехалась молча — она пережила добавление ``ayla_user_id`` в
:data:`AVAILABLE`, и её докстринг при этом продолжал утверждать паритет.
Держит равенство тест
``apps/miniapp_api/tests/test_views.py::TestCatalogShelfMatchesPicker``:
он сравнивает ответы двух поверхностей на всех формах строки мастера, а
не поведение каждой по отдельности.

**Ручных копий предиката продажи больше не осталось ни одной.** Гейт —
единственный способ ответить на вопрос «продаётся ли она», а не один из
способов; раздел «что не накрыто» закрыт.

``accepted_at`` держит модель
-----------------------------
:meth:`CatalogMaster.save` штампует ``accepted_at`` в момент, когда
строка впервые оказывается связанной и принятой, и никогда не стирает
его. Поэтому ``accepted_at IS NULL`` при связанной и принятой строке —
не «легаси», а сигнал, что кто-то записал состояние в обход модели.
Держать столбец в предикате стоит одного ``AND`` и ловит ровно этот
случай.
"""

from __future__ import annotations

from typing import Any, Final, Literal, Mapping

from django.db.models import Q

#: Значение ``CatalogMaster.InviteStatus.ACCEPTED`` строкой.
#:
#: Литерал, а не импорт: ``apps.catalog.models`` импортирует этот модуль,
#: чтобы собрать ``bookable()``, и обратный импорт замкнул бы цикл на
#: загрузке приложения. Литерал закреплён за перечислением тестом
#: ``test_accepted_literal_matches_the_enum`` — разъехаться молча он не
#: может.
ACCEPTED: Final[str] = "accepted"

#: Почему мастер НЕ продаётся клиенту. ``None`` — продаётся.
#:
#: Словарь причин, а не булево: см. раздел докстринга модуля. Каждое
#: значение — это отдельное действие владелицы салона, и два действия не
#: имеют права делить один текст.
#:
#: **Расширяется, а не дублируется.** DRF-1521 добавляет сюда
#: ``profile_incomplete`` и ветку в конце :func:`sale_block`; строить
#: второй гейт рядом запрещено — тогда мастер не продаётся, а ни одно
#: место не отвечает почему, и это ровно тот дефект, ради которого этот
#: механизм заведён.
SaleBlock = Literal[
    "pending", "revoked", "ayla_unlinked", "profile_incomplete", "schedule_unconfirmed"
]

#: Состояние строки для ростера: где она между «приглашена» и «в архиве».
#:
#: Ровно ``"active"`` плюс каждое значение :data:`SaleBlock` — ростер не
#: имеет права знать меньше причин, чем витрина. Равенство держит тест
#: ``test_role_state_is_active_plus_every_sale_block``.
RoleState = Literal[
    "active",
    "pending",
    "revoked",
    "ayla_unlinked",
    "profile_incomplete",
    "schedule_unconfirmed",
]

#: Административно всё в порядке: активна, не в архиве, приглашение принято.
#:
#: Не «продаётся» — это только та часть вопроса, которая про решения
#: салона. Продажа спрашивает сверху ещё и про связь с Ayla
#: (:data:`AVAILABLE`), вход в кабинет — про личность (:data:`LANDED`), и
#: эти две надстройки намеренно разные.
ADMITTED = Q(is_active=True, archived_at__isnull=True, invite_status=ACCEPTED)

#: У строки есть канонический ``ayla_user_id`` — мост для ``master_user_id``.
#:
#: ``ayla_user_id`` это ``UUIDField(null=True)``: пустой строки в нём не
#: бывает, поэтому ``IS NOT NULL`` — полная проверка, а не половина.
LINKED_TO_AYLA = Q(ayla_user_id__isnull=False)

#: Расписание мастера подтверждено владельцем салона (§83).
#:
#: Спрашивается ТОЛЬКО наличие столбца, а не совпадение отпечатка с
#: нынешними часами. Сверка отпечатка — сетевой вызов на человека, а этот
#: предикат зовётся в цикле по ростеру; актуальность держит сброс в момент
#: изменения часов (``apps.catalog.services.schedule_confirmation``).
SCHEDULE_CONFIRMED = Q(schedule_confirmed_at__isnull=False)


def _schedule_gate_enabled() -> bool:
    """Требует ли гейт подтверждения расписания. §83, порядок DRF-1521 п. 7.

    Умолчание — ВЫКЛЮЧЕНО, и это не осторожность: в момент включения с
    витрины уходят все мастера без актуального подтверждения. Сперва
    признак и способ его поставить, потом кампания, и только потом гейт.
    """

    from django.conf import settings

    return bool(getattr(settings, "MASTER_SCHEDULE_CONFIRMATION_REQUIRED", False))


#: Мастер продаётся клиенту (DRF-1540 — И связана с Ayla; §83 — И расписание).
#:
#: **Читается при импорте, и это осознанная разница с остальным модулем.**
#: ``Q`` — значение, а не вызов: собрать его лениво нельзя, а превратить в
#: функцию значило бы переписать четыре чтения в чужих пакетах
#: (``marketplace/discovery``, ``marketplace/resolver_keys``,
#: ``skills/booking/skill``) ради флага, который на боевом контуре живёт в
#: переменной окружения и без перезапуска процесса всё равно не меняется.
#:
#: Для тех, кому нужен ответ в МОМЕНТ вызова — ``override_settings`` в
#: тестах, будущий рантайм-переключатель, — есть :func:`available_q`. Что
#: эти двое не разъедутся, держит тест
#: ``test_available_constant_equals_the_runtime_predicate``.
AVAILABLE = ADMITTED & LINKED_TO_AYLA & (SCHEDULE_CONFIRMED if _schedule_gate_enabled() else Q())


def available_q() -> Q:
    """:data:`AVAILABLE`, посчитанный на нынешних настройках.

    Тот же предикат, но флаг читается сейчас, а не при импорте. Этим
    пользуется ``CatalogMaster.objects.bookable()`` — единственная воронка,
    через которую ходит витрина, — и тесты обеих сторон флага.

    Своего условия не набирает: части те же самые, поэтому разъехаться с
    :data:`AVAILABLE` ему нечем, кроме момента чтения флага.
    """

    base = ADMITTED & LINKED_TO_AYLA
    return base & SCHEDULE_CONFIRMED if _schedule_gate_enabled() else base

#: Мастер продавался бы, если бы оператор верифицировал приглашение.
#:
#: DRF-1553. Это :data:`AVAILABLE` с единственным перевёрнутым условием —
#: приглашением. Форма записи такая намеренно: набрать столбцы заново
#: значило бы завести предикат, который переживёт следующее ужесточение
#: гейта (DRF-1521 добавляет ``profile_incomplete``) и начнёт обещать
#: продажу тем, кого продажа уже не пустит. Равенство
#: ``AWAITING_VERIFICATION & accepted == AVAILABLE`` держит тест
#: ``test_awaiting_verification_is_available_minus_the_invite``.
#:
#: Обещание, которое этот предикат даёт экрану подключения: верификация
#: ЭТИХ строк делает их бронируемыми — ровно столько, сколько
#: верифицировали. Поэтому мастер в архиве или с ``is_active=False``
#: сюда не попадает: верифицировать его можно, но салон от этого видимым
#: не станет, и кнопка «после верификации салон появится в поиске»
#: соврала бы.
AWAITING_VERIFICATION = (
    Q(is_active=True, archived_at__isnull=True) & LINKED_TO_AYLA & ~Q(invite_status=ACCEPTED)
)

#: У строки есть личность: привязанный ``BotUser`` и штамп ``accepted_at``.
#:
#: Вынесено в отдельную ``Q`` (DRF-1521), потому что этих двух столбцов
#: спрашивают теперь двое — :data:`LANDED` и :data:`ENROLLED`, — а копия
#: условия в каждом из них разъехалась бы ровно так, как разъезжались
#: пять определений до DRF-1506. Значение :data:`LANDED` от выноса не
#: изменилось: ``ADMITTED & HAS_IDENTITY`` это те же пять столбцов.
HAS_IDENTITY = Q(linked_bot_user__isnull=False, accepted_at__isnull=False)

#: Мастер приземлилась в боте: административно в порядке И есть личность.
#:
#: База — :data:`ADMITTED`, а не :data:`AVAILABLE`, и это несущая деталь
#: DRF-1540: несвязанная с Ayla мастер в кабинет входит, на витрину не
#: попадает. Подмена базы на ``AVAILABLE`` заперла бы её снаружи.
#:
#: **Про ``is_active`` спрашивает — и поэтому в кабинет пускает не она,
#: а :data:`ENROLLED`.** См. раздел докстринга «Пускают ли её в кабинет».
LANDED = ADMITTED & HAS_IDENTITY

#: Мастер пускается в кабинет: не ушла из салона И есть личность.
#:
#: Третий предикат, DRF-1521. Отличается от :data:`LANDED` ровно одним
#: столбцом — не спрашивает ``is_active``, — и в этом весь смысл: витрина
#: не судья кабинету. Развёрнутое обоснование — в докстринге модуля.
#:
#: ``archived_at IS NULL`` и ``invite_status = ACCEPTED`` повторены здесь,
#: а не взяты из :data:`ADMITTED`: вычесть условие из готовой ``Q``
#: нельзя, а собрать «ADMITTED без is_active» отдельной константой значило
#: бы завести четвёртое имя ради одного использования. Что эти две
#: половины остаются половинами одного целого, держит тест
#: ``test_enrolled_is_landed_minus_is_active``.
ENROLLED = Q(archived_at__isnull=True, invite_status=ACCEPTED) & HAS_IDENTITY


def _field(row: Any, name: str) -> Any:
    """Значение поля у модели или у словаря из ``.values()``.

    Ростер читает строки через ``.values()`` — там нет атрибутов, и
    заставлять его собирать объект ради предиката было бы лишним
    запросом на человека.
    """

    if isinstance(row, Mapping):
        return row[name]
    return getattr(row, name)


def is_admitted(row: Any) -> bool:
    """Административная половина — построчный двойник :data:`ADMITTED`.

    Отдельная функция, потому что на неё опираются два разных вопроса:
    продажа (:func:`is_available`, сверху ещё связь с Ayla) и вход в
    кабинет (:func:`is_landed`, сверху ещё личность). Без неё
    ``is_landed`` пришлось бы строить поверх ``is_available``, и
    ужесточение продажи молча заперло бы мастера снаружи кабинета — это
    и есть тот класс склейки, который DRF-1506 разбирал в пяти местах.
    """

    return (
        bool(_field(row, "is_active"))
        and _field(row, "archived_at") is None
        and _field(row, "invite_status") == ACCEPTED
    )


def _has_identity(row: Any) -> bool:
    """Есть ли у строки личность — построчный двойник :data:`HAS_IDENTITY`.

    У модели читает ``linked_bot_user_id``, чтобы не дёргать связанный
    ``BotUser`` ради проверки на NULL. У словаря принимает оба написания
    ключа: ростер зовёт ``.values("linked_bot_user_id")``, а тесты
    собирают строку руками и пишут короче.

    ``accepted_at`` спрашивается строго: ключа нет — ``KeyError``. Строку
    в гейт передают целиком, и молчаливое умолчание здесь читалось бы как
    «личности нет», то есть как отказ без причины.
    """

    if isinstance(row, Mapping):
        linked = row.get("linked_bot_user_id", row.get("linked_bot_user"))
    else:
        linked = row.linked_bot_user_id
    return linked is not None and _field(row, "accepted_at") is not None


def _profile_is_filled(row: Any) -> bool:
    """Готов ли профиль настолько, чтобы мастера можно было продавать.

    **Сегодня здесь живёт первое из трёх условий владельца** (решение от
    06.09.2026): имя заполнено. Два других — активная услуга с ценой и
    явно подтверждённое человеком расписание — сюда ещё не приехали, и не
    по забывчивости:

    * услуга с ценой — это запрос по связи, а гейт построчный и зовётся в
      цикле по ростеру; тянуть ``MasterService`` на человека значит
      вернуть тот самый N+1, ради отсутствия которого ростер читает
      ``.values()``;
    * подтверждение расписания **приехало §83** — и НЕ сюда. Признак
      живёт на ``CatalogMaster`` (решение владельца 09.09.2026), а
      условие — собственной веткой :func:`sale_block` и собственным
      конъюнктом в :data:`AVAILABLE`. Причина в том, что эта функция
      отказа не выносит: её зовёт только ветка ``not is_active``, а
      тридцать один продаваемый мастер пилота стоит с ``is_active=True``
      из синхронизации и до неё не доходит. Подробно — в докстринге
      модуля.

    Поэтому функция названа по вопросу, а не по единственному условию:
    услуга с ценой дописывается сюда — она и правда лишь ВЫБИРАЕТ СЛОВО
    для уже случившегося отказа, — а условие, которое само отказывает,
    сюда не помещается.

    **Она никого не снимает с продажи.** Её зовёт только ветка
    :func:`sale_block`, в которой мастер уже не продаётся по
    ``is_active``; она выбирает СЛОВО для отказа, а не сам отказ. Порядок
    работ, который это запрещает нарушать, записан в DRF-1521 п. 7: сперва
    признак и способ его поставить, потом кампания подтверждения по уже
    подключённым мастерам, и только потом — гейт, и за флагом.
    """

    name = _field(row, "name")
    return bool(name and name.strip())


def sale_block(row: Any) -> SaleBlock | None:
    """Почему этот мастер не продаётся клиенту; ``None`` — продаётся.

    Единственное место, где живёт ответ «почему». ``is_available`` и
    ``master_state`` — производные от него, и разъехаться им нечем.

    Порядок веток разобран в докстринге модуля: он решает, какую из
    одновременных причин увидит владелица салона. ``ayla_unlinked``
    стоит последним намеренно — «не удалось связать профиль с Ayla»
    имеет смысл ровно для той мастера, которая уже пришла, принята и
    активна, то есть выглядит рабочей и молча не продавалась бы.

    DRF-1521 дописала свою ветку внутрь проверки ``is_active``, §83 —
    свою в самый конец; существующие не тронуты ни одной из них.
    """

    if _field(row, "archived_at") is not None:
        return "revoked"
    if _field(row, "invite_status") != ACCEPTED:
        return "pending"
    if not _field(row, "is_active"):
        # DRF-1521. ``is_active=False`` отвечает на два разных вопроса, и
        # владелице салона они требуют двух разных действий.
        #
        # «Отозван» — это её собственное решение: снять мастера с витрины
        # (``PATCH /admin/masters/<id>`` с ``is_active: false``) или
        # деактивировать с каскадом (там же проставляется ``archived_at``,
        # и его ловит ветка выше). Чинить нечего — она сама так решила.
        #
        # «Профиль не заполнен» — это состояние человека, который принял
        # приглашение, завёл личность и остановился на полпути. Владелица
        # идёт к мастеру, а не ищет, кто отозвал доступ. Ровно эту ложь
        # DRF-1506 убирал для PENDING; здесь та же ложь для ACCEPTED.
        #
        # Разводит их состояние профиля, потому что колонками они не
        # различимы: после DRF-1521 п. 4 ``onboarding_accept`` перестанет
        # ставить ``is_active=True``, и обе причины будут писать одну и ту
        # же строку. Различать их — работа :func:`_profile_is_filled`.
        #
        # На живых данных 07.09.2026 эта ветка недостижима: имя заполнено
        # у всех (``PATCH`` не принимает пустое, путь приглашения требует
        # имя, синхронизация кладёт ``dto.name``), поэтому снятая с
        # витрины мастер по-прежнему читается как ``revoked``. Форма
        # строки собирается в тесте — исход готов, а не работает.
        if _has_identity(row) and not _profile_is_filled(row):
            return "profile_incomplete"
        return "revoked"
    if _field(row, "ayla_user_id") is None:
        # DRF-1540. Пустой ключ — это мастер, до которой не дойдёт ни
        # одно уведомление о записи: мост ``master_user_id`` идёт через
        # этот столбец. Прокси-id сюда писать запрещено (он занял бы
        # ключ значением, по которому совпадения не будет никогда), а
        # склейка по имени или телефону — признак, дающий уверенность
        # без основания. Поэтому здесь отказ, а не догадка.
        return "ayla_unlinked"
    if _schedule_gate_enabled() and _field(row, "schedule_confirmed_at") is None:
        # §83. Ветка стоит ПОСЛЕДНЕЙ, и это не порядок написания.
        #
        # Отказ, который видит владелица салона, — это обещание: «почини
        # вот это, и мастер станет продаваться». Покажи мы «подтвердите
        # расписание» строке, которая вдобавок не связана с Ayla, — она
        # нажмёт кнопку, а мастер продаваться не начнёт, и экран соврал.
        # Тот же довод, по которому очередь верификации не показывает
        # архивных: обещать исход, которого не будет, нельзя.
        #
        # Спрашивается наличие столбца, а не совпадение отпечатка: сверка
        # означала бы сетевой вызов на человека в цикле по ростеру — тот
        # самый N+1, ради отсутствия которого ростер читает ``.values()``.
        # Актуальность держит сброс в момент изменения часов.
        return "schedule_unconfirmed"
    return None


def is_available(row: Any) -> bool:
    """Продаётся ли этот мастер клиенту — построчный двойник :data:`AVAILABLE`."""

    return sale_block(row) is None


def is_landed(row: Any) -> bool:
    """Приземлилась ли она — построчный двойник :data:`LANDED`.

    Принимает и модель, и словарь; чтение личности — в
    :func:`_has_identity`.

    Спрашивает :func:`is_admitted`, а не :func:`is_available`: вход в
    кабинет не зависит от связи с Ayla — см. докстринг модуля.

    **Вход в кабинет спрашивает не её, а :func:`is_enrolled`.** Эта
    функция осталась тем, чем была: «прошла онбординг и стоит на
    витрине». Её читают тесты онбординга и она означает ровно это.
    """

    return is_admitted(row) and _has_identity(row)


def is_enrolled(row: Any) -> bool:
    """Пускать ли её в кабинет — построчный двойник :data:`ENROLLED`.

    Три вопроса и ни одного лишнего: не в архиве, приглашение принято,
    личность есть. Про ``is_active`` не спрашивает намеренно — см.
    раздел докстринга модуля «Пускают ли её в кабинет».
    """

    return (
        _field(row, "archived_at") is None
        and _field(row, "invite_status") == ACCEPTED
        and _has_identity(row)
    )


def master_state(row: Any) -> RoleState:
    """Каким словом ростер владелицы называет эту строку каталога.

    Тонкая обёртка над :func:`sale_block` — и обёртка это вся суть:
    ростер и витрина отвечают на один вопрос одним кодом, поэтому
    «не продаётся» на витрине и слово в ростере не могут разойтись.
    Раньше здесь лежала своя копия трёх условий.

    Порядок проверок — не стилистика, это была вторая половина
    DRF-1506. Прежний порядок спрашивал ``not is_active`` раньше
    ``invite_status``, а путь приглашения пишет ``is_active=False``
    вместе с ``PENDING`` (``apps/admin_api/views_invite.py``) и пишет
    так намеренно: приглашённая мастер не должна попасть на витрину,
    пока не ответила. В итоге владелице салона только что приглашённого
    мастера показывали как «доступ отозван» — слово, за которым она
    пойдёт искать, кто отозвал, вместо того чтобы повторить приглашение.

    Архив идёт первым и остаётся первым: мастер, которую заархивировали
    с непринятым приглашением, ушла, а не ждёт.

    Всё, что короче ACCEPTED, — ``pending``: EXPIRED и CANCELLED это
    люди, которые не пришли, и «приглашена» — честное слово для строки,
    за которой никого нет.

    Принимает строку целиком (модель или словарь из ``.values()``), а не
    перечисленные столбцы: колонок в вопросе стало четыре, и следующая
    задача добавит свои. Именованные аргументы заставляли бы каждого
    вызывающего пересобирать список при каждом расширении гейта, а
    забытый аргумент читался бы как «условие не применилось».
    """

    return sale_block(row) or "active"


