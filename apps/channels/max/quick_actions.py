"""C01 First Contact — Quick Actions and the taps that are not commands.

Утверждённый макет: ``ТЗ Дизайнеру/Клиент/Спецификация UX UI Первый контакт
Ayla.png``, версия 1.0, статус APPROVED, экран **C01 — First Contact**.

Блок ВАЖНО макета говорит одно и то же дважды:

    «Нажатие на Quick Action вставляет текст в composer и отправляет его
     по тому же pipeline, что и свободный текст. **Нет отдельных команд и
     сценариев.**»

На MAX «вставить в composer» буквально невозможно: тап по inline-кнопке
приходит тем же полем ``CanonicalEvent.text``, что и набранное сообщение,
только со значением payload'а. Поэтому «тот же pipeline» здесь строится
**подстановкой на входе**: :func:`resolve_tap_text` переводит payload в ту
самую фразу, которую человек мог бы набрать руками, и обработчик подменяет
``event.text`` **до** записи сообщения и до первой развилки лестницы. Ниже
по течению — история, safety, :mod:`apps.orchestrator.fast_path`, консьерж —
никто не может отличить тап от набора, потому что отличать уже нечего.

Тот же приём, что у :data:`apps.skills.menu.matching.MENU_CALLBACK_TEXT` на
арендаторском пути («тап переводится в каноническую фразу, которую навык уже
и так забирает»), только применённый на ход раньше — до персистенса, а не
внутри навыка. Это заодно закрывает класс DRF-990 для этих кнопок: в
историю глобального диалога ложится фраза, а не сырой ``cb:…`` payload.

### Почему payload — слаг, а не сам текст чипа

Класть в payload готовую фразу было бы ещё «честнее», но: старая клавиатура
в истории чата пережила бы правку копии и слала бы вчерашний текст, а лог
пришлось бы писать с содержимым сообщения (запрещено #842 — только длины).
Слаг решает оба: он переводится в **сегодняшнюю** формулировку, а в лог
уходит слаг, а не то, что человек читает.

### Ограничение владельца на формулировки (DRF-1348, решение 24.08)

    «Goal-like quick actions не должны называться услугами.»

Причина не стилистическая, а маршрутная. Чип, звучащий как потребность,
уходит консьержу **сам собой**: этих слов нет в словаре
:mod:`apps.orchestrator.fast_path`, и дописывать быстрой ветке отдельный
отказ не приходится. Замер DRF-1328 (``docs/REPORT_DRF1328.md``, раздел
«ходы, названные целью»): 15 формулировок такого вида из 16 уходят
консьержу. ``_SERVICE_QUALIFIER_STEMS`` при этом **не тронут** — чип, чей
текст сам является названием услуги («Расслабляющий массаж»), по-прежнему
отвечается карточками мастеров, и это правильный ответ; поэтому чипы просто
не называются услугами.

Инвариант пришпилен тестом, а не соглашением: см.
``apps/channels/tests/test_first_contact_c01.py::TestChipsAreNotServiceNames``.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass
from typing import Any

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Quick Actions
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class QuickAction:
    """Один чип C01: слаг для payload'а, подпись и та самая фраза.

    ``label`` и ``text`` совпадают у goal-like чипов намеренно: человек
    должен видеть на кнопке ровно то сообщение, которое от его имени уйдёт
    в диалог. Расходятся они только у вторичного входа, который сообщением
    от имени человека и не притворяется (см. :data:`SECONDARY_ACTION`).
    """

    slug: str
    label: str
    text: str


#: Три goal-like чипа с утверждённого макета C01.1, дословно (на макете они
#: помечены WORKING COPY — формулировки владельца, не выдуманные здесь).
#:
#: Ни один не называется услугой. Проверка — в тесте, не на слово.
FIRST_CONTACT_QUICK_ACTIONS: tuple[QuickAction, ...] = (
    QuickAction(
        slug="fresh",
        label="Хочу выглядеть свежее",
        text="Хочу выглядеть свежее",
    ),
    QuickAction(
        slug="swelling",
        label="Беспокоят отёки",
        text="Беспокоят отёки",
    ),
    QuickAction(
        slug="tension",
        label="Хочу снять напряжение",
        text="Хочу снять напряжение",
    ),
)

#: Вторичный вход «Найти услугу →» (решение владельца 24.08: **ОСТАВИТЬ**).
#:
#: Его нет на макете основного потока именно потому, что он — выход **из**
#: C01, а не шаг C01→C05. Малый вес: идёт последним, отдельной строкой, и
#: единственный, чья подпись не притворяется репликой человека.
#:
#: Ведёт в каталог через ту же подстановку, что и чипы: фраза «Какие услуги
#: у вас есть» — та, на которую консьерж зовёт ``show_services`` (DRF-1304),
#: и она же работает набранной руками. Отдельного сценария у кнопки нет.
#:
#: Куда она приходит на самом деле, честно: без фильтра ``show_services``
#: каталог целиком не перечисляет (``has_service_criteria``) и отвечает
#: сужающим вопросом «услуги конкретного салона или что-то по виду —
#: например "лицо" или "массаж"?». Это **не** дефект и не тупик: список
#: услуг на первом экране макет запрещает прямо (блок НЕ ДЕЛАЕМ), а вопрос
#: — настоящий следующий шаг, после которого каталог открывается карточками
#: с чипами (салон -> услуги -> мастер -> запись, всё тапами).
#:
#: ``label`` и ``text`` здесь расходятся — единственный случай на экране.
#: Причина: подпись назвал владелец, а сообщением от имени человека уходит
#: то, что человек мог бы сказать сам. Обе формулировки про услуги, так что
#: реплика в чате не противоречит нажатой кнопке.
SECONDARY_ACTION = QuickAction(
    slug="find_service",
    label="Найти услугу →",
    text="Какие услуги у вас есть",
)


# ---------------------------------------------------------------------------
# Callback payloads
# ---------------------------------------------------------------------------

QUICK_ACTION_CALLBACK_PREFIX = "cb:qa:"

#: Payload — префикс плюс слаг из латиницы, и ничего больше.
#:
#: Проверка формы, а не префикса: на MAX payload кнопки и набранный текст
#: приходят одним полем, поэтому «cb:qa:» в начале строки **не доказывает**,
#: что была кнопка — это может быть набрано руками. Без проверки формы
#: произвольный текст «cb:qa:мой телефон +7…» считался бы (кривым) колбэком
#: и попал бы в лог, против правила #842 «только длины, никогда содержимое».
#: Тот же приём, что у ``apps.skills.menu.matching._MENU_CALLBACK_RE``.
_QUICK_ACTION_RE = re.compile(r"^cb:qa:[a-z_]+$")

#: «Повторить» на экране «AI недоступна» (макет C01, ДОПОЛНИТЕЛЬНЫЕ СОСТОЯНИЯ).
#:
#: Повтор — это не «спроси модель ещё раз», а «отправь то же самое ещё раз»:
#: тап переводится в **последнюю реплику самого человека** и идёт по
#: лестнице с самого верха. Тот же принцип, что у чипов, и по той же
#: причине — сценария у кнопки быть не должно.
RETRY_CALLBACK = "cb:retry:last"

_ALL_ACTIONS: tuple[QuickAction, ...] = (*FIRST_CONTACT_QUICK_ACTIONS, SECONDARY_ACTION)
_BY_SLUG: dict[str, QuickAction] = {a.slug: a for a in _ALL_ACTIONS}


def quick_action_callback(action: QuickAction) -> str:
    """Payload кнопки для чипа."""
    return f"{QUICK_ACTION_CALLBACK_PREFIX}{action.slug}"


def is_quick_action_callback(text: str) -> bool:
    """True когда ``text`` имеет форму payload'а чипа."""
    return bool(_QUICK_ACTION_RE.match(text))


def resolve_quick_action(text: str) -> QuickAction | None:
    """Чип по payload'у, или None — включая payload снятой кнопки.

    None у знакомой формы с неизвестным слагом — не ошибка, а старая
    клавиатура в истории чата: чип переименовали или убрали. Вызывающий
    решает, что с этим делать (см. :func:`resolve_tap_text`).
    """
    if not is_quick_action_callback(text):
        return None
    return _BY_SLUG.get(text[len(QUICK_ACTION_CALLBACK_PREFIX) :])


# ---------------------------------------------------------------------------
# Экран C01: текст + клавиатура
# ---------------------------------------------------------------------------

#: Строка над чипами с макета C01.1, дословно.
QUICK_ACTIONS_HINT = "Можно написать своими словами или выбрать пример:"

#: Сколько кнопок разрешено на первом экране (BOT-001 AC-4.2 / DRF-1200).
#:
#: Пришпилено здесь и проверяется тестом: три чипа плюс вторичный вход — это
#: четыре, и пятая кнопка не должна появиться незаметно.
MAX_FIRST_CONTACT_BUTTONS = 5


def first_contact_buttons(
    actions: tuple[QuickAction, ...] = FIRST_CONTACT_QUICK_ACTIONS,
    *,
    with_secondary: bool = True,
) -> list[dict[str, str]]:
    """Клавиатура первого экрана: чипы, затем вторичный вход.

    Порядок несущий. Вторичный вход идёт **последним** и один в строке —
    решение владельца «малый вес, не конкурирует со свободным текстом».
    """
    buttons = [{"label": a.label, "callback": quick_action_callback(a)} for a in actions]
    if with_secondary:
        buttons.append(
            {"label": SECONDARY_ACTION.label, "callback": quick_action_callback(SECONDARY_ACTION)}
        )
    return buttons


def first_contact_action_data(
    actions: tuple[QuickAction, ...] = FIRST_CONTACT_QUICK_ACTIONS,
    *,
    with_secondary: bool = True,
) -> dict[str, Any]:
    """``action_data`` первого экрана в плоской форме.

    Плоская форма (``buttons`` + ``button_columns``), а не канонический
    конверт: этот экран рисует ``_build_attachments`` ветка (2), ровно как
    у остального, что приходит из ``WelcomeSkill`` на этом пути.
    """
    return {
        "buttons": first_contact_buttons(actions, with_secondary=with_secondary),
        "button_columns": 1,
    }


def render_first_contact(
    body: str,
    actions: tuple[QuickAction, ...] = FIRST_CONTACT_QUICK_ACTIONS,
    *,
    with_secondary: bool = True,
) -> tuple[str, dict[str, Any] | None]:
    """Текст и клавиатура экрана C01 — включая состояние **No Quick Actions**.

    Макет, ДОПОЛНИТЕЛЬНЫЕ СОСТОЯНИЯ: «Показываем, если нет релевантных
    примеров в контексте» — то же приветствие, **без** строки-подсказки и
    **без** чипов, композер на месте. Здесь это не отдельная ветка, а
    пустой ``actions``: строка «Можно написать своими словами» существует
    только чтобы объяснить чипы, и без них она врёт.

    Вторичный вход переживает пустой набор — он выход из экрана, а не
    пример запроса, и когда примеров нет, выход нужнее.
    """
    if not actions:
        return body, (
            first_contact_action_data((), with_secondary=with_secondary) if with_secondary else None
        )
    return (
        f"{body}\n\n{QUICK_ACTIONS_HINT}",
        first_contact_action_data(actions, with_secondary=with_secondary),
    )


# ---------------------------------------------------------------------------
# «AI недоступна» (макет C01, ДОПОЛНИТЕЛЬНЫЕ СОСТОЯНИЯ)
# ---------------------------------------------------------------------------

#: Дословно с макета. Отличается от
#: :data:`apps.orchestrator.llm.templates.OUTAGE_RU` («короткий технический
#: сбой — отвечу через минуту»), которое обещает ответ, которого не будет:
#: ход уже потерян, и никто к нему не вернётся, пока человек не напишет сам.
#: Поэтому текст говорит правду, а кнопка делает то, что текст обещает.
AI_UNAVAILABLE_TEXT = (
    "Сейчас у меня временные трудности с подключением 😔\nПопробуйте написать чуть позже."
)

RETRY_LABEL = "Повторить"

#: Ответ на тап, который нечем подставить: «Повторить» без истории (новый
#: диалог, очищенная память) или чип, которого больше нет (старая клавиатура
#: в истории чата). Общий у обоих потому, что положение одно: кнопка была
#: настоящая, а фразы за ней уже нет, и угадывать её — значит вложить
#: человеку в рот слова, которых он не говорил.
STALE_TAP_TEXT = (
    "Не нашла, что повторить. Напишите, пожалуйста, своими словами — или выберите пример ниже."
)


def ai_unavailable_action_data() -> dict[str, Any]:
    """Клавиатура экрана «AI недоступна»: одна кнопка «Повторить»."""
    return {"buttons": [{"label": RETRY_LABEL, "callback": RETRY_CALLBACK}], "button_columns": 1}


# ---------------------------------------------------------------------------
# Главное меню на глобальном пути (DRF-1051)
# ---------------------------------------------------------------------------


#: Перевод ``cb:menu:*`` в каноническую фразу — для ГЛОБАЛЬНОГО пути.
#:
#: Четыре записи взяты из ``apps.skills.menu.matching.MENU_CALLBACK_TEXT``
#: импортом, а не копией: одно определение «во что превращается тап» на оба
#: пути. Пятая — ``cb:menu:help`` — там отсутствует потому, что на
#: арендаторском пути на неё отвечает ``HelpSkill`` локально; глобальный
#: путь навыков не диспетчеризует, поэтому у неё здесь своя фраза.
#:
#: Куда попадает каждая после подстановки (проверено тестом, не на слово):
#:
#:   «Покажи мои записи» -> ``is_personal_booking_lookup`` -> реальные записи
#:   «Хочу записаться»   -> консьерж (услуга не названа) -> уточнение
#:   «Перенести запись»  -> консьерж
#:   «Отменить запись»   -> консьерж
#:   «Что ты умеешь?»    -> консьерж
def _global_menu_text() -> dict[str, str]:
    from apps.skills.menu.matching import CALLBACK_MENU_HELP, MENU_CALLBACK_TEXT

    return {**MENU_CALLBACK_TEXT, CALLBACK_MENU_HELP: "Что ты умеешь?"}


#: Фраза для тапа по кнопке меню, которой больше нет.
#:
#: Слаг снятой кнопки нельзя отдать модели сырым payload'ом (это и есть
#: DRF-1051), но и угадывать, чем она была, нечем. «Что ты умеешь?» —
#: единственный ответ, который верен для любой снятой кнопки.
_RETIRED_MENU_TEXT = "Что ты умеешь?"


# ---------------------------------------------------------------------------
# Вход: тап -> фраза
# ---------------------------------------------------------------------------


def resolve_tap_text(text: str, *, last_user_text: str | None = None) -> str | None:
    """Фраза, которой этот тап является, или None если это не тап.

    None означает «обычное сообщение» — вызывающий не трогает ``event.text``
    и всё идёт как раньше. Это важнее, чем кажется: функция стоит **перед**
    всей лестницей, и любая её ошибка в сторону «это тап» подменила бы
    человеку его собственные слова.

    Поэтому здесь разбираются ровно три формы, каждая — точная:

    * ``cb:qa:{slug}``  — чип C01 или вторичный вход;
    * ``cb:menu:{slug}``— главное меню (DRF-1051);
    * ``cb:retry:last`` — «Повторить» с экрана «AI недоступна».

    Ни один ``cb:`` другого семейства (``cb:discover:``, ``cb:catalog:``,
    ``cb:book:``, ``cb:welcome:``, ``cb:visit:``, ``cb:anketa:``…) сюда не
    попадает: у них свои ветки ниже по лестнице, они несут id, а не фразу,
    и подставлять вместо них текст было бы ровно тем «отдельным сценарием»,
    которого макет требует избегать — только наоборот.

    ``cb:anketa:`` при этом в ИСТОРИЮ сырым payload'ом всё же не уходит —
    но чинится это не здесь (DRF-990). Анкета маршрутизируется ПО payload'у
    (``NutritionAnketaSkill.matches``), поэтому подменить ``event.text``
    нельзя: сломался бы сам опрос. Тап переводится в фразу на месте записи
    в историю — :func:`apps.orchestrator.nutrition_global.resolve_anketa_tap`.

    ``last_user_text`` — что подставить на «Повторить». Пусто (истории нет)
    даёт None, а :func:`is_stale_tap` отличает этот случай от «не тап».
    """
    stripped = (text or "").strip()

    action = resolve_quick_action(stripped)
    if action is not None:
        logger.info("channels.max.global.quick_action_tapped slug=%s", action.slug)
        return action.text
    if is_quick_action_callback(stripped):
        # Знакомая форма, неизвестный слаг — старая клавиатура в истории
        # чата: чип переименовали или сняли. Подставить нечего.
        logger.info("channels.max.global.quick_action_retired")
        return None

    from apps.skills.menu.matching import is_menu_callback

    if is_menu_callback(stripped):
        resolved = _global_menu_text().get(stripped, _RETIRED_MENU_TEXT)
        logger.info(
            "channels.max.global.menu_tapped slug=%s",
            stripped[len("cb:menu:") :],
        )
        return resolved

    if stripped == RETRY_CALLBACK:
        resolved_retry = (last_user_text or "").strip()
        logger.info("channels.max.global.retry_tapped resolved=%s", bool(resolved_retry))
        return resolved_retry or None

    return None


def is_stale_tap(text: str) -> bool:
    """True для тапа, который был настоящей кнопкой, но подставить нечего.

    Две формы: чип со снятым слагом и «Повторить» без истории. Отличать их
    от обычного текста обязательно — иначе сырой ``cb:…`` payload уедет в
    модель, а это ровно тот дефект, который здесь и чинится (DRF-1051).

    Вызывается только после того, как :func:`resolve_tap_text` вернула None,
    поэтому «Повторить» с историей сюда уже не доходит.
    """
    stripped = (text or "").strip()
    return is_quick_action_callback(stripped) or stripped == RETRY_CALLBACK
