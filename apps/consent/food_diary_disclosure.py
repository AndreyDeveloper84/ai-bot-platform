#: Версия раскрытия — ПСЕВДОНИМ константы половины 1, не своё значение (см.
#: докстринг модуля). Схема — ``<предмет>-v<N>``, как у соседей
#: (``personal-calculation-v1``, ``health-data-v1``, ``marketing-v1``).
FOOD_DIARY_DISCLOSURE_VERSION: Final[str] = FOOD_DIARY_CONSENT_DOCUMENT_VERSION

#: Заголовок экрана согласия.
DISCLOSURE_HEADLINE: Final[str] = "Дневник питания: что я делаю с данными"

#: Шесть обязательных утверждений (список владельца), по одному на абзац.
#: Порядок не косметический: сначала ЧТО обрабатываем, потом ЗАЧЕМ фото,
#: потом СКОЛЬКО оно живёт, потом ЧТО хранится отдельно, и лишь затем —
