def disclosure_text() -> str:
    """Текст раскрытия одной строкой — ровно то, что показывают человеку.

    Единственный источник: и экран, и бот, и тест сверки поверхностей
    берут текст отсюда. Скопированный текст расходится с оригиналом молча —
    поэтому копии нет ни одной.
    """
