"""Каноническое раскрытие для дневника питания — Z9 (решение владельца).

## Что это и чем оно НЕ является

Z9 — не имя сущности в коде, а **метка разрыва**: у scope
``food_diary_processing`` / ``NUTRITION_DIARY`` не было canonical
user-facing disclosure. Этот модуль его заводит и версионирует.

**WORKING PRODUCT COPY.** До прохождения Privacy/Legal review этот текст
**не является окончательным legal disclosure**, и обязательное согласие
живым людям на нём не включается: поверхность живёт за флагом
``FOOD_DIARY_CANONICAL_CONSENT``, выключенным по умолчанию. Снятие
ограничения — не действие исполнителя.

## Почему версия НЕ объявляется здесь

Версия это снимок того, **на что** согласились, а не украшение. Меняется
ВМЕСТЕ с текстом: при следующей редакции константа поднимается, старые
согласия перестают её предъявлять, и человека спрашивают заново.

Но объявлена она ОДИН раз — в ``apps/consent/nutrition.py`` (половина 1
DRF-1963): под ней реестр принимает выдачу и под ней отвечает ручка
``me/food-scanner-consent/``. Второе определение той же версии рядом с
текстом разошлось бы с первым молча — и человек подписался бы под текстом
одной версии, а реестр записал бы другую. Поэтому здесь только имя-псевдоним.

Сегодня это ``food-diary-v0``. Владелец назвал рабочее имя ``food-diary-v1``
для канонического раскрытия; от ответа зависит, будет ли re-consent у уже
согласившихся. Развилка открыта и решается не исполнителем — в одну
сторону здесь не трогается.

## Про пункт про удаление — почему он сформулирован именно так

Владелец назвал шесть вещей, которые текст обязан сказать честно. Пятая и
шестая — про отзыв. Замер показал границу, которую общее слово «удаление»
скрывает:

* **запись о еде** удаляется — есть действующий процесс: отзыв согласия на
  хранение запускает ``revoke_data_storage`` → ``delete_personal_data``
  (C5.2), а отдельную запись убирает ``delete_meal``;
* **исходная фотография** приложением **не удаляется никак**: на стороне
  бота она не хранится вовсе (байты живут на объекте разговора в памяти и
  уходят в распознавание), а срок её жизни держит **политика хранилища**.

Поэтому отзыв сформулирован как **граница будущей обработки**, а не как
команда немедленно стереть: после него ни данные дневника, ни фотография
в новую обработку не идут. Запись дневника и посчитанное по ней уходят по
**установленному порядку удаления**, а срок снимка держит **хранилище**, и
мы его не ускоряем.

Заявлять application-side immediate purge, пока его в коде нет, запрещено
прямо (решение владельца по пункту 6). Это ровно тот дефект, ради
искоренения которого раскрытие и пишется: текст утверждает действие,
которого код не совершает.

Срок «до 30 дней» — **со слов владельца** (политика бакета), не результат
измерения в этом репозитории. Названо так намеренно: измерить отсюда
нельзя, а выдать чужое слово за свой замер — та же неправда этажом ниже.
"""

