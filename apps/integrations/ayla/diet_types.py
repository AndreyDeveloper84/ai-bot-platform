"""Типы питания — словарь каталога, один на весь бот (DRF-2392).

Значения принадлежат каталогу: ``users.UserPersonalContext.DietType``
(состав назвал владелец 23.09.2026; решение 24.09 — словарь ОДИН на два
репозитория). Импортировать их нельзя — другой репозиторий, — поэтому здесь
объявлен **контракт провода**, и узлы держат равенство обеих сторон.

# Почему это отдельный модуль, а не константа в анкете

Их стало два. Анкета питания объявила свой набор (``nutrition_anketa.fsm``),
а разбор ответов консьержа — свой (``orchestrator.memory_ask``), и второй
разошёлся с первым молча: в нём не было ``omnivore``. Значит «ем всё, без
ограничений», сказанное консьержу, ложилось как ``other`` — а ``other`` в
анкете означает «и я напишу словами», которых никто не спрашивал.

Разойтись двум словарям одного смысла ничто не мешало, кроме внимания. Теперь
их один, и он лежит там, где ему место: рядом с клиентом каталога, чьему полю
он принадлежит, — не внутри одного из потребителей.
"""
from __future__ import annotations

#: Значения ``users.UserPersonalContext.DietType`` в порядке каталога.
#:
#: «Без ограничений» зовётся ``omnivore``: код каталога, где в нём лежат
#: данные живых людей. Пустая строка в поле каталога — «не знаем», это НЕ
#: значение словаря.
CATALOG_DIET_TYPES: tuple[str, ...] = (
    "omnivore",
    "vegetarian",
    "vegan",
    "keto",
    "halal",
    "kosher",
    "other",
)

#: «Другое»: единственное значение, за которым в анкете следуют слова.
DIET_OTHER = "other"

#: «Без ограничений» — ответ, а не отсутствие ответа.
DIET_OMNIVORE = "omnivore"
