"""Ключи Ayla → ключи зеркала для решения резолвера. T6 (DRF-1567).

Зачем это существует
--------------------
Резолвер рекомендует **мастеров** (решение владельца `OPEN_DECISIONS.md`
§81, «людей, согласен с тобой») и называет их ключом Ayla —
`specialist.id`. Клиентская полка живёт в ключах зеркала и ключа Ayla
не знает: поля у неё нет и не будет.

Перевести может только тот, у кого есть оба, — то есть мы.

Почему в `apps/marketplace/`, а не в `apps/catalog/`
---------------------------------------------------
Межсалонное чтение зеркала разрешено контуром **в одном месте** —
`apps/marketplace/` (правило `MKT1`, #1018, ADR-0009). Разрешение
поимённое и не подразумеваемое: `CatalogMaster.all_tenants` где угодно
ещё — красный билд.

Сначала модуль лежал в `apps/catalog/`, потому что там живёт
`CatalogMaster`, — то есть **по месту данных, а не по роду занятия**.
Сторож это и назвал. По делу он и есть discovery: «дай продаваемых
мастеров по множеству ключей», и рекомендация маркетплейсная по
определению.

Отдельным модулем, а не функцией в `discovery.py`, намеренно: тот
модуль — третье место ранжирования, которое эпик как раз упраздняет
(T12). Довесить к нему инфраструктурный перевод ключей значило бы
привязать нужное к тому, что мы снимаем.

Почему это отдельный модуль, а не строки во вьюхе
------------------------------------------------
Перевод — доменное знание («кто такой этот ключ»), а не разбор HTTP.
Во вьюхе он оказался бы там же, где парсинг тела и коды ответов, и
первый же следующий читатель принял бы его за часть транспорта.

Побочно это уменьшает правку в общем файле до вызова: `views.py` в тот же
час правит соседнее окно, и чем меньше там наших строк, тем меньше
шансов, что мы разойдёмся в тексте, не расходясь в предмете.

Что этот модуль НЕ делает
-------------------------
**Никого не отбрасывает.** Кандидат, которому зеркальной строки
не нашлось, едет дальше **как есть**, с ключом Ayla.

Соблазн отфильтровать здесь был, и он неверен: полка уже умеет назвать
это состояние — `UNRENDERABLE_CANDIDATES`, — и делает это правильно,
проверяя, что умеет отрисовать. Отфильтруй мы заранее, у полки список
пришёл бы уже усечённым, и она **не узнала бы о потере**. Два места
считали бы одно и то же и разошлись бы. Классификатор остаётся один,
и он там, где знают про отрисовку.

Отсюда же форма: мы возвращаем **числа**, а не решение. Наружу человеку
идёт имя состояния от полки, внутрь дежурному — счётчики отсюда.
"""

from __future__ import annotations

import copy
from dataclasses import dataclass
from typing import Any

#: Вид кандидата, который эта поверхность умеет переводить. Резолвер
#: сегодня производит только его (контракт §5, K1 — вид объявлен явно).
#: Значение сверяется, а не подразумевается: придёт `SERVICE` — мы
#: честно не переведём его и не сделаем вид, что перевели.
PROVIDER = "PROVIDER"


@dataclass(frozen=True)
class KeyTranslation:
    """Сколько перевели и почему не перевели остальных.

    Два случая непереведённых считаются **раздельно**, и это не
    педантизм.

    ``no_mirror_row`` — зеркало не знает такого человека: скорее всего
    отстало.

    ``not_for_sale`` — строка есть, но продавать её нельзя. Ненулевое
    значение означает, что пул Ayla и зеркало **разошлись в том, кто
    продаётся**: Ayla рекомендует того, кого мы продать не можем.

    Сложи мы их в одно «не перевелось», две разные болезни с разным
    лечением получили бы одно число, и лечить пошли бы наугад.

    Чинить расхождение здесь не надо и нельзя: честное лечение — не
    рекомендовать непродаваемых, а это условие принадлежит Ayla
    (T10 / DRF-1571). Наше дело — сделать расхождение **видимым
    и измеримым**.
    """

    translated: int = 0
    no_mirror_row: int = 0
    not_for_sale: int = 0

    @property
    def untranslated(self) -> int:
        return self.no_mirror_row + self.not_for_sale

    def as_log_fields(self) -> str:
        return (
            f"translated={self.translated} no_mirror_row={self.no_mirror_row} "
            f"not_for_sale={self.not_for_sale}"
        )


def translate_provider_keys(payload: Any) -> tuple[Any, KeyTranslation]:
    """Заменить ключи Ayla ключами зеркала везде, где встретится кандидат.

    Обход рекурсивный и **не знает формы ответа** — намеренно. Ссылка
    на кандидата объявлена контрактом как `{kind, id}` (§5, K1) и живёт
    в разных обёртках: в решении она внутри `ordered[]`, у поверхности
    домашнего экрана — внутри полки, а полок несколько. Знай этот модуль
    все обёртки поимённо, он ломался бы при каждой смене формы — а формы
    за последние сутки менялись дважды.

    Вход не мутируется: возвращается копия. Вызывающий, который решит
    показать оригинал в логе рядом с переводом, не должен обнаружить,
    что оригинал уже переведён.
    """
    out = copy.deepcopy(payload)
    refs = list(_iter_candidate_refs(out))

    ayla_ids = [ref["id"] for ref in refs if ref.get("kind") == PROVIDER]
    if not ayla_ids:
        return out, KeyTranslation()

    sellable, known = _mirror_rows(ayla_ids)

    translated = no_row = not_sold = 0
    for ref in refs:
        if ref.get("kind") != PROVIDER:
            continue
        ayla_id = ref["id"]
        mirror_id = sellable.get(ayla_id)
        if mirror_id is not None:
            ref["id"] = mirror_id
            translated += 1
        elif ayla_id in known:
            # Строку мы знаем — продавать не можем. Отрисовать бы смогли,
            # но указывать человеку на архивированного мастера нельзя.
            not_sold += 1
        else:
            no_row += 1

    return out, KeyTranslation(
        translated=translated,
        no_mirror_row=no_row,
        not_for_sale=not_sold,
    )


def _mirror_rows(ayla_ids: list[str]) -> tuple[dict[str, str], set[str]]:
    """Продаваемые строки и все известные — двумя множествами.

    Отбор продаваемых идёт **существующим предикатом** `AVAILABLE`
    (`apps/catalog/master_state.py`), а не своим условием. Своё условие
    стало бы вторым определением «продаётся» и разошлось бы с витриной
    ровно в тот день, когда гейт ужесточат: DRF-1521 уже добавляет туда
    `profile_incomplete`.

    Второе множество — «зеркало вообще знает такой ключ» — нужно, чтобы
    отличить отставшее зеркало от расхождения в том, кто продаётся.

    Почему `all_tenants`, а не `objects`
    ------------------------------------
    `CatalogMaster.objects` — тенантный менеджер, и **без контекста он
    молча отдаёт пустоту** (`queryset_without_context`, режим audit).
    Здесь это было бы не неудобством, а систематическим дефектом:

    полка «Ayla подобрала» по устройству рекомендует мастеров из
    **чужих** салонов — её scope прямо исключает салоны из истории
    человека. Тенантный запрос не перевёл бы ровно их, всегда, и полка
    выглядела бы сломанной именно там, ради чего заведена. Полка «твои
    салоны» при этом работала бы — то есть дефект был бы ещё и
    выборочным, а значит незаметным.

    Виден он тоже не был бы: менеджер пишет строчку в аудит, а человеку
    полка сказала бы `UNRENDERABLE_CANDIDATES` — «нам прислали то, чего
    мы не умеем». Снова имя, обвиняющее не ту сторону.

    Доступ через салоны здесь законен по предмету: рекомендация
    маркетплейсная по определению (scope `MARKETPLACE`), и мы переводим
    ключи тех, кого выбрала Ayla, а не ищем кого-то своего. Ровно для
    такого случая менеджер и держит `all_tenants` — «legitimate
    cross-tenant access». Заявляем это явно, а не обходим молча.
    """
    from apps.catalog.master_state import AVAILABLE
    from apps.catalog.models import CatalogMaster

    rows = CatalogMaster.all_tenants.filter(ayla_user_id__in=ayla_ids)
    known = {str(row.ayla_user_id) for row in rows.only("ayla_user_id")}
    sellable = {
        str(ayla_id): str(mirror_id)
        for mirror_id, ayla_id in rows.filter(AVAILABLE).values_list("id", "ayla_user_id")
    }
    return sellable, known


def _iter_candidate_refs(node: Any):
    """Все объекты `{kind, id}`, лежащие под ключом `candidate`.

    Ищем именно по имени ключа, а не по форме: словарь с полями `kind`
    и `id` может оказаться чем угодно ещё, а `candidate` — это имя,
    которое контракт закрепил за ссылкой на кандидата.
    """
    if isinstance(node, dict):
        ref = node.get("candidate")
        if isinstance(ref, dict) and isinstance(ref.get("id"), str):
            yield ref
        for value in node.values():
            yield from _iter_candidate_refs(value)
    elif isinstance(node, list):
        for value in node:
            yield from _iter_candidate_refs(value)
