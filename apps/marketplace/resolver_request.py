"""Сборка `RecommendationRequest` (§4.1) для полки мини-приложения.

Полка шлёт `POST /recommendations` **без тела** — весь запрос границы
собирается здесь, из того, что известно серверу. Это не упрощение, а
требование §4.1: `subject_ref` в теле нет намеренно, «кого спрашивают»
определяет аутентификация. Позволь мы клиенту прислать часть запроса —
он смог бы получить решение за другого человека, и граница, отнявшая
политику, раздала бы личный контекст.

# Почему `safety_state = NOT_APPLICABLE` — это не дыра

Поле обязательно и умолчания у него нет (§4.1). Соблазн написать
``payload.get("safety") or NOT_APPLICABLE`` контракт запрещает прямо:
отсутствие оценки НЕ превращается в «неприменимо» ни при каких условиях.

Здесь другое. `NOT_APPLICABLE` определяется **типом поверхности до
того, как решение выполнено**, и владелец решил (§72, подтверждено §89),
что витрина мини-приложения именно такова: гейт здоровья стоит на пути
ЗАПИСИ, а не на полке. Пустая полка ничего не предотвращала — те же
мастера видны и бронируемы в обычном каталоге одним тапом, так что
закрытым оказывалось объяснение, а не действие.

И заявление это не принимается на слово: резолвер опровергает его
СОДЕРЖАНИЕМ (`_stages._is_safety_sensitive`) — если среди кандидатов
есть требующий проверки здоровья или выдача персонализирована прошлым
опытом, граница переходит на fail-closed как при `UNKNOWN`. То есть мы
заявляем свойство поверхности, а решает всё равно тот, у кого факты.

# Чего здесь нет и почему это названо, а не забыто

План границы (§1.4) делит полки так: полка «твои салоны» — это
`resolve` со `scope.tenant_refs` из истории, полка «Ayla подобрала» —
`resolve` с ИСКЛЮЧЕНИЕМ тех же тенантов.

Источника «тенанты из истории» в этом репозитории **не существует**:
`tenant_history` упоминается ровно в двух докстрингах, описывающих тело,
которого полка никогда не слала. Строить его здесь значило бы завести
межсалонное чтение брони мимо MKT1 и решить за владельца, что именно
считается «историей».

Поэтому запрос уходит без исключений, и это **известное сужение**, а не
недосмотр: полка может показать салон, в котором человек уже был.
Предмет отдельный (DRF-1626 → выделен), и до его решения здесь стоит
пустой кортеж, а не «пока так».
"""

from __future__ import annotations

import uuid
from typing import Any, Final

#: Поверхность полки. По контракту (§9.5) читать `surface` внутри стадий
#: S0–S6 запрещено: один запрос обязан давать одно решение независимо от
#: канала. Поле существует «для аудита и выбора `k` — и больше ни для
#: чего», поэтому неверное значение здесь ничего не сломает в выдаче, но
#: соврёт в журнале, а журнал — единственное, ради чего поле есть.
SURFACE_MINIAPP_HOME: Final = "MINIAPP_HOME"

#: Витрина мини-приложения не выполняет safety-sensitive решение —
#: решение владельца §72, подтверждено §89. Разбор в докстринге модуля.
SAFETY_NOT_APPLICABLE: Final = "NOT_APPLICABLE"

#: Полка межсалонная: она и есть «Ayla подобрала», то есть подбор за
#: пределами салонов человека (§81, MKT1).
SCOPE_MARKETPLACE: Final = "MARKETPLACE"

#: Откуда взялась нужда. Человек ничего не выбирал — он открыл экран, и
#: подбор построен на его цели. `USER_EXPLICIT` здесь был бы неправдой:
#: явного запроса не было.
NEED_ORIGIN_GOAL: Final = "GOAL"

#: Сколько кандидатов просить. Срез под карточки делает поверхность и
#: делает его ПОСЛЕ ротации (§12.2), поэтому здесь берётся запас, а не
#: число карточек.
DEFAULT_K: Final = 10


def build_shelf_request(*, goal_key: str | None, request_id: str | None = None) -> dict[str, Any]:
    """Тело `POST /internal/recommendation/resolve/` для полки подбора.

    ``request_id`` принимается снаружи только затем, чтобы вызывающий мог
    связать журнал с ответом; по умолчанию генерируется. Он же — ключ
    воспроизводимости: один `request_id` при неизменных версиях политик
    обязан давать то же решение (§9.4).
    """

    return {
        "request_id": request_id or str(uuid.uuid4()),
        "surface": SURFACE_MINIAPP_HOME,
        "scope": {
            "mode": SCOPE_MARKETPLACE,
            # Пусто НАМЕРЕННО — см. докстринг модуля. Не «пока так»:
            # источника истории тенантов в этом репозитории нет, и
            # заводить его здесь значило бы решить за владельца, что
            # считается историей.
            "tenant_refs": [],
            "exclude_tenant_refs": [],
        },
        "need": {
            "origin": NEED_ORIGIN_GOAL,
            "capability_refs": [],
            "canonical_service_refs": [],
            "goal_key": goal_key,
        },
        # Обязательное поле без умолчания. Значение — свойство
        # поверхности, а не результат неудавшейся оценки.
        "safety_state": SAFETY_NOT_APPLICABLE,
        "k": DEFAULT_K,
    }


__all__ = [
    "DEFAULT_K",
    "NEED_ORIGIN_GOAL",
    "SAFETY_NOT_APPLICABLE",
    "SCOPE_MARKETPLACE",
    "SURFACE_MINIAPP_HOME",
    "build_shelf_request",
]
