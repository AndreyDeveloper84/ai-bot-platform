/**
 * ESLint для Mini App — три правила, все ошибкой (DRF-2388, DRF-2391).
 *
 * До 24.09 конфигурации ESLint здесь не было **вовсе**, и CI линтер не гонял.
 * Поэтому нарушение порядка хуков дожило до пилота (DRF-2374: `useMemo` после
 * условного `return`) — его некому было поймать: `tsc` такие вещи не видит, а
 * vitest замечает только если сломанную ветку кто-то отрисует.
 *
 * ### Что показал замер, когда линтер наконец запустили
 *
 * Правила нашли **46 мест**, а подавлений в коде было **26**: команда подавляла
 * то, что случайно заметила, — двадцать мест не видел никто. Это измеряет не
 * «правило некому проверить», а **«проверка мнилась там, где её не было»**.
 *
 * | правило | находок | было подавлено |
 * |---|---|---|
 * | `rules-of-hooks` | 8 в 3 файлах | 0 |
 * | `exhaustive-deps` | 21 | 15 |
 * | `no-console` | 25 | 11 |
 *
 * ### Почему у `no-console` разрешены `warn` и `error`
 *
 * Из 25 вызовов — 22 `console.warn` и 3 `console.error`, все с тегом модуля и в
 * ветке отказа (`console.warn("[max-sdk] openLink failed, falling back", err)`).
 * **`console.log` — ни одного**, как и `debug`/`info`. То есть правило в
 * стандартном виде запрещало бы ровно ту диагностику, на которой держится
 * разбор отказов, а в таком — ловит единственное, что действительно отладка.
 * Все 11 подавлений `no-console` после этого стали мёртвыми и удалены.
 *
 * ### Почему у `exhaustive-deps` обязательна причина
 *
 * Из 21 находки шестнадцать безвредны по замыслу (одноразовые эффекты,
 * постоянные на монтировании данные), в двух **совет правила сломал бы
 * замысел**, и три — настоящие предметы: DRF-2394 (утечка адреса превью),
 * DRF-2395 (адрес против фильтра), DRF-2396 (память экрана не работает).
 *
 * При таком соотношении правило без подавлений невозможно, а подавление без
 * причины ничем не лучше отсутствия правила: следующий человек видит «что», но
 * не «почему». Поэтому причина требуется **машинно** —
 * `eslint-comments/require-description`, — а не по договорённости: договорённость
 * держится до первого спешащего.
 *
 * ### Почему ошибкой, а не предупреждением
 *
 * Предупреждение, которое всегда горит, учит его не замечать — тот же
 * несуществующий линтер, только с иллюзией контроля. Плюс задание зовёт
 * `--max-warnings 0`, так что предупреждение и ошибка тут различаются только
 * названием.
 *
 * ### Чего этот файл НЕ делает
 *
 * Стилевые правила не включены: они дали бы сотни замечаний на существующем
 * коде, и настоящий сигнал утонул бы в них с первого дня. Правила компилятора
 * React, которые привозит плагин версии 7, — тоже не включены.
 *
 * ### Почему версии прибиты точно
 *
 * `eslint`, плагины и парсер стоят без `^`, в отличие от остальных зависимостей.
 * Это калитка: патч-версия правила не должна менять то, что краснеет, — иначе
 * задание однажды покраснеет или позеленеет без единой правки в коде.
 */
