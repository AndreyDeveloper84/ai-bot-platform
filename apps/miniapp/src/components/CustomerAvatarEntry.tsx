/**
 * Вход в профиль клиента — аватарка в шапке (решение владельца §77 п.60).
 *
 * «Чат живёт в нижней панели, вход в профиль по клику по аватарке». Как
 * только «Профиль» уйдёт из панели, **это единственная дверь в профиль**, а
 * за ней — цель, свои данные и управление памятью («что Ayla помнит»,
 * «забыть всё»), то есть поверхность 152-ФЗ. Поэтому дверь ставится ДО того,
 * как уйдёт пункт панели, и ставится на все экраны панели сразу: вход,
 * который есть не везде, человек читает как «иногда можно» и не знает, когда.
 *
 * Почему компонент, а не разметка на экране: кружок с инициалами уже жил на
 * Главной (`wellness-dash__avatar`, DRF-2331) и на профиле
 * (`profile-header__avatar`). Третьей копии не завожу — панель ровно эту
 * болезнь уже лечила («четыре набора вкладок в коде и три из них
 * устаревшие», `CustomerTabBar`). Краски и размер берутся у существующего
 * кружка Главной, чтобы один человек оставался одним узнаваемым кружком.
 *
 * Цель нажатия 44×44 (WCAG 2.5.8) — обрамляющей кнопкой, а сам кружок
 * остаётся 36 px. Приём местный: так же сделана стрелка возврата
 * (`.screen__back`, `globals.css`), размером, а не `::after`.
 *
 * Фотографии у клиента нет: `BookingRequest`-поверхности её не несут, а
 * `BotUser.avatar_url` (зеркало из события Ayla) **не отдаёт наружу ни одна
 * ручка `miniapp_api`** — проверено на `8c4aeab7`. Поэтому инициалы, а не
 * заглушка-украшение: кружок нажимается и читается как «это я» и без фото.
 * Появится поле на проводе — здесь добавится `<img>`, и больше нигде.
 */
import { useEffect, useState } from "react";
import { useNavigate } from "react-router-dom";

import { avatarInitials, fetchMe } from "../lib/customer-profile";

export const PROFILE_ROUTE = "/customer/profile";

/**
 * Имя — один раз на сессию, общее для всех экранов панели.
 *
 * Без этого кружок был бы «АП» на Главной (у неё имя приходит с
 * `wellness/today`) и «·» на Дневнике, Плане, Записях и заглушке пилота — у
 * них имени нет вообще, а два экрана из шести не грузят ничего. Один человек
 * с двумя разными кружками — это и есть «заглушка, похожая на украшение»:
 * она прячет единственную дверь. Мемо держит ОДИН запрос на сессию, а не по
 * одному на экран; `fetchMe` при этом не тронут — у него свои читатели.
 */
let namePromise: Promise<string> | null = null;

/**
 * Засев принимает СТРОКУ, а не обещание, и это не мелочь оформления.
 *
 * Прежняя подпись брала `Promise<string>`, поэтому в общий источник можно
 * было положить отклонённое обещание — и приходилось держать в эффекте
 * защитный `.catch`. Проверить его было нечем: обещание, созданное здесь, уже
 * обработано `.catch`'ем ниже, а наблюдаемого поведения у защиты нет —
 * начальное состояние и так даёт «·». Подмена это и показала: снимаешь
 * защиту — ни один узел не краснеет. Непроверяемый код лучше не иметь, чем
 * иметь: со строкой отказ невозможен ПО ПОСТРОЕНИЮ, и защищаться не от чего.
 */
export function primeDisplayName(value: string | null): void {
  namePromise = value === null ? null : Promise.resolve(value);
}

function displayNameOnce(): Promise<string> {
  if (!namePromise) {
    namePromise = fetchMe()
      .then((me) => me.display_name)
      .catch(() => {
        // Отказ НЕ запоминаем. Первая редакция мемоизировала и его — и один
        // отказ (приложение открыли офлайн, у Записей для этого есть свой
        // баннер) прибивал «·» на всех экранах панели до перезапуска, уже
        // после того как сеть вернулась. Дверь при этом оставалась
        // нажимаемой, но портилось ровно то свойство, ради которого она
        // заведена: «читается как это я». И портилось молча — «·»
        // неотличимо от «имени нет». Сбрасываем: следующий монтаж пробует
        // снова, а успех по-прежнему один запрос на сессию.
        namePromise = null;
        return "";
      });
  }
  return namePromise;
}

/**
 * ``displayName`` передаёт тот экран, у которого имя уже есть (Главная —
 * из `wellness/today`, профиль — из `/me`): второй источник одного и того же
 * имени породил бы расхождение в момент загрузки. Остальные не передают
 * ничего и получают общее.
 */
export function CustomerAvatarEntry({ displayName }: { displayName?: string }) {
  const navigate = useNavigate();
  const [resolved, setResolved] = useState(displayName ?? "");

  useEffect(() => {
    if (displayName !== undefined) {
      setResolved(displayName);
      // Экран, у которого имя есть, ОТДАЁТ его в общий источник. Без этого
      // мемо обещало больше, чем делало: первый же переход Главная → Дневник
      // рисовал «·» на целый круг к `/me`, хотя имя было в руках экраном
      // раньше. Обещание жило в докстринге, а не в коде.
      if (displayName) primeDisplayName(displayName);
      return;
    }
    let alive = true;
    displayNameOnce().then((name) => {
      if (alive) setResolved(name);
    });
    return () => {
      alive = false;
    };
  }, [displayName]);

  return (
    <button
      type="button"
      className="customer-avatar-entry"
      // Подпись говорит, КУДА ведёт, а не что нарисовано: инициалы читателю
      // экрана ничего не сообщают. И она НЕ «Профиль»: так зовётся вкладка
      // панели, и на экранах, где есть и то и другое, получалось две кнопки
      // с одним именем — `getByRole` на неоднозначности падал, а читатель
      // экрана слышал «Профиль, кнопка» дважды и не знал, чем они разные.
      // Нашёл это существующий узел заглушки пилота, а не мой.
      aria-label="Мой профиль"
      onClick={() => navigate(PROFILE_ROUTE)}
    >
      <span className="customer-avatar-entry__circle" aria-hidden="true">
        {avatarInitials(resolved)}
      </span>
    </button>
  );
}
