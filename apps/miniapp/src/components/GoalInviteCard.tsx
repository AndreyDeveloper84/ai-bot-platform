/**
 * Приглашение в анкету цели на домашнем экране клиента.
 *
 * Решение владельца 30.08: человек, открывший мини-апп, обязан встретить
 * анкету цели. До этого единственный вход в `/customer/goal-select` жил
 * в стартовой сетке БОТА — то есть в переписке, — и тот, кто пришёл
 * ссылкой в приложение, анкету не встречал никогда.
 *
 * # Кто «новый» — решает сервер, не экран
 *
 * `GET /decision-context` уже отвечает на этот вопрос: поле `missing` —
 * «чего не хватает». Приглашение показывается ровно тогда, когда
 * `missing` непуст, и не показывается, когда пуст. Никакой эвристики
 * «нет записей — значит новый»: она разошлась бы с сервером в первый же
 * день (человек без записей, но с целью — не новый; человек с записью,
 * но без цели — цель всё равно не выбрал).
 *
 * Экран не интерпретирует и `kind`: `goal`, `goal_clarification`,
 * `goal_guidance` рисуются одинаково — текстом `prompt` как есть. Тот же
 * инвариант, что и у `GoalSelectScreen`: документ отображается,
 * решения не принимаются.
 *
 * # Что здесь НЕ обещается
 *
 * `GOAL_RESOLUTION_ENABLED` на пилоте выключен — выбранная цель пока ни
 * на что не влияет. Поэтому в карточке нет ни слова про подбор,
 * рекомендации и «подберём под твою цель»: единственный текст — вопрос,
 * который прислал сервер, и подпись кнопки, называющая место назначения
 * («Выбрать цель» — та же формулировка, что у кнопки бота). Вопрос
 * останется правдой и после включения флага; обещание — стало бы ложью
 * до него.
 *
 * # Дорога к записи
 *
 * Карточка стоит ПЕРВОЙ на домашнем экране — над записями и над «Найти
 * услугу». Это решение владельца 31.08, принятое поверх BOT-001 §13
 * («First Contact MUST NOT begin with a standalone questionnaire»,
 * §2.1 держит Mini App entry в области действия) при полном знании
 * возражений; разбор — в теле PR #1342.
 *
 * Что это НЕ отменяет: карточка ничего не требует и ничего не
 * загораживает. Не модалка, не шаг мастера, не шлюз. Список записей,
 * «Найти услугу» и нижняя навигация работают и достижимы без ответа на
 * вопрос — AC-5.2 и non-goal #1/#3 владелец не отменял. Слова «Анкета»
 * в подписи нет (§13.3, первый пункт): кнопка называется «Выбрать
 * цель», как и в боте.
 *
 * Сбой `decision-context` не рисует ничего — домашний экран не имеет
 * права падать из-за необязательного приглашения.
 *
 * # Повторный проход (DRF-1451 / DRF-1225)
 *
 * Карточка показывается ещё и тому, кто УЖЕ с целью, — но только когда
 * сервер прислал намерение `start_anketa`, то есть сам готов начать
 * новый проход. Подпись кнопки тогда серверная («Пройти анкету
 * заново»), потому что это уже другое действие, а не то же самое.
 * До 03.09 такой человек карточки не видел вовсе, и вход в анкету из
 * приложения для него исчезал — при том что владелец распорядился
 * (DRF-1225), что проходить её можно сколько угодно раз.
 *
 * # Почему у кнопки нет своего модификатора
 *
 * Был `goal-invite__cta` — имя без единого правила, то есть DRF-1066 в
 * чистом виде: React его рисует, браузер игнорирует, тесты молчат.
 * Правило ему не дописано, имя удалено — потому что работы у него не
 * было. Вид кнопки целиком несёт `btn-secondary` (globals.css:116 —
 * рамка и текст акцентом, min-height 44px), так что «голым текстом»
 * она не отрисовывалась ни до, ни после.
 *
 * И тише она остаётся намеренно: ниже стоит «Найти услугу» с
 * `records-empty__cta-primary` — залитая акцентом. Порядок отдан цели,
 * громкость оставлена записи; ровно так карточка идёт первой, никого
 * не оттесняя. Отдельный вид для этой кнопки — решение дизайнера, а не
 * способ погасить линт.
 */

import { useEffect, useState } from "react";
import { useNavigate } from "react-router-dom";
import { fetchDecisionContext, type DecisionContext } from "../lib/customer-goals";

export function GoalInviteCard() {
  const navigate = useNavigate();
  const [doc, setDoc] = useState<DecisionContext | null>(null);

  useEffect(() => {
    let cancelled = false;
    fetchDecisionContext()
      .then((d) => {
        if (!cancelled) setDoc(d);
      })
      .catch(() => {
        /* приглашение необязательно — молчим, экран остаётся рабочим */
      });
    return () => {
      cancelled = true;
    };
  }, []);

  if (!doc) return null;

  // DRF-1451 / DRF-1225 — повторный проход. Человек С целью вопросов не
  // получает (`missing` пуст), и до 03.09 карточка для него исчезала, а
  // вместе с ней и единственный вход в анкету из приложения. Владелец
  // же распорядился, что проходить её можно сколько угодно раз.
  //
  // Признак повторного входа тоже серверный: намерение `start_anketa`
  // приходит в документе ровно тогда, когда сервер готов начать новый
  // проход. Экран его не выводит и не угадывает — читает.
  const restart = doc.intents.find((i) => i.id === "start_anketa") ?? null;
  if (doc.missing.length === 0 && !restart) return null;

  return (
    <section className="goal-invite" aria-label="Цель">
      {doc.missing.map((item, index) => (
        <p key={`${item.kind}-${index}`} className="goal-invite__prompt">
          {item.prompt}
        </p>
      ))}
      <div className="goal-invite__actions">
        <button
          type="button"
          className="btn-secondary"
          onClick={() => navigate("/customer/goal-select")}
        >
          {restart ? restart.label : "Выбрать цель"}
        </button>
      </div>
    </section>
  );
}
