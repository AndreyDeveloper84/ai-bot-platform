/**
 * Готовый текст приглашения, который владелец салона копирует и шлёт сам.
 *
 * Рядом со ссылкой-приглашением лежит `ShareableLink` — он отдаёт ОДИН
 * адрес. Этого мало: адрес без сопроводительного текста приходит
 * незнакомому мастеру голым, и владелец сочиняет объяснение заново на
 * каждое приглашение. Тридцать приглашений подряд — тридцать
 * формулировок, и в каждой владелец сам решает, предупреждать ли про
 * одноразовость.
 *
 * ### Формулировка утверждена владельцем, а не выбрана здесь
 *
 * Текст ниже — дословно решение владельца §44.2 от 07.09.2026
 * (`docs/OPEN_DECISIONS.md`). Три вещи в нём приняты как решения и не
 * подлежат правке из соображений вкуса:
 *
 * 1. **«Приглашаем»** — сообщение идёт от лица салона, не от лица
 *    человека, который его пересылает.
 * 2. **«рабочий профиль мастера»** — слово «кабинет» запрещено.
 * 3. **Предупреждение об одноразовости** сохранено. Смягчать форму
 *    можно, удалять — нельзя: приглашение действительно достаётся тому,
 *    кто откроет ссылку первым (`validate_invite_token` пускает только
 *    `PENDING`, а `onboarding_accept` привязывает строку мастера к той
 *    сессии, которая пришла первой).
 *
 * Черновик §30, написанный до этого решения, **отменён**: он говорил
 * «Приглашаю» от первого лица и называл рабочую поверхность мастера
 * «кабинетом».
 *
 * ### Почему текст редактируемый, а не просто копируемый
 *
 * Решение владельца: «скопировать и **при желании изменить** перед
 * отправкой». Отправляет его не система, а человек, у которого с
 * мастером может быть своя история — «Аня, вот та ссылка, о которой
 * говорили». Поэтому поле правится прямо здесь, а кнопка копирует то,
 * что в поле сейчас, а не исходную заготовку: иначе «изменить» означало
 * бы «вставить и переписать в мессенджере», и правка терялась бы на
 * каждой второй попытке.
 *
 * ### Куда попадает сама ссылка
 *
 * Утверждённый текст говорит «Откройте ссылку», но самой ссылки не
 * содержит — подставляется в нём только название салона. Сообщение,
 * которое велит открыть ссылку и ссылки не несёт, не работает, поэтому
 * адрес встаёт отдельной строкой сразу за фразой, которая на него
 * указывает. Ни одно утверждённое предложение при этом не переписано и
 * не переставлено; если владелец захочет адрес в конце — это правка
 * одной строки здесь.
 */

import { useCallback, useEffect, useState } from "react";

import { hapticSelection } from "../lib/max-sdk";

/**
 * Собрать текст приглашения.
 *
 * Экспортируется ради теста: формулировка утверждена владельцем, и
 * тест должен уметь сверить её посимвольно, не поднимая экрана.
 */
export function buildInviteMessage({
  salonName,
  link,
}: {
  readonly salonName: string;
  readonly link: string;
}): string {
  return (
    `Приглашаем вас присоединиться к салону «${salonName}» в Ayla.\n` +
    "Откройте ссылку, чтобы получить доступ к рабочему профилю мастера.\n" +
    "\n" +
    `${link}\n` +
    "\n" +
    "Ссылка одноразовая. Пожалуйста, не пересылайте её: доступ получит " +
    "тот, кто откроет ссылку первым."
  );
}

interface Props {
  /** Название салона — подставляется в первую строку. */
  readonly salonName: string;
  /** Ссылка-приглашение. Меняется — заготовка пересобирается. */
  readonly link: string;
}

export function InviteMessage({ salonName, link }: Props) {
  const [text, setText] = useState<string>(() =>
    buildInviteMessage({ salonName, link }),
  );
  const [state, setState] = useState<"idle" | "copied" | "failed">("idle");

  // Новая ссылка — новая заготовка. «Выдать ещё одно приглашение» на
  // этом же экране не должно подсовывать владельцу чужой адрес, а
  // сохранять его правку от прошлого человека тем более незачем.
  useEffect(() => {
    setText(buildInviteMessage({ salonName, link }));
    setState("idle");
  }, [salonName, link]);

  const onCopy = useCallback(async () => {
    try {
      await navigator.clipboard.writeText(text);
      setState("copied");
      hapticSelection();
    } catch {
      // Молчаливый отказ на кнопке «копировать» — это владелец,
      // уверенный, что текст у него в буфере, и вставляющий пустоту.
      setState("failed");
    }
  }, [text]);

  return (
    <div className="shareable invite-message">
      <p className="shareable__label" id="invite-message-label">
        Текст приглашения
      </p>
      <p className="shareable__hint">
        Готовое сообщение со ссылкой внутри. Скопируйте и отправьте
        мастеру — можно сначала поправить под себя.
      </p>
      <textarea
        className="admin-textarea invite-message__text"
        aria-labelledby="invite-message-label"
        rows={7}
        value={text}
        onChange={(e) => {
          setText(e.target.value);
          setState("idle");
        }}
      />
      <button
        type="button"
        className="btn-secondary shareable__copy"
        onClick={() => void onCopy()}
      >
        {state === "copied" ? "Скопировано" : "Скопировать текст"}
      </button>
      {/* Итог копирования — вслух: смена подписи кнопки скринридеру не
          событие (та же причина, что в `ShareableLink`). */}
      {state === "copied" && (
        <p className="shareable__copied" role="status">
          Текст скопирован.
        </p>
      )}
      {state === "failed" && (
        <p className="shareable__failed" role="alert">
          Не удалось скопировать — выделите текст и скопируйте вручную.
        </p>
      )}
    </div>
  );
}
