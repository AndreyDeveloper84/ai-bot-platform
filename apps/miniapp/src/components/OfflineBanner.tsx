/**
 * Полоса «нет сети» для экранов воронки записи.
 *
 * Баннер один и текст один: не «данные могут быть устаревшими» (это про
 * список записей), а «записаться сейчас не получится» — потому что на
 * этих экранах человек идёт совершать действие, и оно без сети не
 * произойдёт. Сказать это до нажатия честнее, чем показать ошибку после.
 *
 * Баннер сам по себе НЕ достаточен: рядом с ним действия, которые без
 * сети не сработают, должны быть выключены. Иначе получается ровно то,
 * что было на экране записей — честная полоса и живые кнопки под ней.
 */
export function OfflineBanner({ online }: { online: boolean }) {
  if (online) return null;
  return (
    <div className="offline-banner" role="status" aria-live="polite">
      Нет сети — записаться сейчас не получится.
    </div>
  );
}
