/**
 * «Профиль пока не подключён» + дверь к студии (DRF-2378).
 *
 * Решение владельца (§77 п. 27, 24.09): роли «оператор» в системе НЕТ —
 * одним словом названы группа `Ayla Operations`, флаг
 * `User.is_platform_admin` в каталоге (это не право привязки) и пустой по
 * умолчанию `HANDOFF_DUTY_OPERATORS` (он про клиентские передачи). Роли
 * салона — `receptionist / admin / owner / master`. «Обратитесь к
 * оператору» отправляло мастера к адресату, которого нет.
 *
 * Адресат — студия, и он настоящий: `/master/internal-chat`, экран
 * называется «Со студией», переписка идёт в существующий тред.
 *
 * ОДИН блок на шесть экранов, а не шесть копий. Пять из них рисовали это
 * место одинаково (`<p className="callout" role="status">`), и текст
 * расходился бы при первой же правке — а здесь важна каждая половина:
 * первая утверждена дословно, вторая меняется по предмету экрана.
 *
 * ЧЕГО ЭТОТ БЛОК НЕ ГОВОРИТ, И ЭТО ГРАНИЦА ЛИСТА: он не обещает, что
 * студия подключит профиль. Сегодня она этого НЕ МОЖЕТ — привязка станет
 * автоматической отдельным листом (DRF-2379). Право на обещание
 * появляется вместе с автоматикой, не раньше.
 */
import { useNavigate } from "react-router-dom";

/** Куда ведёт дверь: существующий тред со студией, не новая сущность. */
export const STUDIO_CHAT_PATH = "/master/internal-chat";

/** Подпись кнопки — утверждена владельцем дословно. */
export const WRITE_TO_STUDIO_LABEL = "Написать студии";

/** Первая половина текста — утверждена дословно, одна на все экраны. */
export const NOT_CONNECTED_PREFIX = "Профиль пока не подключён";

/**
 * Собрать текст экрана: утверждённая половина + предмет этого экрана.
 *
 * Функция, а не шесть готовых строк: так первая половина физически одна, и
 * «почти такой же» её сделать нельзя.
 */
export function notConnectedText(subject: string): string {
  return `${NOT_CONNECTED_PREFIX} — ${subject}.`;
}

export function StudioCallout({ text }: { text: string }) {
  const navigate = useNavigate();
  return (
    <div className="callout" role="status">
      <p>{text}</p>
      {/* Кнопки «попробовать снова» здесь нет намеренно (решение
          владельца): повтор не лечит отсутствие привязки, а обещает
          лекарство. */}
      <button
        type="button"
        className="btn-secondary"
        onClick={() => navigate(STUDIO_CHAT_PATH)}
      >
        {WRITE_TO_STUDIO_LABEL}
      </button>
    </div>
  );
}
