/**
 * Кто что видит на салонной поверхности (DRF-1522).
 *
 * # Зачем отдельный модуль
 *
 * Салонную поверхность обслуживают три роли — владелец, администратор и
 * ресепшн. До сих пор каскад в `App.tsx` склеивал их в одну проверку
 * `is_owner || is_admin || is_receptionist`, а нижняя панель не получала
 * данных о человеке вовсе и потому не могла ничего скрыть. В итоге
 * ресепшн каждое утро видела пять вкладок, из которых две ей не
 * открывались: «Чаты» отвечали 403 (`require_admin_role` на бэкенде не
 * пускает ресепшн), «Настройки» были заглушкой на всех.
 *
 * Правило вынесено сюда, а не размазано по компонентам, потому что его
 * читают три места сразу: панель вкладок, страж закрытых адресов и
 * посадка. Разъехавшись, они дали бы ровно тот дефект, который чинится:
 * вкладка скрыта, а посадка ведёт в неё.
 *
 * # Границы
 *
 * Права на бэкенде это НЕ ослабляет и не подменяет: 403 на `/admin/threads/`
 * остаётся правильным ответом. Здесь решается только одно — не показывать
 * ресепшн дверь, которая ей не откроется.
 *
 * Пять разделов сохраняются для владельца и администратора (решение
 * владельца 05.09.2026, DRF-1522). Сокращать их состав —
 * не эта задача.
 */

import type { MeResponse } from "./admin-api";

export type AdminTabKey = "day" | "team" | "services" | "chats" | "settings";

/** Полная салонная панель — владелец и администратор. */
export const ADMIN_TABS_FULL: readonly AdminTabKey[] = [
  "day",
  "team",
  "services",
  "chats",
  "settings",
];

/**
 * Панель ресепшн — две вкладки.
 *
 * «День» и «Команда» она действительно открывает: `AdminSalonDayScreen`
 * роль не проверяет вовсе (а с DRF-1552 её пускает и бэкенд —
 * `require_admin_or_reception_read` на `GET /api/v1/admin/day/`),
 * `AdminTeamScreen` рисует ростер и прячет только действия.
 *
 * «Услуги» стояли здесь после DRF-1522 как прайс, который ресепшн
 * называет клиенту. Владелец решение изменил (`docs/OPEN_DECISIONS.md`
 * §35 п.1): **вкладку «Услуги» у ресепшн убрать, пока для неё нет
 * разрешённого сценария.** Экран за ней — матрица «мастер × услуга» с
 * правкой и массовым применением, а не прайс-лист; читающего варианта
 * для приёмной роли не существует, и придумывать его здесь не место.
 *
 * У владельца и администратора «Услуги» остаются — см. `ADMIN_TABS_FULL`.
 */
export const ADMIN_TABS_RECEPTION: readonly AdminTabKey[] = ["day", "team"];

/** Роли, из которых складывается доступ к салонной поверхности. */
export type AdminRoleFlags = Pick<
  MeResponse,
  "is_owner" | "is_admin" | "is_receptionist"
>;

/**
 * Только ресепшн — и никакой управляющей роли сверху.
 *
 * Проверка НЕ сводится к `is_receptionist`: владелец салона, которому
 * бэкенд заодно проставил приёмную роль, остаётся владельцем и обязан
 * видеть все пять вкладок. Поэтому две управляющие роли здесь —
 * отрицающие.
 */
export function isReceptionOnly(me: AdminRoleFlags): boolean {
  return Boolean(me.is_receptionist) && !me.is_admin && !me.is_owner;
}

/** Вкладки, которые видит этот человек. */
export function adminTabsFor(me: AdminRoleFlags): readonly AdminTabKey[] {
  return isReceptionOnly(me) ? ADMIN_TABS_RECEPTION : ADMIN_TABS_FULL;
}

/** Открыт ли раздел этому человеку. Страж закрытых адресов спрашивает это. */
export function isAdminTabAllowed(me: AdminRoleFlags, tab: AdminTabKey): boolean {
  return adminTabsFor(me).includes(tab);
}

/**
 * Куда садится салонная поверхность.
 *
 * Ресепшн — на «День»: это то, что она открывает каждое утро. Раньше
 * catch-all клал всех на `/admin/team`, то есть на ростер мастеров, где
 * почти все действия от неё скрыты. Комментарий в `AdminTabBar` уже два
 * месяца объяснял, почему «День» стоит первым, — посадка ему
 * противоречила.
 */
export function adminLandingPath(me: AdminRoleFlags): string {
  return isReceptionOnly(me) ? "/admin/day" : "/admin/team";
}
