/**
 * DRF-2549 — единственное место, где мини-приложение называет себя серверу.
 *
 * `Authorization: MaxInitData <initData>` — подписанный MAX пакет запуска.
 * Это ЕДИНСТВЕННОЕ доказательство, что запрос пришёл от этого человека:
 * сервер проверяет подпись (`apps/miniapp_api/auth.py`, `extract_init_data`)
 * и по ней решает, чьи данные отдать. Поэтому заголовок собирается здесь и
 * больше нигде — сторож `auth-headers.guard.test.ts` краснеет на копии.
 *
 * ### Два запрета — оба выведены из живых ошибок, не из вкуса
 *
 * 1. **Не в `<img src>` и не в любую ссылку, которую грузит браузер сам.**
 *    Браузер такие запросы шлёт без заголовков, и сервер ответит отказом —
 *    или, хуже, кто-то «починит» это, открыв ручку без подписи. Байты,
 *    которым нужна личность, берутся `fetch` с этим заголовком и отдаются
 *    картинке `blob:`-адресом. Выведено: DRF-2455 (прокси снимка еды, его
 *    узел k4 `apps/miniapp_api/tests/test_food_photo_proxy_2455.py`),
 *    см. `lib/diary-photo.ts`.
 *
 * 2. **Не в query-параметр, ни под каким именем.** Подпись в адресе уезжает
 *    в журналы nginx, в историю браузера и в `Referer` соседним сайтам — это
 *    утечка ключа доступа к чужим данным на срок жизни подписи. Выведено:
 *    DRF-2455 и DRF-2539 (общий прокси фото нельзя строить как «отдадим
 *    ссылку, браузер загрузит»).
 *
 * ### Что ещё кладётся в тот же конверт
 *
 * Все носители до DRF-2549 собирали одну и ту же тройку в одном порядке —
 * она и перенесена сюда без изменений: подпись, затем обход для локальной
 * разработки (`dev-bypass.ts`, срабатывает только без подписи), затем
 * выбранный салон (`salon-choice.ts`).
 *
 * ### Почему копии вообще были
 *
 * Клиенты, которым нужен ответ-`Blob`, а не JSON (выгрузка данных
 * `personal-data.ts`, снимок еды `diary-photo.ts`), ходят своим `fetch`:
 * `api.ts::request` типизирован под JSON. Заголовок они собирали заново —
 * отсюда шестнадцать копий. Свой `fetch` остаётся законным; собирать
 * заголовок в нём — нет: только через {@link applyIdentityHeaders}.
 */
import { applyDevBypassHeaders } from "./dev-bypass";
import { getInitData } from "./max-sdk";
import { applySalonChoiceHeader } from "./salon-choice";

/** Положить в `headers` подпись человека и сопутствующие заголовки. */
export function applyIdentityHeaders(headers: Headers): Headers {
  const initData = getInitData();
  if (initData) headers.set("Authorization", `MaxInitData ${initData}`);
  applyDevBypassHeaders(headers);
  applySalonChoiceHeader(headers);
  return headers;
}
