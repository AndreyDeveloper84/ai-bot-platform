/**
 * Полка «Ayla подобрала тебе» — ОДИН выключатель на её показ и на запрос
 * за её данными.
 *
 * Решение владельца, `docs/OPEN_DECISIONS.md` §172, ответ 40 (23.09):
 * полка уходит с экрана, но **код не удаляется** — она ждёт, когда у
 * подбора появится «почему». Это ответ, а не отложенный вопрос: константа
 * стоит здесь по решению, а не «пока».
 *
 * Почему выключатель уехал из экрана в отдельный файл (DRF-2348). Решение
 * гасило полку, но не снимало обращение за её данными: оно уходило при
 * каждом открытии Главной, хотя показывать нечего. Чинится это одним
 * выключателем на оба места — и на вёрстку, и на запрос. Два рядом
 * стоящих условия разъезжаются: однажды полку включат, а данных не будет,
 * и выглядеть это будет как «полка сломалась».
 *
 * Функция, а не голая константа, — чтобы сторож мог проверить ОБЕ
 * стороны: тёмная полка не ходит в сеть, зажжённая ходит и показывает
 * привезённое. Без второй половины узла включение полки было бы
 * непроверенным.
 *
 * Дата и номер решения в тексте не для красоты: без них через месяц никто
 * не вспомнит, почему выключено, и выключатель побоятся трогать.
 */
export const AYLA_PICKS_SHELF_ON = false;

/** Зажжена ли полка «Ayla подобрала тебе». Включение — одна строка выше. */
export function aylaPicksShelfOn(): boolean {
  return AYLA_PICKS_SHELF_ON;
}
