/**
 * Адрес принадлежит клиентской поверхности Mini App (DRF-2687).
 *
 * Нужен каскаду ролей в `App.tsx`: сотрудник салона, пришедший по кнопке
 * из клиентского чата на такой адрес, получает клиентское дерево
 * маршрутов, а не catch-all своего кабинета.
 *
 * Граница осознанная:
 *  - `/customer/*` — все цели кнопок чата (`_ROUTE_MAP`, `reco_…`,
 *    `reschedule_…` в `max-sdk.ts`) и все вкладки `CustomerTabBar`;
 *  - `/feedback/*` — единственный внутренний переход клиентских экранов
 *    за пределы `/customer/*` (оценка визита из «Моих записей»).
 *
 * Легаси-алиасы (`/catalog/:id`, `/book/…`, `/my-visits/…`) сюда не
 * входят: кнопки чата на них не ведут и клиентские экраны на них не
 * переходят. «/» тоже нет — это вход в кабинет.
 */
export function isCustomerSurfacePath(pathname: string): boolean {
  return pathname.startsWith("/customer/") || pathname.startsWith("/feedback/");
}
