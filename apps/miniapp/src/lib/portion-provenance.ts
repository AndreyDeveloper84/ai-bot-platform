/**
 * Происхождение порции — единственный вход перевода провода во внутреннее
 * значение (DRF-2371, словарь каталога из DRF-2402).
 *
 * Зачем вообще признак. Числа в ответе о еде считаются от веса порции, а
 * вес берётся из разных источников: его называет распознаватель фото,
 * называет сам человек, подставляет справочник типовой величиной — или
 * не называет никто, и тогда каталог считает по своей базовой константе.
 * Все четыре случая дают число одинакового вида, и по виду они
 * неотличимы. Показать подставленное как названное — та же ложь, что
 * «~0 ккал» о блюде, которого никто не считал.
 *
 * Провод (`portion_source` каталога): `provider` | `typical` | `unknown`.
 * `typical` объявлен, но пока не выдаётся (половина B, DRF-2444).
 *
 * Правила чтения, от которых зависит правдивость:
 *
 * 1. **Поля нет — это `unknown`, а не «названо».** Единственное
 *    умолчание, при котором мы не соврём: старый ответ провенанса не
 *    несёт, и выдавать его за названный нельзя.
 * 2. **Незнакомая строка — тоже `unknown`.** Когда в словаре появится
 *    четвёртое значение, новый клиент покажет его осторожно, а не как
 *    подтверждённое. Fail-closed здесь важнее полноты.
 * 3. **`unknown` — не «чисел нет».** Это «никто не назвал вес»: числа при
 *    этом могут быть посчитаны (каталог считает по своей константе), и
 *    именно поэтому их нельзя подавать как названные.
 *
 * Внутренние имена намеренно не повторяют провод: `provider` на проводе
 * значит «вес назвал наблюдавший», включая самого человека при ручном
 * вводе, — «измерено провайдером» было бы неверным прочтением.
 */

/** Внутреннее значение. `absent` — поля в ответе не было вовсе. */
export type PortionProvenance = "named" | "typical" | "unnamed" | "absent";

/** Провод → внутреннее. Единственное место, где живут строки каталога. */
const WIRE_TO_PROVENANCE: Record<string, PortionProvenance> = {
  provider: "named",
  typical: "typical",
  unknown: "unnamed",
};

/**
 * Прочитать признак из ответа каталога.
 *
 * `undefined`/`null` → `absent`; незнакомая строка → `unnamed`.
 */
export function portionProvenanceOf(wire: unknown): PortionProvenance {
  if (wire === undefined || wire === null) return "absent";
  if (typeof wire !== "string") return "unnamed";
  return WIRE_TO_PROVENANCE[wire] ?? "unnamed";
}

/**
 * Можно ли показать число как названное.
 *
 * Только `named`. `typical` и `unnamed` числа не подтверждают: рядом с
 * ними обязателен ход «назови вес», а до согласованного владельцем текста
 * оговорки число по типовой не показывается вовсе — это строже
 * требования и никого не обманывает.
 *
 * `absent` — переходный случай: до половины B (DRF-2444) числа в ответе
 * существуют только тогда, когда вес кто-то назвал, поэтому старый ответ
 * с числом показывается как прежде. Как только поле появится во всех
 * ответах, эта ветка станет мёртвой — и её надо будет снять вместе с
 * самим значением `absent`.
 */
export function portionNumbersAreNamed(provenance: PortionProvenance): boolean {
  return provenance === "named" || provenance === "absent";
}

/** Нужен ли рядом ход «назови вес». */
export function portionNeedsConfirmation(provenance: PortionProvenance): boolean {
  return provenance === "typical" || provenance === "unnamed";
}
