/**
 * Показывать ли честное отсутствие «недостаточно подтверждённых данных».
 * Ровно один исход: резолвер ответил, кандидаты были, и их отвергло
 * «связь не подтверждена» (§76). Остальные пустоты — свои кадры
 * (:func:`absenceFrame`), а не это имя: одно имя на два состояния
 * запрещено.
 */
export function showsNoVerifiedEvidence(outcome: PicksOutcome): boolean {
  return outcome === "NO_VERIFIED_CANDIDATES";
}

// ---------------------------------------------------------------------------
// Остальные пустоты — каждой своё имя и свой кадр (DRF-1767, DRF-1768).
//
// До этого среза они молчали намеренно: текст «недостаточно данных» на
// них был бы ложью. Молчание оказалось второй ложью — пустой экран. Макет
// C04 (DRF-1270): C04.5 safety boundary — «безопасное объяснение +
// разрешённое следующее действие, без CTA на заблокированное, не
// изображать диагностику»; supporting states — «technical failure,
// retry». Каждому исходу — своё состояние, ни одного пустого.
// ---------------------------------------------------------------------------

export type AbsenceKind =
  /** §76: связи не подтверждены — текст владельца OD-PILOT-9. */
  | "no_verified"
  /** Медицинский гейт отверг кандидатов (C04.5). */
  | "safety_boundary"
  /** Нужда названа, никто не совпал — вопрос к запросу, не к разметке. */
  | "no_capable"
  /** Источник подбора недоступен / ответил не по контракту / прислал то,
   *  что полка не умеет — отказ источника, не состояние знания. */
  | "source_failure";

