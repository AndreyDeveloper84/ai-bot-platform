/**
 * Показывать ли честное отсутствие. Ровно один исход: резолвер ответил,
 * кандидаты были, и их отвергло «связь не подтверждена» (§76).
 *
 * Остальные пустоты остаются молчаливыми намеренно:
 * - `SAFETY_BLOCKED` — сработал медицинский гейт; текст про «недостаточно
 *   данных» послал бы человека чинить разметку там, где чинить нечего;
 * - `NO_CAPABLE_CANDIDATES` — нужда названа, никто не совпал: это не про
 *   подтверждение, а про запрос;
 * - `UNAVAILABLE` / `CONTRACT_VIOLATION` / `UNRENDERABLE_CANDIDATES` —
 *   отказ источника, не состояние знания.
 * Давать им одно имя значило бы то самое «одно имя на два состояния».
 */
export function showsNoVerifiedEvidence(outcome: PicksOutcome): boolean {
  return outcome === "NO_VERIFIED_CANDIDATES";
}
