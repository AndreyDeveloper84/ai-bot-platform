/**
 * Каркас пилотной салонной админки — три раздела (DRF-1235).
 *
 * # Что это
 *
 * Решение владельца 07.09.2026: салонная админка Controlled Pilot — это
 * три вкладки «Сегодня · Расписание · Ayla» и постоянная нижняя
 * навигация. IA зафиксирован в DRF-1235 (комментарий от 21.08.2026,
 * «UX APPROVED / FROZEN FOR NEXT DESIGN STEP») и виден на макете в
 * DRF-1236.
 *
 * # Почему рядом с `admin-tabs.ts`, а не вместо него
 *
 * Пятивкладочная поверхность (`День · Команда · Услуги · Чаты ·
 * Настройки`) — временный мост: 20 живых экранов, 16 маршрутов, 25
 * ручек, и салон работает на них сегодня. Владелец не сказал её
 * выключать, поэтому обе поверхности живут параллельно, и правило
 * доступа у каждой своё. Склеить их в один модуль значило бы связать
 * судьбу моста с судьбой пилота — а снимать мост будут отдельным
 * решением.
 *
 * # Права
 *
 * Владелец и администратор — и никто больше.
 *
 * Это НЕ повтор `adminTabsFor`: там ресепшн видит вкладки моста, здесь
 * она не видит пилота вовсе.
 *
 * И это НЕ отражение гейта ручки — формулировка, которая была здесь до
 * DRF-1552 и успела устареть за один день. `require_admin_role`
 * действительно закрывает `/admin/*` целиком, но `GET
 * /api/v1/admin/day/` с DRF-1552 живёт под
 * `require_admin_or_reception_read` и пускает ресепшн на безопасном
 * методе (решение владельца, `docs/OPEN_DECISIONS.md` §35 п.1). То
 * есть экран «Сегодня» ресепшн получил бы данные, если бы до запроса
 * дошло, — 403 её отсюда не выставит.
 *
 * Закрывает её решение о ПОВЕРХНОСТИ, а не о ручке: пилотная админка
 * открыта владельцу и администратору, а какие салонные сценарии отдать
 * ресепшн — отдельный незакрытый вопрос. Открыть ей пилот значило бы
 * ответить на него молча.
 *
 * Правило вынесено сюда, а не написано в компонентах, потому что его
 * читают два места — страж маршрутов в `App.tsx` и сама панель. Копия
 * в каждом — это будущий разъезд: вкладка видна, а адрес закрыт.
 */

import type { AdminRoleFlags } from "./admin-tabs";

/** Разделы пилотной поверхности, в порядке отрисовки панели. */
export type SalonPilotTabKey = "today" | "schedule" | "ayla";

/**
 * Порядок — часть решения, а не деталь реализации.
 *
 * «Сегодня» стоит первым, потому что это главный экран после входа и
 * операционный центр текущего дня (DRF-1235). «Ayla» — последняя:
 * разговорный вход в те же операции, а не отдельная сущность.
 */
export const SALON_PILOT_TABS: readonly SalonPilotTabKey[] = [
  "today",
  "schedule",
  "ayla",
];

/** Адрес каждого раздела. Маршруты объявлены в `App.tsx`. */
export const SALON_PILOT_PATHS: Readonly<Record<SalonPilotTabKey, string>> = {
  today: "/admin/today",
  schedule: "/admin/schedule",
  ayla: "/admin/ayla",
};

/** Подпись на вкладке — то же слово, что в макете. */
export const SALON_PILOT_LABELS: Readonly<Record<SalonPilotTabKey, string>> = {
  today: "Сегодня",
  schedule: "Расписание",
  ayla: "Ayla",
};

/**
 * Куда садится пилотная поверхность — «Сегодня» (DRF-1235).
 *
 * Мостовая посадка (`adminLandingPath`) не трогается: пока владелец не
 * переключил салон на пилот, вход в приложение ведёт туда же, куда и
 * вчера.
 */
export const SALON_PILOT_LANDING = SALON_PILOT_PATHS.today;

/**
 * Открыт ли пилот этому человеку.
 *
 * Отрицания здесь нет намеренно: спрашивается наличие управляющей роли,
 * а не отсутствие приёмной. Владелец, которому бэкенд заодно проставил
 * роль ресепшн, остаётся владельцем — ровно как в `isReceptionOnly`.
 */
export function canOpenSalonPilot(me: AdminRoleFlags): boolean {
  return Boolean(me.is_owner || me.is_admin);
}
