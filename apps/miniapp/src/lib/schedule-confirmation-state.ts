/**
 * Состояние подтверждения расписания — ТРИ значения, а не два (§29.5, §83).
 *
 * Правило, ради которого этот модуль существует, записано в §29.5
 * (`docs/OPEN_DECISIONS.md`):
 *
 * > Неизвестное расписание нельзя считать ни свободным, ни занятым. Третье
 * > состояние, а не подстановка значения по умолчанию.
 *
 * И там же: **«заглушка 10:00–19:00 подтверждением не является»**. То есть
 * часы, показанные экраном, и часы, за которые салон поручился, — разные
 * утверждения, и сворачивать их в одно нельзя.
 *
 * # Почему трёх состояний, а не «подтверждено / нет»
 *
 * «Подтверждено когда-то» и «подтверждено для ЭТИХ часов» — тоже разные
 * утверждения. Мастер, чьё расписание заверили в понедельник, а во вторник
 * изменили, не подтверждён; но и «никогда не подтверждали» про него неправда,
 * и лечится это иначе — не первым подтверждением, а повторным. Сервер отдаёт
 * обе половины (`confirmed_at` и `is_current`), и склеить их в булево значило
 * бы выбросить ту, которой отличаются действия.
 *
 * # Один словарь на две поверхности
 *
 * Те же три формулировки уже сказаны в `screens/admin/AdminMasterDetailScreen`
 * (старая админка) — там они записаны прямо в разметке. Пилотная поверхность
 * берёт их отсюда, чтобы одно и то же состояние не называлось на двух экранах
 * по-разному. Свести к этому модулю и старый экран — маленькая правка, но он
 * не в моём наделе; названо как долг, а не сделано молча.
 */

import type { MasterScheduleConfirmation } from "./admin-api";

export type ConfirmationState = "confirmed" | "stale" | "never";

/**
 * Какое из трёх состояний перед нами.
 *
 * Порядок проверок значим: `is_current` истинно только вместе с датой, а вот
 * дата без `is_current` — это ровно устаревшее подтверждение, и проверять её
 * первой значило бы прочитать «устарело» как «подтверждено».
 */
export function confirmationState(
  confirmation: MasterScheduleConfirmation | null | undefined,
): ConfirmationState {
  if (confirmation?.is_current) return "confirmed";
  if (confirmation?.confirmed_at) return "stale";
  return "never";
}

/** Читаемая дата подтверждения; пустая строка, если её нет. */
export function formatConfirmedAt(iso: string | null): string {
  if (!iso) return "";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleDateString("ru-RU", { day: "numeric", month: "long" });
}

/**
 * Что показать человеку про подтверждение.
 *
 * Формулировки намеренно говорят о САЛОНЕ, а не о расписании: «не
 * подтверждено» без подлежащего читается как свойство часов, тогда как это
 * свойство поручительства. Часы могут быть верными и неподтверждёнными
 * одновременно — экран не вправе намекать, что они неверны.
 */
export function confirmationLabel(
  confirmation: MasterScheduleConfirmation | null | undefined,
): string {
  switch (confirmationState(confirmation)) {
    case "confirmed": {
      const by = confirmation?.confirmed_by?.name;
      const when = formatConfirmedAt(confirmation?.confirmed_at ?? null);
      return `Расписание подтверждено ${when}${by ? ` · ${by}` : ""}`;
    }
    case "stale":
      return "Часы изменились после подтверждения — салон заверял другие";
    case "never":
      return "Расписание не подтверждено — салон его не заверял";
  }
}
