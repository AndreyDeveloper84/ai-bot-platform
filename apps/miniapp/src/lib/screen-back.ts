/**
 * Вид экрана по отношению к возврату — обязательное объявление
 * (DRF-1493).
 *
 * # Зачем тип, а не соглашение
 *
 * До этого возврат был личным делом каждого экрана: кто нарисовал
 * стрелку и позвал `useBackButton`, у того возврат был; кто забыл — у
 * того не было, и никто об этом не узнавал. Так и уехал каталог
 * (`CustomerCatalogScreen`), на который владелец указал на пилоте:
 * «Нету кнопки назад». Вместе с ним — ещё четыре экрана.
 *
 * Молчание было валидным состоянием. Здесь оно перестаёт им быть:
 * `ScreenLayout` требует `back`, а экран без общего каркаса обязан
 * позвать `useScreenBack` — иначе падает `screens.backContract.test.tsx`.
 *
 * # Почему не `history.back()`
 *
 * Человек попадает в мини-приложение по deep link из бота
 * (`open_app` с payload, `apps/skills/welcome/skill.py`), и истории
 * переходов у него нет вовсе. `navigate(-1)` на таком входе либо не
 * делает ничего, либо закрывает приложение — то есть ведёт себя
 * по-разному в зависимости от того, как человек сюда попал. Поэтому у
 * возврата здесь всегда ЗАДАННОЕ место: `kind: "up"` несёт адрес, а не
 * смещение по истории.
 *
 * # Три вида, и только три
 *
 * - `root` — сюда ведёт вход, выше некуда. Требует `why`: объявить
 *   себя корнем можно, но не молча.
 * - `up` — есть один родитель, и это адрес.
 * - `action` — возврат заданным действием экрана: шаг мастера
 *   онбординга, переход с восстановлением состояния. Тоже заданное
 *   действие, не история.
 */

export type BackIntent =
  | {
      readonly kind: "root";
      /** Почему выше некуда. Пишется для читателя, не для машины. */
      readonly why: string;
    }
  | {
      readonly kind: "up";
      /** Адрес родителя. Именно адрес — не `-1`. */
      readonly to: string;
    }
  | {
      readonly kind: "action";
      /**
       * Возврат — заданное действие самого экрана: шаг назад внутри
       * мастера или переход с восстановлением состояния. Действие, а
       * не смещение по истории: `navigate(-1)` здесь по-прежнему
       * запрещён.
       */
      readonly onBack: () => void;
    };

/** «Я корневой» — объявление с причиной, а не пропуск. */
export function screenRoot(why: string): BackIntent {
  return { kind: "root", why };
}

/** «Мой родитель — вот этот адрес.» */
export function backTo(to: string): BackIntent {
  return { kind: "up", to };
}

/** «Возврат — вот это заданное действие.» */
export function backByAction(onBack: () => void): BackIntent {
  return { kind: "action", onBack };
}
