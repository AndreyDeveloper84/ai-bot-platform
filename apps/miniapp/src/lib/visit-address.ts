/**
 * Адрес визита — одно место, где трёхзначность превращается во фразу.
 *
 * Поле приходит с сервера дословно как в колонке (DRF-1587/1611), и три
 * его состояния значат разное:
 *
 * ```
 * строка   адрес известен
 * ""       САЛОН сказал, что адреса нет. Ответ, а не молчание
 * null     источник об адресе не сказал ничего. Это НАШ пробел
 * ```
 *
 * # Почему функция, а не три тернарника на каждом экране
 *
 * До DRF-1652 разбор жил inline в одном экране. Второй экран, которому
 * понадобился тот же адрес, — это второе место, где решают, что показать
 * человеку при `null`. Две копии совпадают ровно до первой правки одной
 * из них, и разойдутся молча: обе останутся «правильными» по отдельности.
 *
 * # Почему при `null` фраза, а не пустота
 *
 * Асимметрия намеренная и обратная той, что напрашивается. При `""`
 * состояние **окончательное**: салон ответил, спрашивать некого. При
 * `null` — **исправимое**: адрес скорее всего есть, просто до нас не
 * доехал, и человеку стоит спросить. Спрятать строку у `null` значило бы
 * дать меньше тому, кому нужнее.
 */

/** Салон ответил, что адреса нет. */
export const ADDRESS_SAID_NONE = "Адрес не указан";

/** Источник промолчал — человеку есть у кого спросить. */
export const ADDRESS_UNKNOWN = "Уточните адрес в салоне";

/**
 * Фраза для показа человеку.
 *
 * Принимает ровно то, что пришло с провода, и не нормализует вход:
 * `undefined` (ключа в ответе не было вовсе) считается тем же незнанием,
 * что и `null`, — но это ЕДИНСТВЕННОЕ схлопывание здесь, и оно в
 * безопасную сторону: «спросите в салоне» верно в обоих случаях.
 */
export function visitAddressText(address: string | null | undefined): string {
  if (address === null || address === undefined) return ADDRESS_UNKNOWN;
  if (address === "") return ADDRESS_SAID_NONE;
  return address;
}
