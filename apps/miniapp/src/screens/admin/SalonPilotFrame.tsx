/**
 * Рамка экрана пилотной салонной админки (DRF-1235).
 *
 * На макете (DRF-1236) все три экрана начинаются одинаково: строка с
 * названием салона, под ней крупный заголовок раздела, под ним —
 * содержимое, внизу — постоянная панель из трёх вкладок. Рамка вынесена
 * сюда, чтобы три экрана не разъехались по отступам и по тому, откуда
 * они берут имя салона.
 *
 * # Чего на рамке нет
 *
 * * **Стрелки выбора салона.** Макет её показывал; DRF-1235 велел убрать
 *   («убрать стрелку выбора салона, пока multi-salon не входит в P0»).
 *   Имя салона здесь — подпись, а не кнопка.
 * * **Меню «⋮».** На макете оно есть, и DRF-1235 подтвердил для P0 ровно
 *   один его пункт — «Рабочее время». Экрана рабочего времени в
 *   приложении сегодня нет ни по одному адресу, а меню с
 *   единственным пунктом, ведущим в никуда, — это обещание. Кнопка
 *   появится вместе с экраном.
 * * **Своей стрелки «назад».** Возврат есть, но он не нарисован —
 *   см. ниже.
 *
 * Вложенные потоки пилота (создание записи, детали записи) — отдельные
 * экраны с явным возвратом, и DRF-1235 прямо запрещает держать под ними
 * нижнюю панель, поэтому эту рамку они использовать не будут.
 *
 * # Возврат на мост — системной кнопкой MAX, а не своей
 *
 * Пока пилот не стал посадкой, в него ВХОДЯТ — с «Настроек» моста
 * (решение владельца 07.09.2026). Вход без выхода — ловушка: панель
 * пилота ведёт только на три его адреса, и человек, нажавший «Открыть
 * пилотную админку», остался бы в поверхности, где нет ни «Команды»,
 * ни «Услуг», ни «Чатов».
 *
 * Выход сделан самой дешёвой из существующих механик: показывается
 * системная кнопка «назад» MAX и на неё вешается переход на
 * `/admin/settings`. Это ноль новых пикселей, одно место на все три
 * раздела и та же механика, которой в приложении уже управляют
 * (`setBackButton` зовут семь экранов; корни моста её прячут).
 * Рисовать свою стрелку значило бы добавить на пилот элемент, которого
 * нет ни на одном макете, — ровно то, чего DRF-1235 просил не делать.
 *
 * Возврат ЖЁСТКИЙ, а не `navigate(-1)`. История сюда приводит двумя
 * путями — кнопкой с «Настроек» и прямой ссылкой из закладки или
 * старого сообщения бота, — и во втором случае шаг назад по истории
 * увёл бы человека из приложения вовсе. Адрес возврата тот же, с
 * которого вход: получается замкнутый круг «Настройки → пилот →
 * Настройки».
 *
 * Оговорка, которую стоит знать: `setBackButton` вне MAX — пустышка
 * (`maxBridge()` возвращает `undefined`), поэтому в браузере разработчика
 * кнопки не будет. Это верно для всей навигации приложения, а не только
 * для пилота.
 */

import { useEffect } from "react";
import type { ReactNode } from "react";
import { useNavigate } from "react-router-dom";

import { SalonPilotTabBar } from "../../components/SalonPilotTabBar";
import type { MeResponse } from "../../lib/admin-api";
import { onBackButton, setBackButton } from "../../lib/max-sdk";

/** Куда возвращает системная кнопка «назад» — экран, с которого вход. */
const PILOT_EXIT_PATH = "/admin/settings";

export function SalonPilotFrame({
  me,
  title,
  subtitle,
  children,
}: {
  me: MeResponse;
  /** Название раздела — то же слово, что на вкладке. */
  title: string;
  /**
   * Строка под заголовком. Только то, что уже известно наверняка: на
   * «Сегодня» это дата, которую вернул сервер. Пока ответа нет —
   * `null`, и строки нет вовсе. Заранее посчитанная на устройстве дата
   * выглядела бы как ответ сервера и врала бы про часовой пояс салона.
   */
  subtitle?: string | null;
  children: ReactNode;
}) {
  const navigate = useNavigate();

  useEffect(() => {
    setBackButton(true);
    const off = onBackButton(() => navigate(PILOT_EXIT_PATH));
    return () => {
      off();
      setBackButton(false);
    };
  }, [navigate]);

  return (
    <div className="screen">
      <p className="salon-pilot__brand">{me.tenant.name}</p>
      <h1 className="screen__title">{title}</h1>
      {subtitle ? <p className="salon-pilot__subtitle">{subtitle}</p> : null}
      <div className="screen__body">{children}</div>
      <SalonPilotTabBar />
    </div>
  );
}
