/**
 * Строковые литералы исходника — общий разбор для сторожей копии.
 *
 * Жил в `no-person-names.guard.test.ts`, откуда его импортировал второй
 * сторож (DRF-2378). Импорт ТЕСТОВОГО файла заставлял vitest собирать его
 * узлы второй раз: они выполнялись и в своём файле, и в чужом, а падение
 * показывалось не на том файле, где живёт (найдено ревью). Обычный модуль
 * такого не делает.
 *
 * Предел, общий для обоих сторожей: читаются только литералы в кавычках и
 * обратных кавычках. **Голый текст JSX** (`<p>Напишите оператору</p>`)
 * сюда не попадает — это второй класс, и он назван, а не спрятан.
 */

/** Строковые литералы кода без комментариев — по одному на элемент. */
export function stringLiteralsOf(source: string): string[] {
  // `\r` снимается заранее: в JS `.` не матчит перевод строки, и строка
  // комментария с CRLF-хвостом пережила бы `^\s*\/\/.*$` (нашлось пробой).
  const noBlockComments = source.replace(/\r/g, "").replace(/\/\*[\s\S]*?\*\//g, "");
  const literals: string[] = [];
  for (const rawLine of noBlockComments.split("\n")) {
    const line = rawLine.replace(/^\s*\/\/.*$/, "");
    for (const m of line.matchAll(/"((?:[^"\\]|\\.)*)"|'((?:[^'\\]|\\.)*)'|`((?:[^`\\]|\\.)*)`/g)) {
      const text = m[1] ?? m[2] ?? m[3] ?? "";
      if (text.trim()) literals.push(text);
    }
  }
  return literals;
}
