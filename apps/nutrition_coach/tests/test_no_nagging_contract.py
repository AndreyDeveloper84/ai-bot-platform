"""Чем на самом деле держится «не понукает» — T7 (DRF-1464).

`test_copy.py` проверяет, что НАШИ шаблоны проходят страж, и что часть
запрещённых форм страж кусает. Здесь — вопрос, которого тот файл не
задаёт: **чем держится каждое из семи правил и где оно не держится
ничем.**

Ответ оказался не однородным, и в этом вся ценность файла:

* **R2, R3, R5 держит СТРАЖ** — они выражаются формой, и regex её видит.
* **R1, R4, R6 держат ШАБЛОНЫ** — «ешь лёгкое» и «минус 2 кг» страж не
  видит вовсе. На проактивном пути это безопасно: там нет свободного
  текста, весь исходящий — `copy.render_*` (прибито ниже архитектурным
  стражем). На РЕАКТИВНОМ пути (T4, §48) пишет модель, и там эти три
  правила не держит ничто.

Второе — не предположение, а замер: корпус ниже прогнан через страж, и
все восемь строк проходят.

### Почему это записано тестом, а не в заметке

Заметку не читают перед тем, как добавить категорию. Тест — читают,
потому что он падает. Когда кто-нибудь закроет R4 на выходе, корпус
`_UNGUARDED_ON_FREE_TEXT` начнёт врать, тест упадёт и заставит обновить
карту вместо того, чтобы оставить её устаревшей и убедительной.
"""

from __future__ import annotations

import ast
import inspect

import pytest

from apps.orchestrator.safety.outbound import evaluate_outbound

#: Формы, которые страж ВИДИТ. Дубль минимальный и намеренный: если
#: категорию однажды ослабят, здесь станет видно, какое правило осиротело.
_GUARDED = (
    ("R2", "nag", "Не забывайте про цель!"),
    ("R2", "nag", "Вы давно не записывали еду"),
    ("R3", "nag", "Семь дней подряд — так держать!"),
    ("R5", "medical", "У вас аллергия на глютен"),
    ("R5", "medical", "Примите антибиотик и всё пройдёт"),
)

#: Формы, которые страж НЕ видит. Не список пожеланий — ЗАМЕР.
#:
#: На проактивном пути они недостижимы: там нет свободного текста. На
#: реактивном (T4) их пишет модель, и единственное, что стоит между ними и
#: человеком, — инструкция в промпте, то есть просьба, а не гарантия.
#:
#: Классы промахов названы, чтобы следующий видел не «восемь строк», а
#: три дыры:
_UNGUARDED_ON_FREE_TEXT = (
    # R4 — шкалы, размеры, дефициты (§2.1)
    ("R4", "Минус 2 кг за месяц — отличный результат"),
    ("R4", "Талия 65 см — реальная цель"),
    ("R4", "Твой дефицит калорий 300 ккал"),
    # R1 — предписание привычки вместо исхода (§2.3)
    ("R1", "Ешь лёгкое на ужин"),
    ("R1", "Съешь салат вместо пасты"),
    # R6 — автономия (§2.6)
    ("R6", "Ты обязана продолжать"),
    ("R6", "Не бросай, ты почти у цели"),
)


class TestWhatTheGuardActuallyHolds:
    @pytest.mark.parametrize(("rule", "category", "text"), _GUARDED)
    def test_the_guarded_rules_bite(self, rule: str, category: str, text: str) -> None:
        verdict = evaluate_outbound(text)

        assert verdict.blocked, f"{rule}: страж перестал видеть {text!r}"
        assert category in verdict.categories, rule

    @pytest.mark.parametrize(("rule", "text"), _UNGUARDED_ON_FREE_TEXT)
    def test_the_unguarded_rules_are_measured_not_assumed(self, rule: str, text: str) -> None:
        """Замер текущего состояния, а НЕ желаемого.

        Тест падает в двух случаях, и оба полезны. Если кто-то закроет
        правило на выходе — падение скажет обновить карту выше, и файл
        перестанет утверждать неправду. Если кто-то ослабит страж так, что
        строка вдруг заблокируется по чужой категории, — падение скажет
        и об этом.
        """
        verdict = evaluate_outbound(text)

        assert verdict.allowed, (
            f"{rule}: строка теперь блокируется ({verdict.categories}). "
            "Это, вероятно, хорошая новость — обновите карту в докстринге "
            "модуля и перенесите строку в _GUARDED."
        )

    def test_the_map_is_not_vacuous(self) -> None:
        """Контроль присутствия на весь файл.

        Если бы страж вдруг перестал блокировать что угодно, половина
        «не видит» прошла бы победно, а половина «видит» упала бы. Эта
        проверка ловит вырождение раньше и одной строкой.
        """
        assert evaluate_outbound("Не забывайте про цель!").blocked
        assert evaluate_outbound("Записала обед: борщ.").allowed


class TestTheProactiveSurfaceSpeaksOnlyTemplates:
    """Архитектурный страж: на проактивном пути нет свободного текста.

    Это и есть то, чем держатся R1, R4 и R6 на этой поверхности — не
    страж, а невозможность сказать что-то кроме шаблона. Пока это правда,
    их отсутствие в выходном фильтре не стоит ничего; в ту минуту, когда
    кто-нибудь передаст в отправку f-строку, оно начнёт стоить всё.

    Приём тот же, что у ``test_no_frequency_counters``: разбор исходника.
    Проверка поведением тут невозможна — «текст пришёл не из шаблона»
    неотличимо от «текст пришёл из шаблона» по самому тексту.
    """

    def test_every_vetted_string_comes_from_copy(self) -> None:
        from apps.nutrition_proactive import coach

        tree = ast.parse(inspect.getsource(coach))
        vetted: list[ast.expr] = [
            node.args[0]
            for node in ast.walk(tree)
            if isinstance(node, ast.Call)
            and isinstance(node.func, ast.Name)
            and node.func.id == "vet_outbound"
            and node.args
        ]

        # Контроль присутствия: отправка вообще существует. Пустой список
        # прошёл бы циклом ниже победно и не доказал бы ничего.
        assert vetted, "vet_outbound не найден — страж смотрит не туда"

        for argument in vetted:
            assert isinstance(argument, ast.Call), (
                "в отправку ушло не вызванное выражение — на проактивном "
                "пути допустим только рендер шаблона"
            )
            func = argument.func
            assert isinstance(func, ast.Attribute), ast.dump(argument)
            assert func.attr.startswith("render_"), (
                f"в отправку ушёл {func.attr}(), а не рендер шаблона. "
                "R1, R4 и R6 на этой поверхности не проверяются стражем — "
                "их держит только то, что сказать можно лишь шаблоном."
            )
