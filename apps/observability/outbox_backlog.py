"""Счётчик неразобранного исходящего ящика (`eventbus.DomainEvent`).

Замер пилота 09.09.2026 (`docs/PILOT_MEASUREMENTS.md` §11): в ящике
**53 события, 0 отправленных, 0 попыток**, самой старой записи **двадцать
восемь суток**. Разбирать их некому — задача диспетчера объявлена, но в
`CELERY_BEAT_SCHEDULE` её нет, и вызвать её больше неоткуда.

Этот модуль не чинит доставку. Он отвечает на единственный вопрос,
на который сегодня не отвечает никто: **разбирается ли ящик вообще.**

## Почему счётчик заводится ПЕРВЫМ, до подписчика и до расписания

Порядок починки — счётчик → подписчик → расписание — выбран потому, что
без счётчика об исходе починки нельзя будет сказать ничего, кроме
«стало ноль». А ноль даёт и заглушка: `NoopSubscriber` не бросает
исключений, поэтому диспетчер пометит `is_dispatched=True` всё, до чего
дотянется, ничего никому не доставив. Счётчик — единственное, что
отличает доставку от пометки.

## Почему он живёт ЗДЕСЬ, а не в `apps/eventbus`

Единственная тревога исходящей шины — `_emit_dlq_alert` — вызывается из
тела `dispatch_pending_events`. Диспетчер не идёт → тревога не звучит →
молчание читается как здоровье. **Сторож, живущий внутри того, за чем он
следит, — не сторож.**

Поэтому счётчик стоит снаружи предмета: он не знает о диспетчере ничего,
не зависит от его существования и смотрит только на таблицу. Проверка,
которой он обязан удовлетворять, одна: *если предмет мёртв — закричит ли
сторож?* Здесь — да, и именно потому, что предмет ему не нужен.

## Почему возраст, а не только количество

Ноль неотправленных при мёртвом ПИСАТЕЛЕ выглядит ровно так же, как ноль
при работающей доставке. Различает их возраст самой старой строки: пока
кто-то пишет, а никто не разбирает, он растёт монотонно.

По той же причине порогом служит **возраст**, а не число: у здорового
диспетчера ящик непуст постоянно — между тиками в нём лежит то, что он
разберёт через минуту. Ненулевой размер нормален; старая строка — нет.

## Чего этот счётчик НЕ делает — читать до того, как на него положиться

**Он считает при СТАРТЕ процесса, а не непрерывно.** Форма взята у
`observability.W010`: системная проверка плюс запись из
``AppConfig.ready()``. Значит рост ящика МЕЖДУ стартами процессов не
виден: пока контейнеры перезапускаются (выкладки, рестарты воркеров) —
число будет всплывать при каждом старте; если не перезапускается ничто,
ящик растёт молча до следующего старта.

Периодический замер — отдельная работа: одна задача-обёртка над
:func:`measure_outbox_backlog` и одна запись в ``CELERY_BEAT_SCHEDULE``.
Сознательно не сделана здесь, чтобы не трогать расписание. **Пока её
нет, не строить выводов вида «сторож молчал, значит ящик разбирался»** —
он молчал ровно столько, сколько процесс не стартовал.

**Размен, принятый сознательно:** замер из ``AppConfig.ready()`` — это
обращение к БД во время инициализации приложений, и Django на него
ругается ``RuntimeWarning``. Альтернатива — считать только системной
проверкой — оставила бы сторожа невидимым в `uvicorn config.asgi`,
который системных проверок не гоняет, то есть ровно в том процессе, ради
которого W010 в своё время и продублировали логом. Прецедент в контуре
тот же: `apps.workers.subscriber_audit` пишет инвентарь из ``ready()``
и живёт с тем же предупреждением. Отказ (нет таблицы под ``migrate``,
недоступная БД) не роняет загрузку и получает СВОЮ строку — см.
:func:`apps.observability.checks.log_outbox_backlog`.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import datetime, timedelta

logger = logging.getLogger(__name__)

#: Возраст самой старой неразобранной строки, после которого ящик
#: считается незабираемым. Час выбран как заведомо больший, чем любой
#: разумный интервал опроса: диспетчер, поставленный в расписание,
#: разбирает пачками и не оставит строку лежать час. Сегодня, когда
#: разбирать некому вовсе, порог перейдён на двадцать восемь суток —
#: то есть сторож сработал бы в первый же день.
STALE_AFTER = timedelta(hours=1)

#: События, чьё застревание стоит называть ОТДЕЛЬНО от общей суммы.
#:
#: Сорок событий об атрибуции и записях переживут потерю; тринадцать
#: событий о разрешениях — вопрос 152-ФЗ. Само согласие при этом не
#: теряется: `apps/consent/services.py` пишет три независимые копии
#: (строка `ConsentRecord`, аналитическое событие, локальный аудит) и
#: все три коммитит до шины. Застревает четвёртая, доменная. Цена не
#: сегодняшняя, а завтрашняя: потребитель согласий, построенный на шине,
#: начнёт с пустой историей и не узнает, что она была непустой.
CONSENT_EVENT_NAMES = frozenset({"customer.consent.changed"})


@dataclass(frozen=True)
class OutboxBacklog:
    """Что лежит в ящике неразобранным. Пустой ящик — все нули и ``None``."""

    pending: int = 0
    oldest_created_at: datetime | None = None
    oldest_age: timedelta | None = None
    by_event_name: dict[str, int] = field(default_factory=dict)

    @property
    def is_stale(self) -> bool:
        """Ящик не разбирается: в нём есть строка старше :data:`STALE_AFTER`."""
        return self.oldest_age is not None and self.oldest_age > STALE_AFTER

    @property
    def consent_pending(self) -> int:
        """Сколько из неразобранного — события о разрешениях."""
        return sum(n for name, n in self.by_event_name.items() if name in CONSENT_EVENT_NAMES)

    def describe(self) -> str:
        """Одна строка для лога и текста проверки. Возраст — в сутках и часах."""
        parts = [f"{self.pending} неотправленных"]
        if self.oldest_age is not None:
            days = self.oldest_age.days
            hours = self.oldest_age.seconds // 3600
            parts.append(f"самая старая лежит {days} сут {hours} ч")
        if self.consent_pending:
            # Названы отдельно, а не растворены в сумме: у разрешений
            # другой вес, и читателю нельзя предлагать заметить это самому.
            parts.append(f"из них о согласиях: {self.consent_pending}")
        if self.by_event_name:
            breakdown = ", ".join(f"{name}={n}" for name, n in sorted(self.by_event_name.items()))
            parts.append(f"по именам: {breakdown}")
        return "; ".join(parts)


def measure_outbox_backlog(*, now: datetime | None = None) -> OutboxBacklog:
    """Снять ящик одним проходом. Читает, ничего не меняет.

    ``now`` — точка отсчёта возраста; параметром, а не ``timezone.now()``
    внутри, чтобы тест мерил возраст, а не расхождение часов.

    Импорты — внутри функции: модуль обязан импортироваться, даже когда
    приложения Django ещё не загружены (его зовут из ``AppConfig.ready``).
    """
    from django.db.models import Count, Min
    from django.utils import timezone

    from apps.eventbus.models import DomainEvent

    now = now or timezone.now()

    # Неразобранное — это НЕ отправленное и НЕ отложенное в dead-letter:
    # у dead-letter своя судьба и свой (пока не заведённый) разбор, и
    # смешивать их значило бы объявить разобранным то, что отложено.
    pending_qs = DomainEvent.objects.filter(is_dispatched=False, dead_lettered_at__isnull=True)

    aggregate = pending_qs.aggregate(total=Count("event_id"), oldest=Min("created_at"))
    total = aggregate["total"] or 0
    if not total:
        return OutboxBacklog()

    oldest_created_at = aggregate["oldest"]
    by_name = {
        row["event_name"]: row["n"]
        for row in pending_qs.values("event_name").annotate(n=Count("event_id"))
    }

    return OutboxBacklog(
        pending=total,
        oldest_created_at=oldest_created_at,
        oldest_age=(now - oldest_created_at) if oldest_created_at else None,
        by_event_name=by_name,
    )
