"""Слова модели над карточками не называют услугу, по которой поиск не шёл.

### Ход, из-за которого это написано

Пилот, 09.11. Человек нажал чип «Биоэнергетический массаж». Модель вызвала
``show_masters`` с услугой «массаж», получила пять массажистов и написала над
ними: «нашёл мастеров, которые предлагают биоэнергетический массаж». Трое из
пяти такой услуги не оказывают. Карточки были честным ответом на поиск по
слову «массаж»; ложным их сделала одна фраза над ними.

Сам поиск исправлен отдельно: названная услуга теперь доходит до каталога
целиком (:func:`apps.orchestrator.discovery.named_bookable_service`). Но тот
страж узнаёт только название услуги, слово в слово. Ход «хочу массаж лица
завтра вечером» названием не является, модель по-прежнему вправе искать
«массаж» — и по-прежнему может написать над списком «мастера массажа лица».

### Правило

Над карточками модель оставляет свои слова (DRF-1354). Она теряет их в одном
случае — когда все три условия верны разом:

1. слово сказал человек в этой реплике;
2. поиск по нему не шёл: его нет ни в услуге, ни в городе, ни в других
   аргументах вызова;
3. модель повторила его в тексте над карточками, и каталог знает это слово
   как слово из названия услуги.

Тогда текст модели заменяется детерминированным показом тех же карточек — со
строкой «Искала по твоим словам», которая называет то, по чему искали на
самом деле. Человек видит тот же список и правду о нём.

### Чего страж не делает

* Не судит, верен ли список. Он сравнивает слова, а не мастеров.
* Не трогает слова, которых в названиях услуг нет: «завтра», «недорого»,
  название города. Ими нельзя пообещать услугу.
* Не трогает ход без карточек: отказ обязан назвать услугу, о которой
  спросили (DRF-1283), и повтор слов человека там — требование.

### В какую сторону ошибается

Ложное срабатывание стоит тёплой фразы: человек получает сухой, но верный
показ. Пропуск стоит уверенной неправды о том, кто что делает. Поэтому любая
ошибка чтения каталога здесь означает «не срабатывать» только потому, что
иначе ход остался бы без ответа; всё остальное решается в пользу замены.
"""

from __future__ import annotations

import logging
import re
from collections.abc import Iterable

logger = logging.getLogger(__name__)

#: Короче этого — предлог или союз, а не слово услуги. Та же граница, что у
#: ``_SHORT_WORD_LEN`` поиска: ниже неё слово судят целиком, а не как основу.
_MIN_STEM_CHARS = 4

#: Длина основы — та же, которой поиск режет слово запроса
#: (``apps.marketplace.discovery._STEM_LEN``): «биоэнергетического» и
#: «Биоэнергетический» сходятся на «биоэне».
_STEM_CHARS = 6

_WORD_RE = re.compile(r"\w+", re.UNICODE)


def _said_stems(message_text: str) -> list[str]:
    """Основы слов реплики — ВСЕЙ, без среза по числу слов.

    Не ``query_stems`` поиска: тот оставляет последние пять содержательных
    слов, потому что ищет услугу в хвосте фразы. Этому стражу хвоста мало —
    он нужен как раз на длинной реплике, где услуга названа в начале
    («запишите на биоэнергетический массаж на завтра после шести вечера, если
    можно»), а модель унесла в поиск одно слово (ревью этой правки, 09.11).
    Числа основой не считаются: телефон услугу не называет.
    """
    words = _WORD_RE.findall((message_text or "").casefold())
    stems = (word[:_STEM_CHARS] for word in words if not word.isdigit())
    return [stem for stem in dict.fromkeys(stems) if len(stem) >= _MIN_STEM_CHARS]


def unverified_service_words(
    message_text: str,
    prose: str,
    *,
    searched: Iterable[str | None],
) -> list[str]:
    """Основы слов услуги, которые человек сказал, поиск пропустил, а текст повторил.

    Пустой список — текст модели можно оставить. ``searched`` — всё, по чему
    шёл поиск: услуга, город и прочие аргументы вызова ``show_masters``.

    Два бесплатных условия идут первыми, каталог читается последним и только
    когда слово уже прошло оба. На обычном ходе, где модель искала то, что
    сказано, чтения каталога нет вовсе. Не бросает.
    """
    said = _said_stems(message_text)
    if not said:
        return []
    searched_text = " ".join(str(part) for part in searched if part).casefold()
    # По началу основы, а не по ней целиком: «в Пензе» и город поиска «Пенза»
    # расходятся падежным окончанием, и считать такое слово пропущенным значит
    # читать каталог на каждом ходе, где назван город.
    unsearched = [stem for stem in said if stem[:_MIN_STEM_CHARS] not in searched_text]
    if not unsearched:
        return []
    prose_words = set(_WORD_RE.findall((prose or "").casefold()))
    repeated = [stem for stem in unsearched if any(word.startswith(stem) for word in prose_words)]
    if not repeated:
        return []
    try:
        from apps.marketplace.discovery import stems_used_in_service_names

        return stems_used_in_service_names(repeated)
    except Exception:  # noqa: BLE001 — страж не стоит хода
        logger.warning("orchestrator.cards_prose_guard.catalog_unavailable", exc_info=True)
        return []


__all__ = ["unverified_service_words"]
