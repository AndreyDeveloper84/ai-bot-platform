"""Разметка ответов, утверждающих выполненное действие (DRF-2341, шаг 3).

Бот говорит «записала», «удалила», «подтверждено» — и это утверждение о
СОСТОЯНИИ, а не о намерении. Три живых дефекта (DRF-2337, DRF-2338,
DRF-2344) — именно такие утверждения, за которыми ничего не стоит.

Признак ставит ветка, а не сторож угадывает по словам: «Запись отменена» и
«Не удалось отменить запись» отличаются одним словом, формулировки владелец
правит регулярно, и перепись по тексту ломалась бы от каждой правки, попутно
пропуская дефекты. Кто сделал — тот и объявляет.

### Два поля

* :attr:`DoneClaim.kind` — ЧТО утверждается (``water_logged``,
  ``booking_cancelled``): короткое имя действия, не текст;
* :attr:`DoneClaim.evidence` — ЧЕМ это доказано: **прочитанный результат**,
  а не факт вызова. Вызов может уйти в никуда — так и выглядел DRF-2337.

Доказательства бывают двух родов, и правило обязано знать оба (иначе треть
веток уедет в исключения, а исключение на треть списка — это отсутствие
правила):

* **внешнее действие** — идентификатор или статус ОТ каталога:
  ``ayla.log_id``, ``ayla.entry_id``, ``yclients.record_id``;
* **наше действие** — прочитанный результат нашей же записи: число
  изменённых строк, перечитанное состояние, возвращённый флаг. «Забудь
  всё», согласие и выключатели проактива меняют нашу базу, внешнего
  идентификатора там нет и быть не может.

Пустое ``evidence`` при непустом ``kind`` — это не ошибка разметки, а
честно названный дефект: ветка утверждает выполненное и доказать этого не
может (сегодня таких три, и все три — листы).

### Образцы в репозитории

Так выглядит правильно сделанное — читать раньше, чем писать новое:

* ``nutrition_anketa`` (ручной вес) — сверяет ``saved.weight_kg`` с тем, что
  просили, и при несовпадении отвечает аварийным текстом, а не «записала»;
* ``nutrition_anketa`` (отзыв параметров тела) — различает «удалено» и
  «не подтверждено» ОТДЕЛЬНЫМ ответом;
* ``persona.memory_commands`` («забудь всё») — три исхода вместо одного:
  началось, частично, удалено;
* ``global_onboarding`` (согласие) — проверяет, что журнал 152-ФЗ
  действительно записан, и при неудаче говорит другое.

### Носитель

Поле у нашего класса ответа там, где класс наш (:class:`SkillResult`,
:class:`MemoryCommandResult`), и ключ ``meta`` там, где поля нет. Читатель
ОДИН — :func:`done_claim`; ветки не разбирают носитель сами, иначе два
читателя разойдутся на первой же правке.
"""

from __future__ import annotations

from typing import Any, NamedTuple

#: Имена ключей — одни на оба носителя.
KIND_KEY = "claims_done"
EVIDENCE_KEY = "claims_done_evidence"


class DoneClaim(NamedTuple):
    """Что ветка утверждает выполненным и чем это доказано."""

    kind: str
    evidence: str


def done_claim(reply: Any) -> DoneClaim | None:
    """Разметка ответа, или ``None`` — «ветка ничего не утверждает».

    Читает оба носителя в одном порядке: сперва поле, потом ``meta``.
    Порядок важен только при расхождении, которого быть не должно; он
    объявлен здесь, чтобы не зависеть от того, кто спрашивает.
    """
    kind = _read(reply, KIND_KEY)
    if not kind:
        return None
    return DoneClaim(kind=kind, evidence=_read(reply, EVIDENCE_KEY))


def _read(reply: Any, key: str) -> str:
    value = getattr(reply, key, "") or ""
    if value:
        return str(value)
    meta = getattr(reply, "meta", None)
    if isinstance(meta, dict):
        return str(meta.get(key) or "")
    return ""


__all__ = ["EVIDENCE_KEY", "KIND_KEY", "DoneClaim", "done_claim"]
