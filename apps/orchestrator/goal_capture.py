"""Цель словами человека, сказанная в переписке (DRF-2283, решение владельца CD §73).

Владелец 22.09: «человек записывает свою цель как есть, Ayla хранит её как
его слова». Хранилище и путь записи уже были — ``goals.ClientGoal.goal_text``
в каталоге и ``POST /internal/me/goals/select/``; не было входа в чате: там
стояла только кнопка «Выбрать цель», ведущая в приложение. Этот модуль — вход,
и ничего кроме входа.

## Одно место записи, а не второе хранилище

Пишем той же ручкой, что и приложение, с ``source_channel="bot"``. Своей
таблицы, своего кэша и своей копии слов здесь нет: цель живёт в каталоге, и
канал её не дублирует (цель переживает смену канала — `ClientGoal`).

## Ворота здоровья — те же

Путь приложения прогоняет ``goal_text`` через ``health_gate.screen_goal_body``
(DRF-1763): сигнал здоровья останавливает запись и показывает человеку
вопросы. Чатовый вход, который писал бы мимо этих ворот, был бы обходом
безопасности через другую дверь. Поэтому здесь тот же вызов — и при остановке
мы **не пишем и не забираем ход**: его ведёт обычный путь, у которого есть и
тексты, и безопасность. Своих слов на этот случай не выдумываем.

## Чего этот модуль боится

«Хочу …» — обычная человеческая фраза, и большинство таких фраз целью не
являются. **Ложная цель хуже отсутствующей**: человек потом не может
объяснить, откуда она взялась, а стереть её — отдельный поход. Поэтому:

* отрицательные образцы **старше** положительных: «хочу записаться на стрижку
  к лету» — запись, хотя срок в ней есть;
* положительный образец обязан быть заявлением о результате или форме, а не
  желанием вообще;
* не уверены — не распознаём. Кнопка «Выбрать цель» никуда не делась, и
  приложение остаётся полным входом со своими подсказками и анкетой.

Ход этот модуль забирает только когда запись действительно прошла.
"""

from __future__ import annotations

import logging
import re
from typing import Any

logger = logging.getLogger(__name__)

#: Подтверждение после записи. **Черновик**: формулировка уходит владельцу
#: вместе с листом. Она не выдумана здесь — ровно так уже отвечает каталог на
#: свободный ввод цели (`goals/decision_context.py`), и второй формулировки для
#: одного и того же события заводить не стоит.
CONFIRMATION_DRAFT = "Записала: «{goal}»."

#: Не цель, что бы ни стояло рядом. Проверяется ПЕРВЫМ.
_NOT_A_GOAL = re.compile(
    r"\b("
    # еда
    r"есть|поесть|покушать|пицц\w*|кофе|чай|шаурм\w*|суши|бургер\w*|сладк\w*|"
    # запись и услуги
    r"запис\w*|к\s+мастеру|маникюр\w*|педикюр\w*|стрижк\w*|окрашив\w*|бров\w*|"
    r"ресниц\w*|массаж\w*|салон\w*|"
    # быт
    r"спать|домой|в\s+отпуск|пить|кури\w*"
    r")\b",
    re.IGNORECASE,
)

#: Заявление о результате или форме. Проверяется ВТОРЫМ и только если выше
#: ничего не совпало.
_GOAL = re.compile(
    r"("
    r"похуде\w*|худе\w*|"
    r"[-−–—]\s?\d+\s?(кг|килограмм\w*)|минус\s+\d+\s?(кг|килограмм\w*)|"
    r"сброс\w*\s+(вес|\d+)|набрать\s+(вес|массу)|"
    r"привести\s+себя\s+в\s+порядок|в\s+форму|подтянуть\w*|"
    r"\bмоя\s+цель\b|\bцель\s*[:—-]"
    r")",
    re.IGNORECASE,
)


def looks_like_goal_statement(text: str) -> bool:
    """Заявил ли человек этой фразой свою цель.

    ``False`` — значит «не знаем», а не «цели нет»: ход уходит дальше своим
    обычным путём, и человек может назвать цель кнопкой.
    """

    cleaned = (text or "").strip().replace("ё", "е")
    if not cleaned:
        return False
    if _NOT_A_GOAL.search(cleaned):
        return False
    return bool(_GOAL.search(cleaned))


def _screen(bot_user: Any, body: dict[str, Any]) -> tuple[Any, dict[str, Any]]:
    """Ворота здоровья приложения, вызванные из чата (DRF-1763)."""

    from apps.miniapp_api.health_gate import screen_goal_body

    return screen_goal_body(bot_user, body)


def capture_goal_from_chat(*, bot_user: Any, external_user_id: str, text: str) -> str | None:
    """Записать цель словами человека. Вернуть его же слова, если записали.

    ``None`` — ход не забираем: сигнал здоровья, отказ Ayla или пустые слова.
    Логи и события дословного текста не несут — только его наличие и длину
    (каталог держит то же правило на своей стороне: событие с ``has_text``).
    """

    goal_text = (text or "").strip()
    if not goal_text:
        return None

    body: dict[str, Any] = {"goal_text": goal_text, "source_channel": "bot"}
    stop, body = _screen(bot_user, body)
    if stop is not None:
        logger.info("orchestrator.goal_capture.health_stop chars=%d", len(goal_text))
        return None

    from apps.integrations.ayla import goals_client

    try:
        goals_client.post_goal_select(external_user_id=external_user_id, payload=body)
    except Exception:  # noqa: BLE001 — запись не прошла: ход ведёт обычный путь
        logger.warning("orchestrator.goal_capture.write_failed chars=%d", len(goal_text))
        return None

    logger.info("orchestrator.goal_capture.written chars=%d", len(goal_text))
    return goal_text
