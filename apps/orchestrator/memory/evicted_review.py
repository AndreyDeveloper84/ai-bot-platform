"""Просмотр сообщения, уходящего из короткой памяти (DRF-2511).

# Что это чинит — и чего НЕ чинит

**Чинит:** факт, сказанный в минуту, когда Ayla была недоступна, не
записывался **никогда**. `record_explicit_green_facts` возвращает ноль, когда
личность не разрешилась, и в его комментарии написано «the next turn
retries» — но следующий ход это **другой текст**, и повтора для того
сообщения не существует. Просмотр уходящего сообщения и есть тот повтор.

**НЕ чинит** «память обрывается на двадцати сообщениях». Разница
существенная, и её надо держать в голове, читая этот модуль: явные факты
снимаются **на входе**, на каждой реплике человека
(`apps/channels/max/handler.py` → `apps/orchestrator/memory_announce.py` →
`record_explicit_green_facts`). Что шаблонный извлекатель не узнаёт — то не
узнает и здесь: это тот же извлекатель. Общая задача «помнить сказанное
двадцать реплик назад» остаётся открытой.

# Провенанс — `explicit`, и это не недосмотр

Первая редакция листа требовала `source='inferred'`. Это было бы нарушением
названного решения: выводимое может становиться постоянной памятью **только**
через поток предложений (`MemoryProposal`, MDC §3.1/§3.2, AYLA-DEC-0024), а
писатель выводимого (`apps.identity.services.memory_inferred`) намеренно
усыплён и имеет ноль боевых вызывающих — ровно по этой причине. Сам
`MemoryProposal` в коде отсутствует.

Здесь провенанс остаётся `explicit`, потому что **слова человек произнёс.
Опоздание не меняет автора.** Мы не выводим ничего нового — мы дочитываем то,
что было сказано вслух, и что не записалось из-за нашего сбоя.

# Право на забвение: надгробия читаются здесь, а не в писателе

Дедуп писателя строится по **живым** фактам, а сторож забвения — на человеке
целиком. **Поштучное стирание не попадает ни туда, ни туда:** человек сказал
«забудь, что я веган», строка помечена удалённой, живой её нет — и запись
прошла бы снова.

На живом ходу это терпимо, потому что факт вернётся, только если человек
**повторит** его сам, а повторное заявление — его право. Здесь терпимого нет:
мост дочитывает старое сообщение, которого никто не повторял, и стёртое
вернулось бы **без нового заявления**, выглядя обычной записью. Это возврат
удалённых персональных данных.

Поэтому мост читает надгробия и передаёт писателю запрет
(``blocked_dedup_keys``). Запрет — свойство **этого вызова**, а не правило
хранилища: безусловный запрет внутри писателя запретил бы и повторное
заявление, то есть отнял бы у человека право сказать то же снова.

Заодно это закрывает вторую половину той же дыры: «забудь что я веган»
содержит подстроку «я веган», и обработчик поэтому не запускает извлечение на
ходе-команде (`handler.py`, `was_memory_command`). Но защита живёт **в
обработчике**, а не в данных: в короткой памяти реплика человека лежит без
пометки «это была команда» — на её дописывании `extras` не передаются вовсе,
я проверил. Надгробие снимает вопрос на уровне данных: чем бы ни был текст,
стёртое по просьбе не возвращается.

# Гейты не дублируются

Согласие, дедуп против живых фактов, forget-all и разрешение личности живут
**внутри** `record_explicit_green_facts`. Здесь их нет намеренно: вторая
копия гейта разошлась бы с первой молча, и именно на это мы натыкались в
`ApiError.details` — правило, воплощённое в двух местах, начинает
расходиться. Дедуп заодно и есть ответ на «а не запишем ли дважды»: факт,
уже сохранённый на входе, повторной записи не получает.

# Названный предел охвата

Просмотр стоит на **входе реплики человека** — там, где `bot_user` в руках и
где уже работает запись фактов. Вытеснение, вызванное дописыванием **ответа
ассистента**, этим просмотром не покрывается: при строгом чередовании ролей
это примерно половина случаев.

Закрывать это здесь значило бы либо вешать просмотр в десяти местах
`handler.py`, либо тянуть согласие и личность в модуль хранилища. Оба выхода
хуже названного предела. Полное покрытие — отдельный лист, и у него другая
форма: не «смотреть уходящее», а «повторять неудавшуюся запись», с пометкой
на самом сообщении.
"""

from __future__ import annotations

import logging
from typing import Any

logger = logging.getLogger(__name__)

#: Роль, чьи слова принадлежат человеку. Ответы ассистента не просматриваются:
#: извлекать «факты о человеке» из собственных реплик — это учить систему на
#: её же выдумках.
_HUMAN_ROLE = "user"

#: Причины удаления, которые означают «человек попросил забыть ЭТО».
#:
#: Из них и только из них следует запрет на возврат: остальные причины —
#: не воля человека. ``ttl_purge`` — срок хранения, ``minor_protection`` —
#: защита несовершеннолетнего, ``unknown_legacy`` — след переноса; вернуть
#: факт после них не значит вернуть стёртое по просьбе.
#:
#: ``withdrawal`` и ``forget_all`` здесь для полноты, хотя до них дело не
#: доходит: отзыв согласия ловит гейт согласия, «забудь всё» — надгробие на
#: человеке целиком. Перечислены, чтобы список читался как ответ на вопрос
#: «какие стирания — воля человека», а не как сегодняшний минимум.
_ERASURE_BY_REQUEST = frozenset(
    {
        "user_delete",
        "user_request_miniapp",
        "forget_all",
        "withdrawal",
    }
)


def _erased_by_request(bot_user: Any) -> frozenset[tuple[str, Any, Any]]:
    """Ключи фактов, которые человек просил забыть, — их возвращать нельзя.

    Дедуп писателя строится **по живым** строкам и надгробия не видит; сторож
    забвения стоит на человеке целиком (``upc.soft_deleted_at`` /
    ``forget_all_requested_at``), а поштучное стирание в него не попадает.

    На живом ходу это терпимо: факт вернётся только если человек **повторит**
    его сам, а повторное заявление — его право. Мост дочитывает СТАРОЕ
    сообщение, которого никто не повторял, поэтому здесь терпимого нет:
    стёртое вернулось бы без нового заявления, и выглядело бы это как обычная
    запись.
    """
    user_id = getattr(bot_user, "ayla_user_id", None)
    if not user_id:
        return frozenset()

    from apps.identity.models import MemoryEntry

    rows = MemoryEntry.objects.filter(
        user_id=user_id,
        sensitivity_zone=MemoryEntry.SENSITIVITY_GREEN,
        soft_deleted_at__isnull=False,
        deletion_reason__in=sorted(_ERASURE_BY_REQUEST),
    )
    keys: set[tuple[str, Any, Any]] = set()
    for row in rows:
        content = row.content or {}
        keys.add((row.kind, content.get("key"), content.get("value")))
    return frozenset(keys)


def review_evicted(bot_user: Any, dropped: list[dict[str, Any]]) -> int:
    """Просмотреть уходящие сообщения; вернуть число записанных фактов.

    ``dropped`` — то, что вернул :func:`apps.orchestrator.memory.short_term.append`.
    Пусто (обычный случай, окно не переполнено) — работы нет.

    Ход никогда не ломается: память не имеет права стоить человеку ответа, и
    это то же правило, по которому написан `memory_announce`.
    """
    if not dropped or bot_user is None:
        return 0

    from apps.orchestrator.memory.personal_context import record_explicit_green_facts

    blocked = _erased_by_request(bot_user)
    written = 0
    for message in dropped:
        if message.get("role") != _HUMAN_ROLE:
            continue
        text = str(message.get("content") or "")
        if not text:
            continue
        try:
            written += record_explicit_green_facts(bot_user, text, blocked_dedup_keys=blocked)
        except Exception:  # noqa: BLE001 — память не ломает ход
            logger.exception(
                "orchestrator.memory.evicted_review.failed bot_user=%s",
                getattr(bot_user, "id", None),
            )

    if written:
        # Строка нужна именно про этот путь: факт, пойманный здесь, — это
        # факт, который на входе записать НЕ удалось. Слитая с обычной
        # записью, она перестала бы отвечать на вопрос «а сбои вообще были?».
        logger.info(
            "orchestrator.memory.evicted_review.recovered bot_user=%s facts=%d — "
            "сказанное сохранено при уходе из короткой памяти; на входе запись "
            "не состоялась (DRF-2511)",
            getattr(bot_user, "id", None),
            written,
        )
    return written


__all__ = ["review_evicted"]
