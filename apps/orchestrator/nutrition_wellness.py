"""Nutrition Wellness Interpretation — допуск, который решает код (§48).

Решение владельца 07.09.2026, `docs/OPEN_DECISIONS.md` §48.

### Это не исключение из медицинской границы

Название выбрано владельцем намеренно, и оно не косметика. «Исключение из
медицинской границы» — формулировка, которая приглашает себя расширять:
каждый следующий случай будет проситься в то же исключение, и граница
станет решетом по одному разумному шагу за раз.

**Nutrition Wellness Interpretation — отдельная, положительно определённая
способность со своим гейтом.** Она у медицинской границы ничего не
отнимает и существует рядом с ней. Общая граница
(:mod:`apps.orchestrator.concierge`, раздел «Границы», Constitution Art. X
и Art. XII, Journey Spec Stage 8) **не ослабляется** — её текст этой
работой не тронут вовсе.

Практическое следствие, ради которого всё и названо так: расширить
способность нельзя, дописав ещё одно исключение в промпт. Придётся
расширить **гейт ниже**, а это видимое действие в коде, которое видно в
дифе и ловится ревью.

### Гейт детерминированный — и почему это обязательно

Допуск решает **не модель и не тема разговора**, а факт, проверяемый
кодом: относится ли ход к еде и не уходит ли он в медицину. Модель узнаёт
о разрешении только тем, что к ходу приложена картина питания; нет
блока — нет и разрешения.

Причина, по которой гейт обязан быть кодовым, а не текстовым: четыре
контрактных класса из §48 (ALLOW/ALLOW/BLOCK/BLOCK) иначе непроверяемы.
Утверждение «модель не должна отвечать на боль» проверяется только
прогоном модели, то есть недетерминированно; утверждение «на ход про боль
блок не прикладывается» проверяется тестом.

### Две службы одного предиката

:func:`turn_is_about_food` нужен был и без §48: сегодня
``build_nutrition_context_block`` зовётся на КАЖДОМ ходу консьержа, и это
бесплатно ровно до тех пор, пока флаг выключен. В минуту включения каждый
ход начнёт платить два похода в Ayla и ~200 токенов — включая «во сколько
вы работаете».

§48 дал ему вторую службу: он же ограничитель области действия
способности. Один предикат, две причины существовать, и обе настоящие.

### Почему veto-список свой, а не из safety/outbound

:mod:`apps.orchestrator.safety.outbound` смотрит в другую сторону — на то,
что говорит БОТ, и требует утвердительного глагола («примите», «у вас
аллергия»). Здесь смотрим на то, что сказал ЧЕЛОВЕК, и утвердительности не
требуем вовсе: «болит живот» — это вопрос, а не утверждение, и он обязан
закрыть допуск.

Списки поэтому не переиспользуются. Общий список, натянутый на оба
направления, ошибался бы в обе стороны сразу.

### Чего veto НЕ ловит, и это проверено тестом

Слова, которые звучат медицински, но принадлежат утверждённой таксономии
целей (`customer-wellness-goal-setting-ux.md` §3.1): **усталость**
(категория 1), **отёчность** (категория 4), **сон** (категория 5),
**кожа** и **волосы** (категории 3 и 6). Veto, который глушит собственные
цели продукта, закрывал бы способность ровно для тех, ради кого она есть.

### Юридический статус

§48 зафиксирован как **продуктово-архитектурное направление**. Перед
превращением в окончательный медицинский канон решение отдельно
прогоняется через Privacy / Safety / Legal. До тех пор ни этот модуль, ни
текст в промпте не считаются канонической медицинской нормой.
"""

from __future__ import annotations

import logging
import re
from typing import Any, Final

logger = logging.getLogger(__name__)

#: Имя способности — одно на код, логи и тесты, чтобы её нельзя было
#: расширить, назвав другим словом.
CAPABILITY: Final[str] = "nutrition_wellness_interpretation"

#: Ход про еду: прямые упоминания приёма пищи, рациона и дневника.
#: Границы слов обязательны — «ем» без них ловит «проблема» и «ремонт».
_FOOD_MARKERS: Final[tuple[re.Pattern[str], ...]] = tuple(
    re.compile(p)
    for p in (
        r"(?i)\bпитани\w*",
        r"(?i)\bрацион\w*",
        r"(?i)\b(еда|еду|еды|еде|едой)\b",
        r"(?i)\b(ем|ешь|ест|едим|едят)\b",
        r"(?i)\b(ел|ела|ели|поел\w*|съел\w*|наел\w*)\b",
        # «съесть», «поесть», «покушать» — вопрос о будущей еде. Голое
        # «есть» сюда НЕ входит: это же слово значит «имеется», и на нём
        # предикат ловил бы «есть ли у вас окошко в четверг».
        r"(?i)\b(съесть|поесть|покушать|кушать)\b",
        r"(?i)\b(завтрак\w*|обед\w*|ужин\w*|перекус\w*)\b",
        r"(?i)\bдневник\w*\s+питани\w*",
        r"(?i)\b(белк\w*|углевод\w*|жиры|клетчатк\w*)\b",
        r"(?i)\bкалори\w*",
        r"(?i)\bпорци\w*",
        # «диета» стоит и здесь, и в veto ниже — намеренно. Вопрос про
        # диету ЭТО вопрос про еду; закрывается он veto (§2.1), а не
        # тем, что мы его не разглядели. Разница видна в логе: «не про
        # еду» и «заблокировано» — разные исходы с разными причинами.
        r"(?i)\bдиет\w*",
    )
)

#: Медицинское veto: тема ушла в симптом, боль, диагноз, лечение или вес.
#: Утвердительности не требуем — вопрос закрывает допуск так же, как
#: утверждение.
_MEDICAL_VETO: Final[tuple[re.Pattern[str], ...]] = tuple(
    re.compile(p)
    for p in (
        # симптом и боль
        r"(?i)\b(болит|болел\w*|боль|боли|больно)\b",
        r"(?i)\bсимптом\w*",
        r"(?i)\b(тошн\w*|рвот\w*|изжог\w*|вздути\w*|диаре\w*|запор\w*)\b",
        r"(?i)\b(температур\w*|давлени\w*|пульс)\b",
        # диагноз и состояние
        r"(?i)\bдиагноз\w*",
        r"(?i)\b(гастрит\w*|язв\w*|диабет\w*|аллерги\w*|непереносим\w*)\b",
        r"(?i)\b(щитовидк\w*|гормон\w*|анемi\w*|анеми\w*)\b",
        r"(?i)\bбеременн\w*",
        # лечение и назначения
        r"(?i)\b(лечени\w*|лечить|вылечить|терапи\w*)\b",
        r"(?i)\b(лекарств\w*|таблетк\w*|препарат\w*|антибиотик\w*)\b",
        r"(?i)\b(добавк\w*|бад\b|витамин\w*)",
        r"(?i)\b(врач\w*|доктор\w*|анализ\w*|обследовани\w*)\b",
        # вес и мишени — §2.1, запрещены как цель, значит и как повод
        r"(?i)\b(похуде\w*|худе\w*|похудет\w*|сброс\w*\s+вес\w*)\b",
        r"(?i)\b(вес|веса|весе|килограмм\w*|\d+\s*кг)\b",
        r"(?i)\bдиет\w*",
    )
)


def turn_is_about_food(text: Any) -> bool:
    """Относится ли ход к еде. Дешёвый предикат, никогда не бросает.

    Положительная половина гейта и одновременно ограничитель стоимости:
    без него включённый флаг платит два похода в Ayla за каждый ход бота.

    Переиспользует существующие распознаватели, а не заводит третий:
    :func:`apps.skills.food_clarify.hints.looks_like_food_drink` (короткая
    запись блюда) и :func:`apps.orchestrator.personal_surface.
    looks_like_diary_request` (просьба показать дневник) — плюс список
    выше для свободного текста, которого не покрывает ни один из них.
    """

    if not isinstance(text, str):
        return False
    stripped = text.strip()
    if not stripped:
        return False

    if any(pattern.search(stripped) for pattern in _FOOD_MARKERS):
        return True

    try:
        from apps.skills.food_clarify.hints import looks_like_food_drink

        if looks_like_food_drink(stripped):
            return True
    except Exception:  # noqa: BLE001 — предикат не смеет ронять ход
        logger.exception("orchestrator.nutrition_wellness.food_drink_probe_failed")

    try:
        from apps.orchestrator.personal_surface import looks_like_diary_request

        if looks_like_diary_request(stripped) is not None:
            return True
    except Exception:  # noqa: BLE001 — то же самое
        logger.exception("orchestrator.nutrition_wellness.diary_probe_failed")

    return False


def medical_veto(text: Any) -> bool:
    """Ушла ли тема в медицину. ``True`` — допуска нет.

    Отдельная функция, а не ветка внутри :func:`interpretation_eligible`,
    потому что это та половина гейта, которую будут пытаться ослабить.
    Пусть её ослабление будет отдельной строкой дифа.
    """

    if not isinstance(text, str):
        return False
    return any(pattern.search(text) for pattern in _MEDICAL_VETO)


def goal_is_medical(goal: Any) -> bool:
    """Медицинская ли цель человека. ``True`` — допуска нет.

    Курируемые ключи безопасны по построению: таксономия §3.1 медицинских
    целей не содержит, а §3.3 разворачивает их на входе. Опасность — в
    свободной формулировке (`category='custom'`, у нас ``key == ""``):
    туда человек мог написать что угодно, и §3.3 ловит не всё.

    ``None`` (цели нет) медицинской не считается: отсутствие цели — это
    отсутствие цели, а не подозрение.
    """

    if goal is None:
        return False
    if getattr(goal, "key", ""):
        return False
    return medical_veto(getattr(goal, "text", "") or "")


def interpretation_eligible(text: Any, *, goal: Any = None) -> bool:
    """Допущен ли этот ход к Nutrition Wellness Interpretation (§48).

    Четыре контрактных класса владельца читаются отсюда напрямую:

    ==================================  ========
    ход                                 итог
    ==================================  ========
    питание + цель восстановления       ALLOW
    питание + бьюти/wellness-цель       ALLOW
    питание + симптом или боль          BLOCK
    питание + медицинская цель          BLOCK
    ==================================  ========

    Порядок намеренный: veto проверяется ПОСЛЕ положительной половины, но
    его результат сильнее. Ход, не относящийся к еде, не «заблокирован» —
    он просто не про это, и разница видна в логе.
    """

    if not turn_is_about_food(text):
        return False
    if medical_veto(text):
        logger.info("orchestrator.nutrition_wellness.blocked reason=medical_topic")
        return False
    if goal_is_medical(goal):
        logger.info("orchestrator.nutrition_wellness.blocked reason=medical_goal")
        return False
    return True


__all__ = [
    "CAPABILITY",
    "goal_is_medical",
    "interpretation_eligible",
    "medical_veto",
    "turn_is_about_food",
]
