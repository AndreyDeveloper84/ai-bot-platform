"""Копии текста без знаков для входного гейта (K19-Б, DRF-2922).

Многословные шаблоны ``pre_check`` ждут между словами пробел: знак внутри
фразы («Не хочу, жить.», «Хочу... умереть») совпадение снимает. Поэтому гейт
смотрит не только на текст как есть, но и на его копию без знаков:

* :func:`without_marks` — без всех знаков между словами. Её получает гейт
  ГОЛОСА (``voice_turn.strip_for_gate``): распознавание ставит знаки всегда, а
  гипербола «Умираю, хочу кофе.» в расшифровке не должна давать кризис.
* :func:`without_inner_marks` — без знаков ВНУТРИ предложения (запятые, тире,
  двоеточия, кавычки, скобки, многоточие); одиночные «.», «!», «?» остаются.
  Её смотрит гейт для набранного текста (:func:`gate.evaluate_inbound`):
  копия без концов предложений склеивала бы соседние предложения — «Начинайте
  без меня. Лучше я подъеду к 16:00.» читалось бы как «без меня лучше», а
  мастер в своём ассистенте получал бы телефон доверия.

Апостроф и дефис внутри слова сохраняются в обеих копиях («don't»,
«self-harm», «как-то»): иначе английские шаблоны и слова с дефисом перестают
совпадать.
"""

from __future__ import annotations

import re

#: Все знаки между словами — копия голоса (K19-Б). Апостроф и дефис внутри
#: слова остаются: «don't want to live» и «self-harm» — шаблоны гейта, и без
#: апострофа кризис по-английски терялся (проба DRF-2423 это поймала).
_ALL_MARKS = re.compile(r"[,.!?;:…\"«»“”„()\[\]{}<>—–]|(?<!\w)['\-’]|['\-’](?!\w)")
#: Знаки внутри предложения: всё, кроме одиночных «.», «!», «?». Многоточие —
#: внутри предложения («Хочу... умереть»).
_INNER_MARKS = re.compile(r"[,;:\"«»“”„()\[\]{}<>—–]|\.{2,}|…|(?<!\w)['\-’]|['\-’](?!\w)")
_WS = re.compile(r"\s+")

#: Меняется вместе с правилом копии: входит в ``assessment.policy_version()``,
#: чтобы одна и та же версия политики не означала разное поведение гейта.
NORMALIZATION_VERSION = "inner-marks-v1"


def without_marks(text: str) -> str:
    """Копия без всех знаков между словами (гейт голоса)."""
    return _WS.sub(" ", _ALL_MARKS.sub(" ", text)).strip()


def without_inner_marks(text: str) -> str:
    """Копия без знаков внутри предложения; «.», «!», «?» остаются (гейт набранного текста)."""
    return _WS.sub(" ", _INNER_MARKS.sub(" ", text)).strip()
