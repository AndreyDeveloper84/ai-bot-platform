_NEW_ENTRIES = {
    marker: next(p for p in _DEFAULT_PATTERNS[HANDOFF.value] if marker in p)
    for marker in (r"взять\s+и\s+", r"вечным\s+сном", "предсмертн")
}


class TestCost:
    """Стем внутри чужого слова раньше и ошибался, и перебирал квадратично."""

    @pytest.mark.parametrize("marker", list(_NEW_ENTRIES))
    @pytest.mark.parametrize(
        "unit",
        [
            "нае",
            "брос",
            "прыгн",
            "таблетк",
            "хочу ",
            "не ",
            "уснуть и ",
            "меня не ",
            "хочухочу",
            # Ревью кода: «((так|больше)\s+)+жить не могу» и «хотел…бы» без
            # ``\b`` давали секунды на 20 000 знаков.
            "так ",
            "больше ",
            "так больше ",
            "хотел",
            "вот бы ",
            "чтобы меня в ",
        ],
    )
    def test_a_hostile_long_text_costs_milliseconds(self, marker: str, unit: str) -> None:
        rule = re.compile(_NEW_ENTRIES[marker])
        text = (unit * (20000 // len(unit) + 1))[:20000]
        best = float("inf")
        for _ in range(3):
            started = time.perf_counter()
            rule.search(text)
            best = min(best, time.perf_counter() - started)
        # Замер ревью — до 63 мс на 20 000 знаков; потолок с запасом на
        # загруженную машину. Квадратичный шаблон давал здесь секунды.
        assert best < 0.5, f"{unit!r}: {best:.2f} с на 20 000 знаков"
