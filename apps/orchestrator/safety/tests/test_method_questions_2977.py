def test_spoken_variants_of_the_crisis_set_are_not_weaker_after_strip() -> None:
    weaker: list[str] = []
    checked = 0
    for phrase in CRISIS:
        baseline = _PRIORITY[pre_check(phrase).verdict.value]
        for variant in spoken_variants(phrase):
            checked += 1
            if _PRIORITY[pre_check(strip_for_gate(variant)).verdict.value] < baseline:
                weaker.append(variant)
    assert checked > 500
    assert weaker == []  # empty-assert-ok: checked counts the variants above


# Две записи этой правки — по строке, которая есть только в каждой из них.
_NEW_ENTRIES = {
    marker: next(p for p in _DEFAULT_PATTERNS[HANDOFF.value] if marker in p)
    for marker in ("способ", "памереть")
}


class TestCost:
    """Стем без ``\\b`` («окн», «мост», «крыш») давал секунды на длинном тексте."""

    @pytest.mark.parametrize("marker", list(_NEW_ENTRIES))
    @pytest.mark.parametrize(
        "unit",
        [
            "окн",
            "окно ",
            "мост",
            "крыш",
            "крыша ",
            "чтобы не ",
            "как не ",
            "х ",
            "а ",
            "таблет",
            "хочу ",
            "себя ",
            "выпью много ",
            "если я умру ",
        ],
    )
    def test_a_hostile_long_text_costs_milliseconds(self, marker: str, unit: str) -> None:
        rule = re.compile(_NEW_ENTRIES[marker])
        text = (unit * (20000 // len(unit) + 1))[:20000]
        best = float("inf")
        for _ in range(3):
            started = time.perf_counter()
            rule.search(text)
            best = min(best, time.perf_counter() - started)
        # Замер ревью — до 65 мс на 20 000 знаков; потолок с запасом.
        assert best < 0.5, f"{unit!r}: {best:.2f} с на 20 000 знаков"
