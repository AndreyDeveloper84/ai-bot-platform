@pytest.mark.parametrize("text", TICKET)
def test_a_mark_inside_the_phrase_no_longer_hides_the_crisis(text: str) -> None:
    # Положительная пара: текст как есть шаблон не берёт — копия берёт.
    assert pre_check(text).verdict.value == "allow"
    outcome = evaluate_inbound(text)
    assert outcome.verdict == "handoff"
    assert outcome.allowed is False
    assert outcome.normalized is True


@pytest.mark.parametrize("text", SEVERAL_SENTENCES)
def test_sentences_are_not_glued_together(text: str) -> None:
    # Набор действительно из нескольких предложений, и копия без ВСЕХ знаков
    # (как у голоса) склеила бы их — именно от этого держат концы предложений.
    assert any(mark in text for mark in ".!?")
    assert without_marks(text) != without_inner_marks(text)
    assert evaluate_inbound(text).verdict == "allow"


@pytest.mark.parametrize("text", THEATRICAL_DOTS)
@pytest.mark.xfail(
    strict=True,
    reason=(
        "DRF-2922: копия набранного текста держит концы предложений — иначе склейка "
        "даёт ложные тревоги; «Хочу. Умереть.» проходит, как и до правки"
    ),
)
def test_theatrical_full_stops_in_typed_text(text: str) -> None:
    assert evaluate_inbound(text).verdict == "handoff"


def test_the_winning_pass_is_reported() -> None:
    raw = evaluate_inbound("хочу умереть")
    assert raw.verdict == "handoff"
    assert raw.normalized is False
    assert raw.result is not None and raw.result.matched_patterns == raw.matched_patterns

    copy = evaluate_inbound("хочу, умереть")
    assert copy.verdict == "handoff"
    assert copy.normalized is True
    assert copy.result is not None
    assert copy.matched_patterns == list(copy.result.matched_patterns)
    assert copy.matched_patterns == raw.matched_patterns


def test_voice_gets_one_pass_exactly_as_before(monkeypatch) -> None:
    calls: list[str] = []
    real = pre_check

    def counting(text, *args, **kwargs):
        calls.append(text)
        return real(text, *args, **kwargs)

    monkeypatch.setattr("apps.orchestrator.safety.gate.pre_check", counting)
    transcript = "Умираю, хочу кофе. Запишите на пятницу!"
    copy = strip_for_gate(transcript)
    outcome = evaluate_inbound(copy)

    assert calls == [copy]
    assert outcome.normalized is False
    assert without_inner_marks(copy) == copy


def test_the_voice_copy_is_the_same_rule_as_before() -> None:
    for text in (
        "Умираю, хочу кофе.",
        "don't want to live",
        "self-harm, честно",
        "Хочу... как-то так!",
    ):
        assert strip_for_gate(text) == without_marks(text)
    assert strip_for_gate("don't want to live") == "don't want to live"
    assert without_inner_marks("Хочу... умереть. Правда!") == "Хочу умереть. Правда!"


def test_the_policy_version_names_the_copy_rule(monkeypatch) -> None:
    assessment.reset_policy_version_cache()
    before = assessment.policy_version()
    monkeypatch.setattr(normalize, "NORMALIZATION_VERSION", "other-rule")
    assessment.reset_policy_version_cache()
    after = assessment.policy_version()
    assert before.startswith("pre_check-")
    assert after != before
    assessment.reset_policy_version_cache()
