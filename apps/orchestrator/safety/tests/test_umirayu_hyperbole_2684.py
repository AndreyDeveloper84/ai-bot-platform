class TestDyingOfTheBody:
    """«умираю от …» — тело, не отчаяние: 103 / 112 (DRF-2000)."""

    @pytest.mark.parametrize(
        "text",
        [
            "умираю от боли в груди",
            "умираю, от боли в груди",
            "умираю — от боли",
            "умираю: от боли в груди",
            "больше не могу, умираю от боли в груди",
        ],
    )
    def test_a_comma_does_not_send_the_body_to_the_helpline(self, text: str) -> None:
        assert _both(text) == (MEDICAL, MEDICAL)

    @pytest.mark.parametrize(
        "text",
        [
            "Умираю. От вас никакой помощи.",
            "Я умираю. От меня все отвернулись.",
            "Умираю! От меня ушёл муж.",
        ],
    )
    def test_of_in_the_next_sentence_keeps_the_typed_text_with_the_crisis_rule(
        self, text: str
    ) -> None:
        # Набранный текст различает «умираю, от боли» и «Умираю. От меня…». Копия
        # для голоса конец предложения теряет и даёт 103 / 112, как и до правки:
        # это тоже остановка, расхождение известное и не новое.
        assert pre_check(text).verdict == HANDOFF
        assert pre_check(strip_for_gate(text)).verdict == MEDICAL


# Всё, что снимает ``strip_for_gate``, плюс перенос строки и дефис без пробелов.
_SEPARATORS = [
    " ", ", ", ",", ". ", "! ", "? ", "… ", "... ", " — ", "—", " - ", "-", ": ", "; ",
    "\n", ".\n", " ' ", "' ", "’ ", ' "', " «", ") ", " (", "\t", "  ",
]  # fmt: skip
_TAILS = {
    "кофе": ALLOW,
    "к вам на массаж": ALLOW,
    "спать и не проснуться": HANDOFF,
    "уйти из жизни": HANDOFF,
    "в кино": HANDOFF,
    "": HANDOFF,
}


@pytest.mark.parametrize("first", _SEPARATORS)
def test_marks_between_the_words_do_not_change_the_verdict(first: str) -> None:
    seen = 0
    for second in _SEPARATORS:
        for tail, expected in _TAILS.items():
            for text in (
                f"Умираю{first}хочу{second}{tail}",
                f"умираю{first}как{second}хочу {tail}",
            ):
                assert _both(text) == (expected, expected), repr(text)
                seen += 1
    assert seen == len(_SEPARATORS) * len(_TAILS) * 2


