class TestCost:
    """Шаблон длинный: текст без «умираю» должен уходить из него за один проход."""

    def test_a_text_without_the_word_leaves_at_the_gate(self) -> None:
        rule = re.compile(_UMIRAYU_CRISIS)
        text = "Запишите меня пожалуйста на маникюр на пятницу после шести вечера. " * 60
        assert len(text) >= 4000
        started = time.perf_counter()
        for _ in range(20):
            assert rule.search(text) is None
        assert (time.perf_counter() - started) / 20 < 0.01

    @pytest.mark.parametrize(
        "unit",
        ["умираю, как, хочу к вам ", "умираю хочу а б кофе не могу ", "меня ааа ббб не умираю "],
    )
    def test_a_hostile_long_text_stays_linear(self, unit: str) -> None:
        rule = re.compile(_UMIRAYU_CRISIS)
        short, long_ = unit * 40, unit * 160
        assert len(long_) >= 3500

        def cost(text: str) -> float:
            started = time.perf_counter()
            list(rule.finditer(text))
            return time.perf_counter() - started

        # Вчетверо длиннее — не в шестнадцать раз дольше; и в абсолюте далеко от
        # бюджета хода (потребитель очереди один на всех).
        assert cost(long_) < max(cost(short), 0.001) * 12
        assert cost(long_) < 1.0
