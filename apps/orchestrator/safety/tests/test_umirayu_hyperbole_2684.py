class TestCost:
    """Шаблон длинный: без «умираю» текст уходит из него за проход, с ним — рост линейный."""

    @staticmethod
    def _best_of_three(rule: re.Pattern[str], text: str) -> float:
        best = float("inf")
        for _ in range(3):
            started = time.perf_counter()
            rule.search(text)
            best = min(best, time.perf_counter() - started)
        return best

    def test_a_text_without_the_word_leaves_at_the_gate(self) -> None:
        rule = re.compile(_UMIRAYU_CRISIS)
        text = "Запишите меня пожалуйста на маникюр на пятницу после шести вечера. " * 60
        assert len(text) >= 4000
        assert rule.search(text) is None
        assert self._best_of_three(rule, text) < 0.01

    @pytest.mark.parametrize(
        "text",
        [
            # Ревью кода: неограниченный хвост слова под окном — 6,5 с на 4 000 знаков.
            "умираю хочу кофе. "
            + "запишите меня на пятницу после шести вечера, " * 5
            + "смысл" * 760,
            "исчез" * 740 + " " + "запишите меня на пятницу, " * 9 + "умираю хочу кофе.",
            "умираю хочу кофе. " + "с жизн" * 660,
            # Повторённое слово: каждое вхождение не взвешивается отдельно.
            "умираю хочу кофе " * 235,
            "умираю, как, хочу к вам " * 166,
            # Худшее, что нашлось без совпадения: одна гипербола и длинный бытовой текст.
            "хочу записаться на маникюр завтра в десять утра, " * 80 + "умираю хочу кофе",
            "умираю хочу кофе " + "а потом ещё на массаж и на маникюр " * 114,
            "меня ааа ббб не " * 249 + " умираю хочу кофе",
        ],
    )
    def test_a_hostile_text_of_message_length_costs_milliseconds(self, text: str) -> None:
        # Потолок с запасом на загруженную машину: замер — до 15 мс на 4 000 знаков.
        assert 3900 <= len(text) <= 4100
        assert self._best_of_three(re.compile(_UMIRAYU_CRISIS), text) < 0.5
