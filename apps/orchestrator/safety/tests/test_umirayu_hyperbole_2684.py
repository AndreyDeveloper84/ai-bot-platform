"""DRF-2684 (K19-А) — «умираю (как) хочу …»: гипербола или беда.

Правило в ``pre_check.py`` узкое. «Умираю» НЕ тревога, только если сразу:

* после «(как) хочу» стоит бытовой предмет желания (еда, сон, отдых, услуга,
  «к вам»), а между ними — не больше трёх слов из закрытого списка;
* рядом нет слов о смерти, конце, прощании, безысходности;
* сообщение по форме — фигура речи: одно «умираю», до него только
  приветствие, после его предложения — только вопросы.

До правки исключением было «хочу + что угодно» через пробел. Отсюда две беды
сразу: «Умираю, хочу кофе.» с запятой поднимало ложную тревогу, а «умираю
хочу просто умереть» без запятой проходило мимо гейта — и у голоса тоже,
потому что гейту голоса отдаётся копия без знаков (``strip_for_gate``, K19-Б).

Каждая фраза проверяется дважды — как набрана и как её увидит гейт голоса.

### Чего правило не обещает (и где это закреплено)

Списки слов беды подгонялись под наборы ниже — на них они держат всё. Проверка
на свежих фразах, написанных после заморозки списков (ревью кода, 64 фразы
«бытовое желание + беда своими словами»): до правил формы списки удержали 9.
С правилами формы и дополненными списками набранный текст держит 57 из 64,
копия для голоса — 37. Оставшееся названо поимённо строгими ``xfail``:

* ``UNKNOWN_WORDS_IN_ONE_SENTENCE`` — беда незнакомыми словами в ОДНОМ
  предложении с бытовым желанием проходит. На dev набранный текст с запятой
  ловил такое случайно (тревогу давала сама запятая) — это цена правки;
* ``*_SEEN_ONLY_BY_SHAPE`` — правило формы читает концы предложений, а в копии
  для голоса их нет. У голоса эти фразы проходили и до правки (DRF-2922).
"""

