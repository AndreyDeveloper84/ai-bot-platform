"""DRF-2684 (K19-А) — «умираю (как) хочу …»: гипербола или беда.

Правило в ``pre_check.py`` устроено как белый список. Тревога снимается, только
если после «(как) хочу» в пределах двух слов стоит бытовой предмет желания
(еда, сон, отдых, услуга, «к вам») и рядом нет слов о смерти, конце, прощании,
безысходности. Всё остальное со словом «умираю» — кризисный ответ.

До правки исключением было «хочу + что угодно» через один пробел. Отсюда две
беды сразу: «Умираю, хочу кофе.» с запятой поднимало ложную тревогу, а «умираю
хочу просто умереть» без запятой проходило мимо гейта — и у голоса тоже, потому
что гейту голоса отдаётся копия без знаков (``strip_for_gate``, K19-Б).

Наборы фраз ниже — те, на которых правило мерили при ревью плана: кризисные
хвосты, отложенный набор (писался после заморозки списков), беда вокруг
бытового хвоста и бытовые двойники. Каждая фраза проверяется дважды — как
набрана и как её увидит гейт голоса. Вердикты обязаны совпасть.
"""

