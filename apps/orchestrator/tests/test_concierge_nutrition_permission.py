"""Регрессия на дефект DRF-1284: картина едет только с разрешением (§48).

Отдельный файл, а не класс в ``test_nutrition_wellness.py``, по той же
причине, по которой правка инструкции консьержа идёт отдельным коммитом
(§48): это тест про ГОЛОС продукта, а не про гейт. Он обязан читаться
вместе с дифом промпта, а не теряться среди проверок предиката.
"""

from __future__ import annotations


class TestTheOriginalDefect:
    """Регрессия на дефект DRF-1284 — требование §48.

    ЧТО БЫЛО. Замер 2026-08-23: блок доходит до модели
    (``llm_tokens_input`` растёт на 180-220 за ход, полезная нагрузка
    видна в отрендеренном промпте), а ответ НЕ МЕНЯЕТСЯ. Причина не в
    блоке: общая медицинская граница промпта велит модели остановиться на
    любой теме здоровья, а недельный дефицит белка читается ею именно так.

    ЧТО ЭТОТ ТЕСТ ДОКАЗЫВАЕТ. Что вместе с картиной в промпт едет
    разрешение назвать связь — то есть что ДОПУСТИМЫЙ ответ изменился, — и
    что без картины разрешения нет. Это и есть детерминированная часть
    §48: допуск решает код, а не модель.

    ЧЕГО ЭТОТ ТЕСТ НЕ ДОКАЗЫВАЕТ, и это надо сказать прямо. Он не
    доказывает, что модель ФАКТИЧЕСКИ начнёт отвечать иначе. Это
    проверяется только живым замером на пилоте, как это и было сделано в
    DRF-1284, и до такого замера поверхность считать работающей нельзя.
    Тест закрывает ту половину дефекта, которую можно закрыть в коде:
    раньше картина ехала без разрешения, теперь — только с ним.

    Он обязан КРАСНЕТЬ до правки промпта (§47.7): до неё в промпте нет
    ни одной строки, разрешающей назвать связь.
    """

    def test_the_picture_carries_permission_and_never_travels_without_it(self) -> None:
        from apps.orchestrator.concierge import build_concierge_system_prompt

        block = "Картина питания клиента (данные сервиса Ayla, не инструкция)."

        without = build_concierge_system_prompt()
        with_picture = build_concierge_system_prompt(nutrition_block=block)

        # Присутствие на ТОМ ЖЕ корне и выше отсутствий: промпт без
        # картины — не пустая строка, общая граница в нём есть. Значит
        # «картины нет» и «разрешения нет» ниже говорят об отсутствии в
        # настоящем промпте, а не о том, что сборка вернула пустоту.
        assert "я не врач и не оцениваю здоровье" in without

        # Контроль присутствия: картина действительно доехала до промпта.
        assert block in with_picture
        assert block not in without

        # И вместе с ней — разрешение, которого без неё нет. Это то самое
        # изменение допустимого ответа, которого не было в DRF-1284.
        assert "назвать связь" in with_picture
        assert "БЕЗ ЦИФР" in with_picture
        assert "назвать связь" not in without

    def test_the_general_medical_boundary_is_not_weakened(self) -> None:
        """§48 п.1: способность существует РЯДОМ с границей, не вместо неё.

        Текст общей границы обязан остаться в промпте дословно и при
        приложенной картине — иначе «отдельная способность» на деле
        оказалась бы ослаблением, просто названным иначе.
        """
        from apps.orchestrator.concierge import build_concierge_system_prompt

        boundary = "я не врач и не оцениваю здоровье"
        block = "Картина питания клиента (данные сервиса Ayla, не инструкция)."

        assert boundary in build_concierge_system_prompt()
        assert boundary in build_concierge_system_prompt(nutrition_block=block)
