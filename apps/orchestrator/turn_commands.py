"""DRF-2981 — реплика-команда не бывает ни ответом на вопрос памяти, ни продолжением записи.

Замер на dev ``d52b1c37`` (``try_handle_answer`` с висящим вопросом памяти):
«отмени запись на завтра», «покажи мои записи», «а сколько стоит маникюр?»
сохранялись РАЙОНОМ с ответом «Записала, спасибо»; «отмени запись на вечер» —
удобным временем; «удали запись к мастеру за 2000» — бюджетом 2000 и
рейтингом 2.0; «сотри бронь на субботу» — занятым днём. Посреди записи
«отмени запись на завтра» продолжала СОЗДАНИЕ записи на завтра.

Словарь — закрытые формы глаголов, без открытых корней: «отмен» и «удал»
корнями ловят «отменный район» и «работаю удалённо» (так ошибается
``apps.skills.booking.lookup._CANCEL_SIGNAL`` — поэтому он здесь не годится).

Отрицание — не команда. «Не забудь, я веган» команда памяти сознательно
отдаёт дальше (``memory_commands._NEGATED_FORGET_RE``, DRF-2887), и именно
такие реплики доходят до вопроса памяти — как настоящий ответ.

Чистый модуль: без Django, только текст.
"""

from __future__ import annotations

import re

#: «не отменяй», «не забудь» — левый контекст из одного слова.
_NOT_NEGATED = r"(?<!\bне )"
_W, _E = r"(?<!\w)", r"(?!\w)"

#: Остановить: отменить, удалить, стереть, забыть.
_STOP = (
    r"отмен(?:и|ите|ить|яй|яйте|им|имте|ю|яю|а|у|ы)"
    r"|удал(?:и|ите|ить|яй|яйте|им|имте|яю)"
    r"|сотри(?:те)?|стереть|стира(?:й|йте)"
    r"|забудь(?:те)?|забыть"
)
#: Снять и отказаться — команда только рядом с записью: «сними» и «убери»
#: бывают о чём угодно.
_TAKE_OFF = (
    r"сним(?:и|ите)|снять|убер(?:и|ите)|откаж(?:усь|ись|итесь)|отказываюсь"
    r"|аннулир(?:уй|уйте|овать)"
)
#: Другое намерение: перенести, записаться, найти. «Запиши» — только с тем,
#: кого и куда («запиши меня», «запиши на субботу»): «запишите: Ленинский» —
#: ответ на вопрос о районе.
_OTHER = (
    r"перенес(?:и|ите|ти|ем|емте)|сдвин(?:ь|ьте|уть)"
    r"|запиши(?:те)?\s+(?:меня|нас|на|к|ко)|записаться|запишусь"
    r"|забронир(?:уй|уйте|овать)|найди(?:те)?|подбери(?:те)?"
)
#: Запись к мастеру — те же формы, что ``memory_commands._FOREIGN_NOUN``.
_BOOKING_NOUN = (
    r"запис(?:ь|и|ей|ью|ям|ями|ях)"
    r"|брон(?:ь|и|ей|ью|ям|ями|ях)"
    r"|бронирован(?:ие|ия|ий|ию|иям|иями|иях)"
    # DRF-2982 — «отмени визит на завтра» посреди записи продолжала её создание.
    r"|визит(?:а|у|ом|е|ы|ов|ам|ами|ах)?"
)

_STOP_RE = re.compile(_W + _NOT_NEGATED + r"(?:" + _STOP + r")" + _E)
_TAKE_OFF_RE = re.compile(_W + _NOT_NEGATED + r"(?:" + _TAKE_OFF + r")" + _E)
_OTHER_RE = re.compile(_W + _NOT_NEGATED + r"(?:" + _OTHER + r")" + _E)
_BOOKING_NOUN_RE = re.compile(_W + r"(?:" + _BOOKING_NOUN + r")" + _E)


def _normalise(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").lower().replace("ё", "е")).strip()


def mentions_booking(text: str) -> bool:
    """В реплике есть запись к мастеру или бронь."""

    return _BOOKING_NOUN_RE.search(_normalise(text)) is not None


def names_a_booking_stop(text: str) -> bool:
    """«Отмени / удали / сотри / сними запись …» — остановить запись.

    Глагол без записи — не стоп: «нет, отмени, лучше на послезавтра» посреди
    записи — это исправление дня, и запись продолжается.
    """

    norm = _normalise(text)
    if _BOOKING_NOUN_RE.search(norm) is None:
        return False
    return _STOP_RE.search(norm) is not None or _TAKE_OFF_RE.search(norm) is not None


def names_a_command(text: str) -> bool:
    """Реплика — команда (остановить, перенести, записаться, найти), а не ответ."""

    norm = _normalise(text)
    if _STOP_RE.search(norm) is not None or _OTHER_RE.search(norm) is not None:
        return True
    return names_a_booking_stop(norm)


# ---------------------------------------------------------------------------
# DRF-2982 — «отмени запись на завтра» → список визитов с кнопкой «Отменить»
# ---------------------------------------------------------------------------
#
# Замер на dev ``79b15ec3``: любая фраза отмены уходила консьержу, у которого
# глагола отмены нет («Какая услуга интересует?»). Отмена есть только на
# карточке визита (решение владельца §37: сначала запись, потом действие).
#
# «Запись» двусмысленна (DRF-1055): запись переписки, голосового, звонка — не
# визит, и такая просьба бывает просьбой стереть ПДн; запись дневника питания
# бот сам советует удалить («удали запись и запиши заново»). Поэтому ниже —
# окна чужого предмета, вопроса о правилах и дневника. Они только СУЖАЮТ:
# открытые основы в них допустимы — лишнее исключение стоит хода, отданного
# консьержу, как сегодня.

#: Отменить / удалить / снять — без «забудь»: «забудь про запись» — не отмена.
_CANCEL_VERB = (
    r"отмен(?:и|ите|ить|яй|яйте|им|имте|ю|яю|а|у|ы)"
    r"|удал(?:и|ите|ить|яй|яйте|им|имте|яю)"
    r"|сотри(?:те)?|стереть|стира(?:й|йте)|" + _TAKE_OFF
)
#: «записи обо мне», «запись что я веган» — память (DRF-2891); «запись что на
#: завтра» — визит.
_NOT_ABOUT_ME = r"(?!\s+(?:обо|об|о|про)\b|\s+что\s+я\b)"
_CANCEL_VERB_RE = re.compile(_W + _NOT_NEGATED + r"(?:" + _CANCEL_VERB + r")" + _E)
_CANCEL_NOUN_RE = re.compile(_W + r"(?:" + _BOOKING_NOUN + r")" + _E + _NOT_ABOUT_ME)

_DET = (
    r"(?:(?:мо(?:его|ей|их|ю|й|е|и)|наш(?:его|ей|их|е|и)?|эт(?:ого|ой|их|у|и)"
    r"|последн\w+|сегодняшн\w+|вчерашн\w+|все(?:х)?)\s+)?"
)
#: Записи-не-визиты: звук, переписка, экран, эфир.
_RECORDING = (
    r"голос\w*|аудио\w*|видео\w*|звонк\w*|разговор\w*|диалог\w*|переписк\w*|сообщени\w*"
    r"|чат(?:а|е|ом|у|ов)?|экран\w*|трансляци\w*|вебинар\w*|эфир\w*|созвон\w*"
)
_DIARY_WORDS = (
    r"дневник\w*|блюд\w*|еды|завтрак\w*|обед\w*|ужин\w*|перекус\w*|при[её]ма\s+пищи"
    r"|калори\w*|ккал|воды|стакан\w*"
)
_PLACE = r"календар\w*|истори\w*|памят\w*|телефон\w*|диктофон\w*|рассылк\w*|подписк\w*"
#: Чужой предмет — по ДОПОЛНЕНИЮ «записи», а не по всей фразе: «отмени запись и
#: верни оплату» — отмена визита.
_FOREIGN_RECORD_RE = re.compile(
    r"(?<!\w)запис\w*\s+" + _DET + r"(?:" + _RECORDING + r"|" + _DIARY_WORDS + r")(?!\w)"
    r"|(?<!\w)запис\w*\s+(?:в|во|из|с|со|на)\s+"
    + _DET
    + r"(?:"
    + _RECORDING
    + r"|"
    + _DIARY_WORDS
    + r"|"
    + _PLACE
    + r")(?!\w)"
    r"|(?:голосов\w*|аудио|видео|экранн\w*|дневников\w*)\s*-?\s*запис"
)
#: Вопрос о правилах отмены — не просьба отменить (как ``_CANCEL_QUESTION_FRAME``
#: в ``booking.lookup``). «Можно отменить запись?» — просьба: список с кнопкой
#: на неё хороший ответ.
_CANCEL_QUESTION_RE = re.compile(
    r"\bесли\b(?!\s+(?:можно|не\s+сложно|не\s+трудно|получится|не\s+затруднит))"
    r"|что\s+будет|\bвдруг\b|правил|услови|штраф|\bсгор(?:ит|ают)\b"
    r"|деньги\s+вернут|вернут\s+ли|сколько\s+(?:стоит|будет)|когда\s+можно|бесплатн|платн"
    r"|за\s+сколько"
)
_DIARY_TEXT_RE = re.compile(r"дневник|калори|ккал|блюд|при[её]м\w*\s+пищи")
#: Явная примета визита перебивает контекст дневника: «удали запись на завтра»
#: после «Записала: борщ — 250 ккал» — визит.
_BOOKING_CUE_RE = re.compile(
    r"брон|визит|мастер|салон"
    r"|на\s+(?:завтра|сегодня|послезавтра|понедельник|вторник|среду|четверг|пятницу|субботу"
    r"|воскресенье|\d)|в\s+\d{1,2}(?:[:.]\d{2})?\b"
)


def names_a_booking_cancel(text: str, *, diary_context: bool = False) -> bool:
    """«Отмени / удали / сними запись …» — просьба отменить визит (DRF-2982).

    ``diary_context`` — предыдущий ход был о дневнике питания (последний ответ
    бота — запись дневника, или ждёт ввод еды): тогда «удали / отмени запись»
    — о записи дневника, если в реплике нет явной приметы визита.

    Всегда влечёт :func:`names_a_booking_stop` и :func:`names_a_command`: иначе
    продолжение записи и вопрос памяти забрали бы ход раньше.
    """

    norm = _normalise(text)
    if _CANCEL_NOUN_RE.search(norm) is None or _CANCEL_VERB_RE.search(norm) is None:
        return False
    if (
        _FOREIGN_RECORD_RE.search(norm)
        or _CANCEL_QUESTION_RE.search(norm)
        or _DIARY_TEXT_RE.search(norm)
    ):
        return False
    return not diary_context or _BOOKING_CUE_RE.search(norm) is not None
