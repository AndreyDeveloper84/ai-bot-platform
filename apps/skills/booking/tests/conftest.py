"""DRF-1636 — тесты записи не строят клиента вендора LLM.

### Что здесь случилось

Тест `test_lookup_routing.py::…::test_compound_phrases_never_reach_show_my_bookings`
проверяет **маршрутизацию**: составная фраза со словом «запись» не должна
попадать в навык записи. Он патчит `BookingSkill.handle` — и только его.
Поэтому дальше по диспетчеру честно отрабатывает FAQ, а FAQ идёт в
роутер LLM, конструирует настоящий `AsyncOpenAI` и уходит в сеть.

Тест при этом зелёный: ответ FAQ не содержит `show_my_bookings` при любом
исходе вызова, в том числе при провалившемся. То есть **предмет
доказывался дорогой, к предмету не относящейся**, а зелень бралась из
случайности.

Пока рядом никого — случайность работает. Стоит соседу оставить после
себя `AsyncOpenAI` с исчерпанным `side_effect` (в наборе такие моки
живут в `apps/llm/providers/tests/` и `apps/orchestrator/tests/`), как
конструктор клиента бросает `StopIteration`, и эти двадцать параметров
краснеют — в файле, который сам ничего не патчит. Красный CI на `dev`
выглядел как дефект записи, а был дефектом изоляции.

### Почему сторож здесь, а не в самом тесте

Правку одного теста нечем доказать. «Падал до, проходит после»
неприменимо: **запущенный в одиночку он проходит и сегодня** — красным
его делает соседство, а соседство воспроизводимо только подделкой, и
сторож стерёг бы подделку.

Поэтому утверждение сформулировано положительно и не зависит от порядка:
**ни один тест этого каталога не конструирует клиента вендора.** У него
есть число на обоих концах — двадцать узлов до правки, ноль после
(замер: обёртка вокруг `_get_client`, звавшая оригинал, в
`apps/skills/booking/tests/`, без соседних каталогов).

### Почему перехват именно на `_get_client`

Это наш собственный шов, а не чужой. Патчить `openai.AsyncOpenAI` —
делать ровно то, чем вызван дефект: ставить в общий модуль подмену,
чья жизнь длиннее теста. `_get_client` принадлежит нам, вызывается
непосредственно перед конструктором SDK у обоих вендоров и переживёт
смену вендорской библиотеки.

Сторож ЗАПРЕЩАЕТ, а не подменяет. Молчаливая заглушка вернула бы
зелень, не сказав, что путь к вендору снова открыт: тест, который
опять пошёл бы в FAQ за живым ответом, выглядел бы точно так же, как
тест, который туда не ходит. Здесь такой тест обязан упасть с именем.
"""

from __future__ import annotations

from typing import Any

import pytest


class VendorClientForbidden(AssertionError):
    """Тест записи попытался построить клиента вендора LLM."""


_MESSAGE = (
    "DRF-1636: тест из apps/skills/booking/tests/ дошёл до конструктора "
    "клиента вендора LLM. Проверка записи не должна зависеть от живого "
    "провайдера: подменяйте `OpenAIProvider.complete` детерминированным "
    "ответом (как это делает TestWhitespaceNormalization) либо сам навык, "
    "чей ответ проверяете. Чужой мок рядом — не средство изоляции: он "
    "исчерпывается и роняет этот файл."
)


@pytest.fixture(autouse=True)
def forbid_vendor_llm_client(monkeypatch: pytest.MonkeyPatch) -> None:
    """Закрыть обоим провайдерам дорогу к конструктору SDK."""

    from apps.llm.providers.anthropic_provider import AnthropicProvider
    from apps.llm.providers.openai_provider import OpenAIProvider

    def _refuse(self: Any) -> Any:
        raise VendorClientForbidden(_MESSAGE)

    monkeypatch.setattr(OpenAIProvider, "_get_client", _refuse)
    monkeypatch.setattr(AnthropicProvider, "_get_client", _refuse)
