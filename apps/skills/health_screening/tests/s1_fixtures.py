@dataclass(frozen=True)
class S1Fixture:
    group: str
    kind: str
    #: Фраза без длинного начала — ключ в :data:`KNOWN_MISSES`.
    core: str

    @property
    def text(self) -> str:
        return LONG_PREFIX + self.core if self.kind == "long" else self.core

    @property
    def expected_detected(self) -> bool:
        return self.kind != "negative"

    @property
    def key(self) -> tuple[str, str, str]:
        return (self.group, self.kind, self.core)


def _build() -> tuple[S1Fixture, ...]:
    out: list[S1Fixture] = []
    for kind, table in (
        ("explicit", _EXPLICIT),
        ("ambiguous", _AMBIGUOUS),
        ("negative", _NEGATIVE),
        ("post_procedure", _POST_PROCEDURE),
    ):
        for group, phrases in table.items():
            out.extend(S1Fixture(group, kind, phrase) for phrase in phrases)
    # Длинное сообщение — первая явная фраза группы после обычной просьбы о записи.
    out.extend(S1Fixture(group, "long", phrases[0]) for group, phrases in _EXPLICIT.items())
    return tuple(out)


