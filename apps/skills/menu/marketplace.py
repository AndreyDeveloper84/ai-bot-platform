# Разбор тапов подменю и предупреждения
# ---------------------------------------------------------------------------

#: Те же строгие формы и по той же причине, что у ``cb:health:``.
_EXTRA_CALLBACK_RE = re.compile(r"^cb:extra:[a-z0-9_]+$")
_OPEN_CALLBACK_RE = re.compile(r"^cb:open:[a-z0-9_]+$")


def is_extra_callback(text: str) -> bool:
    """True для тапа «Ещё» / «Помощь» / «Назад» — по форме."""
    return bool(_EXTRA_CALLBACK_RE.match((text or "").strip()))


def is_open_callback(text: str) -> bool:
    """True для тапа экранного пункта меню — по форме."""
    return bool(_OPEN_CALLBACK_RE.match((text or "").strip()))


def _screen_items() -> tuple[MenuItem, ...]:
    """Все экранные пункты обоих меню — один источник для разбора тапа."""
    return tuple(item for item in (*MAIN_ITEMS, *NUTRITION_ITEMS) if item.where == "miniapp")


def open_callback_slug(text: str) -> str | None:
    """Слаг маршрута из ``cb:open:{слаг}``; ``None`` — незнакомый пункт.

    Незнакомый слаг — это снятая кнопка из истории чата. Открывать по
    нему ничего нельзя (маршрута может уже не быть), и угадывать нечего:
    ветка ответит меню, как и всякий снятый пункт.
    """
    stripped = (text or "").strip()
    if not _OPEN_CALLBACK_RE.match(stripped):
        return None
    slug = f"open_{stripped[len(OPEN_CALLBACK_PREFIX) :]}"
    return slug if slug in {item.callback for item in _screen_items()} else None


