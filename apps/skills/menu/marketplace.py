def _miniapp_button(item: MenuItem, *, web_app: str, miniapp_url: str) -> dict[str, str] | None:
    """Кнопка, ОТКРЫВАЮЩАЯ экран, — или None, когда приложение не настроено.

    Лестница вырождения ровно приветственная
    (``welcome.skill._welcome_buttons``): ``open_app``, внешняя ссылка,
    ничего. Третий случай не ошибка: ботовая половина меню от него не
    зависит и продолжает работать.

    Рисуется НЕ в самом меню, а под предупреждением
    (:func:`open_warning_reply`): в меню на её месте стоит обычная
    ``cb:open:{слаг}``, потому что ``open_app`` открывает приложение
    мгновенно и предупреждать «перед» было бы уже поздно.
    """
    label = item.button_label or OPEN_BUTTON_LABEL
    if web_app:
        return {"label": label, "callback": item.callback, "web_app": web_app}
    if miniapp_url:
        from apps.skills.welcome.skill import _miniapp_url

        return {"label": label, "url": _miniapp_url(miniapp_url, item.callback)}
    return None


def _config() -> tuple[str, str]:
    from django.conf import settings

    return (
        getattr(settings, "MAX_BOT_WEB_APP", "") or "",
        getattr(settings, "MAX_MINIAPP_URL", "") or "",
    )


def miniapp_configured() -> bool:
    """Есть ли вообще куда открывать мини-приложение."""
    web_app, miniapp_url = _config()
    return bool(web_app or miniapp_url)


def nutrition_enabled() -> bool:
    """Первые ворота: мастер-выключатель питания.

    Читается тем же способом, что и в ``apps.skills.food_scanner.skill``
    — ``getattr`` с ``False`` по умолчанию, — чтобы «не задан» на обеих
    сторонах значило одно и то же.
    """
    from django.conf import settings

    return bool(getattr(settings, "NUTRITION_ENABLED", False))


def health_granted(bot_user: Any) -> bool:
    """Вторые ворота: действующее согласие ``HEALTH`` у ЭТОГО человека.

    Тот же предикат, которым ходит сторож нутриционной поверхности
    (:func:`apps.consent.health.is_granted`), — чтобы меню не могло
    показать вход туда, куда поверхность откажет.

    Fail-closed: любая ошибка чтения — это «согласия нет», то есть тап
    приведёт на запрос согласия. Ошибиться в другую сторону значило бы
    открыть медданные по сбою БД.
    """
    from apps.consent.health import is_granted

    try:
        return bool(is_granted(bot_user))
    except Exception:  # noqa: BLE001 — сторож согласия обязан быть fail-closed
        return False


def _item_button(item: MenuItem) -> dict[str, str] | None:
    """Кнопка ПУНКТА МЕНЮ — ботовая всегда, даже у экранного пункта.

    Экранный пункт рисуется ``cb:open:{слаг}``: приложение откроется
    вторым тапом, под предупреждением (§37 п.6). Без настроенного
    мини-приложения экранного пункта нет вовсе — иначе предупреждение
    вело бы к кнопке, которой не будет.
    """
    if item.where == "bot":
        return {"label": item.button_label, "callback": item.callback}
    if not miniapp_configured():
        return None
    slug = item.callback.removeprefix("open_")
    return {"label": item.button_label, "callback": f"{OPEN_CALLBACK_PREFIX}{slug}"}


def marketplace_menu_buttons(*, bot_user: Any) -> list[dict[str, str]]:
    """Клавиатура ГЛАВНОГО меню витрины для КОНКРЕТНОГО человека.

    ``bot_user`` ЧИТАЕТСЯ — с OD-UI-2 главное меню перестало быть одним и
    тем же для всех: пищевой пункт поднялся сюда из снесённого подменю и
    принёс с собой обе двери §25 п.6.

    Пищевой пункт подменяется на кнопки :func:`_nutrition_buttons`, а не
    строится ``_item_button``, и это не оптимизация: у него ДВА исхода
    вместо одного (фраза дневника при согласии, ``cb:health:need:*`` без
    согласия) плюс правило «без мини-приложения безсогласного пункта нет
    вовсе». Считать всё это здесь во второй раз — тот самый четвёртый
    экземпляр предиката, из-за которого ворота разъезжаются молча.

    ``_nutrition_buttons`` отдаёт кнопки на ВЕСЬ :data:`NUTRITION_ITEMS`
    разом, поэтому подставляются они РОВНО ОДИН РАЗ — на первом пищевом
    пункте, встреченном в составе. Сегодня пункт один и разницы не видно;
    когда вернётся «Сканер еды» (модуль это обещает прямо в комментарии к
    ``NUTRITION_ITEMS``), подстановка на каждом совпадении нарисовала бы
    каждую пищевую кнопку дважды. Поймал бы это не тест, а человек в MAX,
    поэтому позиция подстановки закреплена здесь и проверена
    ``TestNutritionGates::test_two_nutrition_items_are_drawn_once_each``.
    """
    buttons: list[dict[str, str]] = []
    nutrition = _nutrition_buttons(bot_user=bot_user)
    nutrition_drawn = False
    for item in main_items(bot_user=bot_user):
        if item in NUTRITION_ITEMS:
            if not nutrition_drawn:
                buttons.extend(nutrition)
                nutrition_drawn = True
            continue
        button = _item_button(item)
        if button is not None:
            buttons.append(button)
    return buttons


def _nutrition_buttons(*, bot_user: Any) -> list[dict[str, str]]:
    """Пищевые пункты по таблице §25 п.6.

    Первая строка таблицы («флаг не задан») сюда не доходит вовсе —
    :func:`main_items` не кладёт пункт в состав. Вторая («флаг задан,
    согласия нет») отдаёт кнопку в ``cb:health:need:*``: тап ведёт на
    запрос согласия, а не в поверхность и не в пустоту. Третья отдаёт
    ботовую кнопку с фразой — дневник отвечает В ЧАТЕ (§37 п.5).

    Без настроенного мини-приложения пункт БЕЗ согласия не рисуется:
    согласие выдаётся в профиле мини-приложения, и запрос вёл бы к
    кнопке, которую негде показать. С согласием пункт живёт и без
    приложения — дневник ботовый.
    """
    if not nutrition_enabled():
        return []
    if health_granted(bot_user):
        # ``_item_button`` — тот же построитель, что у остальных пунктов:
        # ботовый отдаёт фразу, экранный отдаёт ``cb:open:{слаг}`` и потому
        # получает своё предупреждение, а не открывает приложение молча.
        # Сегодня пищевой пункт один и он ботовый; сканер вернётся
        # экранным, и правило для него уже готово.
        out: list[dict[str, str]] = []
        for item in NUTRITION_ITEMS:
            button = _item_button(item)
            if button is not None:
                out.append(button)
        return out
    if not miniapp_configured():
        return []
    return [
        {
            "label": item.button_label,
            "callback": f"{CALLBACK_HEALTH_NEED_PREFIX}{_surface_slug(item)}",
        }
        for item in NUTRITION_ITEMS
    ]


def nutrition_entry_buttons(*, bot_user: Any) -> list[dict[str, str]]:
    """Пищевые входы для ЛЮБОЙ поверхности, а не только для «Ещё».

    Решение владельца 07.09.2026 вывело дневник ещё и на экран первого
    появления (:mod:`apps.channels.max.quick_actions`), НЕ убирая его из
    «Ещё». Два места — но ворота одни: и флаг ``NUTRITION_ENABLED``, и
    согласие ``HEALTH``, и требование настроенного мини-приложения для
    безсогласного случая считаются здесь один раз.

    Копия этой логики на первом экране разошлась бы с «Ещё» на первом же
    изменении ворот — и разошлась бы молча, потому что экран первого
    появления видит только новый человек.
    """
    return _nutrition_buttons(bot_user=bot_user)


def _menu_action_data(
    buttons: list[dict[str, str]], *, kind: str, columns: int = 2
) -> dict[str, Any]:
    """Плоская форма ``action_data`` — та, что несёт ключи кнопок целиком.

    НЕ платформенный конверт ``attachments`` (его строит
    ``matching.main_menu_action_data`` для салонного пути): конверт
    прогоняется через ``make_inline_keyboard_attachment`` без колонок, а
    раскладка 2×3+1 из решения владельца задаётся именно колонками.
    Плоскую форму читает ветка (2) ``handler._build_attachments`` и
    передаёт словари в ``_button_to_max`` как есть.
    """
    return {"buttons": buttons, "button_columns": columns, "kind": kind}


def _lines(items: tuple[MenuItem, ...]) -> list[str]:
    return [f"• {item.line}" for item in items if item.line]


def marketplace_menu_text(*, intro: str = _INTRO, compact: bool = False) -> str:
    """Текст меню — перечень ПОСТОЯННОГО состава, а не копия клавиатуры.

    **Перечень и клавиатура намеренно не совпадают, и это не расхождение,
    а правило.** Клавиатура строится НА ЧЕЛОВЕКА
    (:func:`marketplace_menu_buttons`) и при открытых воротах питания
    несёт восемь кнопок; перечень собирается из :data:`MAIN_ITEMS` и
    описывает семь. Пищевого пункта в перечне нет, потому что его наличие
    — вопрос ворот §25 п.6, а не состава меню: назвать его словами тому, у
    кого он не нарисован, значит соврать. Обратной ошибки при этом нет —
    в перечне не может оказаться того, чего нет на клавиатуре.

    Асимметрия держится на том, что пищевой пункт и БЕЗ перечня не
    молчит: его подпись («🥗 Дневник питания») сама себя объясняет, а
    ``line`` у него существует ради будущих поверхностей, где перечень
    будет строиться на человека.

    ``compact`` — рамка промаха: перечень и длинный хвост опускаются
    ЦЕЛИКОМ, чтобы реплика влезала в потолок длины (см.
    :data:`_FALLBACK_OUTRO` — 300 символов на негативных случаях золотых
    фикстур). Раньше опускалась только экранная половина перечня; после
    §37 строк стало семь, и одной этой экономии не хватает.

    Клавиатура при этом НЕ урезается: ни один пункт не пропадает — он
    просто не пересказан словами, и все свои подписи человек видит
    кнопками.

    Экранные пункты перечисляются только там, где они нарисованы: на
    развёртывании без мини-приложения меню не обещает экранов, которых
    человек не откроет. Пищевой пункт опущен по тому же правилу, просто
    считается оно не здесь.
    """
    if compact:
        return f"{intro}\n\n{_FALLBACK_OUTRO}"
    drawn = tuple(item for item in MAIN_ITEMS if item.where == "bot" or miniapp_configured())
    return "\n\n".join([intro, "\n".join(_lines(drawn)), _OUTRO])


def marketplace_menu_reply(*, bot_user: Any) -> tuple[str, dict[str, Any]]:
    """Экран «что хотите сделать» — текст и клавиатура одним куском."""
    buttons = marketplace_menu_buttons(bot_user=bot_user)
    return marketplace_menu_text(), _menu_action_data(buttons, kind="marketplace_menu")


def marketplace_fallback_reply(*, bot_user: Any) -> tuple[str, dict[str, Any]]:
    """Ветка «я пока не поняла» — тот же состав, другая рамка.

    Состав тот же намеренно: человек, которого не поняли, и человек,
    спросивший «что ты умеешь», нуждаются в одном и том же — в списке
    того, что сработает. Разная только первая строка, и она честная: во
    втором случае человеку не сообщают, что его не поняли.
    """
    buttons = marketplace_menu_buttons(bot_user=bot_user)
    return (
        marketplace_menu_text(intro=FALLBACK_INTRO, compact=True),
        _menu_action_data(buttons, kind="marketplace_fallback"),
    )


def open_warning_reply(slug: str) -> tuple[str, dict[str, Any]] | None:
    """Предупреждение перед открытием приложения — текст и одна кнопка.

    ``None``, когда открывать нечем (мини-приложение не настроено) или
    слаг незнаком: обе ситуации — снятая кнопка из истории чата, и обе
    отвечаются меню, а не пустым экраном.

    Кнопка ОДНА и подписана нейтрально (:data:`OPEN_BUTTON_LABEL`): что
    именно откроется, уже сказано строкой предупреждения, и повторять это
    на кнопке значило бы объяснять человеку одно и то же дважды.
    """
    item = next((i for i in _screen_items() if i.callback == slug), None)
    if item is None:
        return None
    web_app, miniapp_url = _config()
    button = _miniapp_button(
        MenuItem(label=OPEN_BUTTON_LABEL, callback=item.callback, line="", where="miniapp"),
        web_app=web_app,
        miniapp_url=miniapp_url,
    )
    if button is None:
        return None
    return item.warning, {
        "buttons": [button],
        "button_columns": 1,
        "kind": "marketplace_open_warning",
    }


def health_request_action_data() -> dict[str, Any]:
    """Клавиатура экрана запроса согласия.

    «Открыть профиль» ведёт туда, где согласие ВЫДАЁТСЯ
    (``apps.consent.health.GRANT_SOURCE`` = ``miniapp:profile_health_consent``),
    а не в саму пищевую поверхность: поверхность без согласия откажет, и
    это была бы ровно та мёртвая кнопка, которую §25 п.6 запрещает.

    Открывает приложение НАПРЯМУЮ, без второго предупреждения: текст
    экрана сам и есть предупреждение — он говорит, что откроет профиль,
    и обещает возврат.

    Остаётся одна «Не сейчас», когда мини-приложения нет. На практике так
    сюда не попадают — пищевой пункт в такой конфигурации без согласия не
    рисуется, — но экран достижим по payload'у из истории чата, и
    оставлять человека без выхода нельзя.
    """
    web_app, miniapp_url = _config()
    buttons: list[dict[str, str]] = []
    grant_item = MenuItem(
        label="Открыть профиль",
        callback="open_profile",
        line="",
        where="miniapp",
    )
    button = _miniapp_button(grant_item, web_app=web_app, miniapp_url=miniapp_url)
    if button is not None:
        buttons.append(button)
    buttons.append({"label": "Не сейчас", "callback": CALLBACK_HEALTH_DECLINE})
    return {"buttons": buttons, "button_columns": 1, "kind": "health_consent_request"}
