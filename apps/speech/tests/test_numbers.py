"""Нормализация чисел (K15). Таблица случаев — из замеров этапа 0 (§2.5, §2.5.1)."""

from __future__ import annotations

import pytest

from apps.speech.numbers import normalize_numbers


@pytest.mark.parametrize(
    ("src", "expected"),
    [
        # Живой замер 21.09 — одна величина двумя способами
        ("Съела борщ, триста грамм.", "Съела борщ, 300 грамм."),
        ("Триста грамм борща.", "300 грамм борща."),
        (
            "Съел двести пятьдесят грамм гречки с курицей.",
            "Съел 250 грамм гречки с курицей.",
        ),
        ("На завтрак овсянка сто пятьдесят грамм", "На завтрак овсянка 150 грамм"),
        (
            "Съела ноль целых три десятых килограмма творога.",
            "Съела 0,3 килограмма творога.",
        ),
        ("Выпил два литра воды.", "Выпил 2 литра воды."),
        ("Короче, съел пиццу, четыре куска.", "Короче, съел пиццу, 4 куска."),
        # Время записи — тоже словами
        (
            "Запишите меня на массаж спины в субботу на три часа дня.",
            "Запишите меня на массаж спины в субботу на 3 часа дня.",
        ),
        (
            "Можно записаться на чистку лица на десять утра?",
            "Можно записаться на чистку лица на 10 утра?",
        ),
        # Составные
        ("Полтора литра", "1,5 литра"),
        ("полторы порции", "1,5 порции"),
        ("Две целых пять десятых", "2,5"),
        ("одна целая двадцать пять сотых", "1,25"),
        ("Тысяча двести калорий", "1200 калорий"),
        ("Двадцать одна тысяча", "21000"),
        ("Три тысячи", "3000"),
        ("Сто", "100"),
        ("девятьсот девяносто девять", "999"),
        ("Триста, двести", "300, 200"),
        ("ТРИСТА ГРАММ", "300 ГРАММ"),
    ],
)
def test_converts(src: str, expected: str) -> None:
    assert normalize_numbers(src) == expected


@pytest.mark.parametrize(
    "src",
    [
        "Один раз в неделю",  # одиночное «один» — счёт, не количество
        "Одна подруга советовала",
        "В первый раз третьего числа",  # порядковые
        "Полчаса и полкило",  # «пол» внутри слова
        "Съел 250 грамм",  # уже цифры
        "",
        "Нет чисел вовсе",
        "три-четыре раза",  # через дефис — не одно число, не трогаем
    ],
)
def test_leaves_untouched(src: str) -> None:
    assert normalize_numbers(src) == src


def test_two_numbers_separated_by_word() -> None:
    assert normalize_numbers("двести грамм и триста миллилитров") == "200 грамм и 300 миллилитров"


def test_fraction_without_whole_part_is_left() -> None:
    # «три десятых» без «целых» — двусмысленно, не трогаем
    assert normalize_numbers("три десятых") == "три десятых"


def test_broken_thousands_left() -> None:
    assert normalize_numbers("тысяча тысяча") == "тысяча тысяча"


def test_punctuation_between_words_breaks_the_number() -> None:
    assert normalize_numbers("двести, пятьдесят") == "200, 50"


def test_lone_one_with_continuation_is_a_number() -> None:
    assert normalize_numbers("одна тысяча сто") == "1100"
