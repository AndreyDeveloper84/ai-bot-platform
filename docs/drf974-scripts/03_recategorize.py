print(f"услуг: {len(catalog)} | целевых узлов таксономии: {len(set(MAP.values()))}")
plan = Counter()
for name, cid in MAP.items():
    s = catalog.get(name)
    if s is not None and str(s.category_id) != cid:
        plan[ServiceCategory.objects.get(pk=cid).name] += 1
for k, v in sorted(plan.items(), key=lambda kv: -kv[1]):
    print(f"   → {k}: {v}")
print("всего переназначений:", sum(plan.values()))

