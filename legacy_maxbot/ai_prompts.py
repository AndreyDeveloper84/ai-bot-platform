def render_system_prompt(
    *,
    today: date,
    client_name: str,
    bookings_count: int,
    master_context: MasterContext,
    last_visits: list | None = None,
    extra_hint: str = "",
    advice_mode: str = "full",
) -> str:
    """Render system prompt с конкретными значениями context'а.

    today — для парсинга «завтра», «послезавтра» в датах.
    client_name — для персонализации (если есть).
    bookings_count — для tone-adjustment (новый/постоянный клиент).
    master_context.summary_text — рендер top-N мастеров с реальными ID.
    last_visits — Phase 2.4 T05: список dict {date, master, service} —
        последние 3 успешных визита через бот. Если есть — добавляется
        блок «ИСТОРИЯ КЛИЕНТА» в context, и LLM приветствует по имени
        с упоминанием прошлого визита.
    extra_hint — DRF-248 cross-domain bridge: optional soft-context block
        composed by the caller (e.g. nutrition deficit signal). Empty string
        means no block is rendered. The block is framed as an advisory hint,
        not a rule, so unrelated questions don't get derailed.
    advice_mode — Phase 3.2A T08: "full" (default) | "degraded".
        В degraded mode (TIER-B health screening НЕ пройден) добавляется
        блок «ВАЖНО (degraded-advice mode)» — запрет на персональные советы
        по питанию/БАДам/калориям до прохождения screening.
    """
    extra_hint_text = (extra_hint or "").strip()
    extra_hint_block = (
        f"\nДОПОЛНИТЕЛЬНЫЙ КОНТЕКСТ (мягкая подсказка, не правило):\n{extra_hint_text}\n"
        if extra_hint_text
        else ""
    )

    prompt = SYSTEM_PROMPT_TEMPLATE.format(
        today=today.isoformat(),
        client_name=client_name.strip() or "клиент",
        bookings_count=bookings_count,
        masters_summary=master_context.summary_text or "(нет активных мастеров)",
        client_history_block=_render_client_history(last_visits or []),
        fewshot_block=_render_fewshot_block(),
        pain_examples_block=_render_pain_examples_block(),
        extra_hint_block=extra_hint_block,
    )

    if advice_mode == "degraded":
        prompt += (
            "\n\nВАЖНО (degraded-advice mode): пользователь ещё не прошёл "
            "health screening (TIER-B). Не давай персональных советов по "
            "питанию, не рекомендуй БАДы, не делай выводов про калории/БЖУ. "
            "На health-вопросы отвечай: «Чтобы посоветовать аккуратно, нужно "
            "пройти короткий screening — напиши «настрой советы»»."
        )

    return prompt


def _render_pain_examples_block() -> str:
    """DRF-358: компактный few-shot block для diagnostic-first pain rule.

    Источник — `voice_examples.DIAGNOSTIC_FIRST_PAIN_EXAMPLES` (5 examples).
    Рендерится как «# ПРИМЕРЫ — diagnostic-first для жалоб» с pair user/AI.
    Усиливает text rule про эмпатию+вопросы перед tool-call.
    """
    from maxbot.voice_examples import DIAGNOSTIC_FIRST_PAIN_EXAMPLES
    if not DIAGNOSTIC_FIRST_PAIN_EXAMPLES:
        return ""
    lines = ["# ПРИМЕРЫ — diagnostic-first для жалоб на здоровье"]
    for ex in DIAGNOSTIC_FIRST_PAIN_EXAMPLES:
        lines.append(f"\nUser: {ex.user}")
        lines.append(f"Assistant: {ex.assistant}")
    return "\n".join(lines) + "\n\n"


def _render_fewshot_block() -> str:
    """Блок «ПРИМЕРЫ ХОРОШИХ ОТВЕТОВ» из FewShotExample (auto-tune #1).

    Best-effort: если БД недоступна (тесты без django) или таблицы нет —
    возвращает пустую строку, prompt рендерится без примеров.
    """
    try:
        from services_app.models import FewShotExample
        examples = list(
            FewShotExample.objects
            .filter(is_active=True)
            .order_by("-created_at")[:10]
            .values("user_text", "assistant_text")
        )
    except Exception:  # noqa: BLE001
        return ""
    if not examples:
        return ""
    lines = [
        "",
        "ПРИМЕРЫ ХОРОШИХ ОТВЕТОВ из реальных успешных диалогов",
        "(учись стилю и структуре, не копируй буквально):",
        "",
    ]
    for ex in examples:
        u = (ex["user_text"] or "").strip().replace("\n", " ")
        a = (ex["assistant_text"] or "").strip()
        # Обрезаем assistant до 280 char чтобы не раздуть prompt
        if len(a) > 280:
            a = a[:280].rstrip() + "…"
        lines.append(f"— Клиент: «{u}»")
        lines.append(f"— Бот: {a}")
        lines.append("")
    return "\n".join(lines) + "\n"


def _render_client_history(last_visits: list) -> str:
    """Блок «ИСТОРИЯ КЛИЕНТА» — пустая строка если visits=[]."""
    if not last_visits:
        return ""
    lines = ["", "ИСТОРИЯ КЛИЕНТА (последние визиты через бот):"]
    for v in last_visits[:3]:
        date = v.get("date") or "—"
        master = v.get("master") or "—"
        service = v.get("service") or "—"
        lines.append(f"- {date}: {master}, {service}")
    lines.append("")
    return "\n".join(lines)
