"""Выкладка спрашивает системные проверки, и спрашивает до миграций — DRF-2393.

### Что было измерено

Восемь наших системных проверок (`handoff.E001`, `payments.W001`,
`admin_api.W002`, дрейф env-файлов и прочие) **не выполняются там, где идёт
запрос**: стенд поднимается `uvicorn config.asgi:application`
(`docker-compose.staging.yml`), а ``get_asgi_application()`` делает
``django.setup()`` и ``run_checks()`` не зовёт никогда. Проверки гоняет
management-команда, и в выкладке такая одна — ``migrate``.

Опыт (местные настройки, оба дежурных значения пусты):

```
manage.py migrate --plan  → ВЫХОД=1,  ERRORS: (handoff.E001) …
manage.py check           → ВЫХОД=1
```

То есть механизм есть. Этот узел закрепляет, что он вызван **явно и
отдельно**, а не остаётся побочным свойством миграций.

### Почему отдельный шаг, а не вызов внутри ``asgi.py``

Вызов проверок в ASGI-приложении поднял бы их в каждом воркере uvicorn:
ошибка превратилась бы в петлю рестартов уже ПОСЛЕ успешной выкладки, а
предупреждения печатались бы при каждом старте каждого воркера — тот самый
постоянный шум, который мы гасили в DRF-2021. Отдельный шаг платит дешевле:
при ложном отказе встаёт **выкладка**, а обслуживание продолжается.

### Почему ДО миграций

Если проверка падает после ``migrate``, часть миграций уже применена, и
контур остаётся в состоянии «схема новая, код старый». Шаг стоит раньше,
чтобы отказ ничего не успел изменить.

### Предел, названный вслух

Шаг ловит состояние **на момент выкладки**. Дрейф после неё — кто-то
поправил ``.env.staging`` руками и перезапустил контейнер — он не увидит:
между выкладками проверки не спрашивает никто. Это честная граница
варианта, а не недосмотр.
"""

from __future__ import annotations

import re
from pathlib import Path

WORKFLOW = Path(__file__).resolve().parents[1] / ".github/workflows/deploy-dev.yml"

#: Команда проверки: явный уровень отказа, без ``--deploy``.
#:
#: ``--fail-level ERROR`` — требование «ошибка обязана останавливать»
#: записано в самой команде, а не подразумевается умолчанием.
#:
#: ``--deploy`` НЕ берётся намеренно: он добавляет шесть чужих
#: предупреждений Django (``security.W016``, ``security.W018`` и прочие),
#: и строка «0 silenced», по которой мы читаем свои проверки, перестала бы
#: что-либо значить.
CHECK_RE = re.compile(r"manage\.py\s+check\b[^\n]*--fail-level\s+ERROR")
MIGRATE_RE = re.compile(r"manage\.py\s+migrate\b")
DEPLOY_FLAG_RE = re.compile(r"manage\.py\s+check\b[^\n]*--deploy")


def _workflow() -> str:
    return WORKFLOW.read_text(encoding="utf-8")


def test_deploy_asks_system_checks() -> None:
    """Выкладка зовёт ``manage.py check`` с явным уровнем отказа."""

    text = _workflow()
    # Присутствие первым: файл прочитан и это действительно выкладка.
    assert MIGRATE_RE.search(text), "в выкладке не нашёлся даже migrate — проверь путь"
    assert CHECK_RE.search(text), (
        "выкладка не спрашивает системные проверки: восемь сторожей молчат "
        "на стенде, потому что uvicorn их не зовёт"
    )


def test_checks_run_before_migrations() -> None:
    """Отказ приходит до того, как схема изменится."""

    text = _workflow()
    check_at = CHECK_RE.search(text)
    migrate_at = MIGRATE_RE.search(text)
    assert check_at and migrate_at
    assert check_at.start() < migrate_at.start(), (
        "проверка стоит после миграций: при отказе часть миграций уже "
        "применена, и контур остаётся со схемой от нового кода"
    )


def test_deploy_flag_is_not_used() -> None:
    """``--deploy`` не берётся: чужие предупреждения обесценят «0 silenced»."""

    text = _workflow()
    # Наличие первым: команда проверки в файле есть, значит отсутствие
    # флага ниже — про флаг, а не про отсутствующую команду.
    assert CHECK_RE.search(text)
    assert DEPLOY_FLAG_RE.search(text) is None
