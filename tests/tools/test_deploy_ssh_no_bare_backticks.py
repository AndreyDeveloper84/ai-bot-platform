# Сторож без теста на обход — сторож, про который никто не знает, где он слеп.


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("# обычный комментарий", 0),
        ("# с `голой` кавычкой", 2),
        ("# с \\`экранированной\\` кавычкой", 0),
        ("# смешанный: \\`ок\\` и `нет`", 2),
        # Литеральный слэш перед кавычкой: кавычка ГОЛАЯ.
        ("# слэш и кавычка: \\\\`", 1),
    ],
)
def test_counter_itself(text: str, expected: int) -> None:
    """Счётчик, разучившийся видеть кавычки, зеленел бы на любом файле."""
    assert bare_backticks(text) == expected


@pytest.mark.parametrize(
    "invocation",
    ['bash -lc "', 'bash -l -c "', 'bash --login -c "', 'bash  -lc  "'],
)
def test_the_form_of_the_invocation_does_not_hide_the_step(invocation: str) -> None:
    """Обход 1, проверенный опытом на прежней редакции стража.

    Прежняя искала блоки по литералу ``bash -lc "`` — и на ``bash -l -c "``
    находила ноль блоков, ноль нарушений, зелень.
    """
    doc = yaml.safe_load(
        "jobs:\n"
        "  deploy:\n"
        "    steps:\n"
        "      - name: шаг\n"
        "        run: |\n"
        f'          ssh -i k "u@h" {invocation}\n'
        "            # тут `голая` кавычка\n"
        '          "\n'
    )
    steps = ssh_steps(doc)
    assert steps, f"шаг с {invocation!r} не найден — страж слеп к форме вызова"
    assert sum(bare_backticks(run) for _, run in steps) == 2


def test_a_lone_quote_inside_the_body_does_not_end_the_check() -> None:
    """Обход 2: прежняя редакция закрывала блок на строке, равной кавычке."""
    doc = yaml.safe_load(
        "jobs:\n"
        "  deploy:\n"
        "    steps:\n"
        "      - name: шаг\n"
        "        run: |\n"
        '          ssh -i k "u@h" bash -lc "\n'
        "            echo первая\n"
        '            "\n'
        "            echo `дата`\n"
        '          "\n'
    )
    steps = ssh_steps(doc)
    assert sum(bare_backticks(run) for _, run in steps) == 2, (
        "кавычки после одинокой закрывающей не посчитаны — тело всё ещё ограничивают"
    )


def test_a_step_without_ssh_is_not_policed() -> None:
    """Отрицательный контроль: правило узкое и не растекается.

    Без него страж, считающий кавычки ВЕЗДЕ, зеленел бы на этом наборе так
    же, как правильный, и разницы было бы не видно.
    """
    doc = yaml.safe_load(
        "jobs:\n"
        "  deploy:\n"
        "    steps:\n"
        "      - name: локальный шаг\n"
        "        run: |\n"
        "          echo `date`\n"
    )
    assert ssh_steps(doc) == []
