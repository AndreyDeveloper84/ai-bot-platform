"""Страж: внутри ``ssh ... bash -lc "…"`` не должно быть голых обратных кавычек.

# Что сломалось 11.09.2026

Выкладка пилота упала так:

```
bash: line 35: path: No such file or directory
##[error]Process completed with exit code 1
```

Образы собрались, а ``migrate``, ``collectstatic`` и ``up -d`` не
выполнились: пилот остался на старых контейнерах при новом дереве.

# Почему

Шаг выкладки передаёт скрипт одной строкой в **двойных кавычках**:

```
ssh -i ~/.ssh/dev_deploy "${DEV_USER}@${DEV_HOST}" bash -lc "
  …
"
```

Внутри двойных кавычек обратная кавычка — **подстановка команды**, и
выполняет её оболочка **раннера**, ещё до отправки по ssh. Поэтому
безобидный комментарий

```
# Каталог проекта смонтирован внутрь (`volumes: ./:/app`), а сам
```

перестаёт быть комментарием: текст между кавычками исполняется, а
результат подставляется в скрипт. Пары кавычек при этом **пересекают
строки**, так что испорченной оказывается не та строка, где ошибка
видна глазом.

Автор правки экранировал ``$(…)`` — и не экранировал ``` ` ``` в
комментариях, которые сам же и написал. Это тот же дефект в другом
написании: между агентом и файлом два разбора escape-последовательностей,
и ни один не виден в выводе.

# Почему страж, а не аккуратность

Правка держится ровно до следующего комментария с обратной кавычкой.
Комментарий пишут, чтобы объяснить соседу, — то есть в самом безопасном
на вид месте файла. Правило без сторожа есть совпадение.

# Границы стража

Он ловит **написание**, а не смысл: экранированная кавычка пройдёт, даже
если подстановка задумана ошибочно. И он смотрит только блоки, открытые
``bash -lc "`` — другой способ передать скрипт по ssh он не увидит.
Названный предел, а не закрытая граница.
"""

from __future__ import annotations

from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
WORKFLOW = REPO_ROOT / ".github" / "workflows" / "deploy-dev.yml"

#: Открывает блок, который оболочка раннера разбирает как двойные кавычки.
BLOCK_OPEN = 'bash -lc "'


def _bare_backticks(line: str) -> int:
    """Сколько обратных кавычек в строке НЕ экранировано.

    Проходим посимвольно, а не регулярным выражением: ``\\`` съедает
    следующий символ, и только так экранированная кавычка отличается от
    голой. Регулярка с look-behind на этом уже ошибалась.
    """
    count = 0
    i = 0
    while i < len(line):
        if line[i] == "\\":
            i += 2
            continue
        if line[i] == "`":
            count += 1
        i += 1
    return count


def _blocks(text: str) -> list[tuple[int, list[str]]]:
    """Блоки ``bash -lc "…"`` как (номер первой строки, строки блока)."""
    out: list[tuple[int, list[str]]] = []
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        if BLOCK_OPEN in lines[i]:
            start = i + 1
            body: list[str] = []
            j = i + 1
            while j < len(lines) and lines[j].strip() != '"':
                body.append(lines[j])
                j += 1
            out.append((start + 1, body))
            i = j
        i += 1
    return out


def test_workflow_is_where_we_think_it_is() -> None:
    """Присутствие — впереди отсутствия.

    Без этой проверки переименованный или удалённый файл дал бы ноль
    блоков, ноль нарушений и зелёный страж. Пустой прогон — не зелёный
    прогон.
    """
    assert WORKFLOW.is_file(), f"{WORKFLOW} не найден — страж смотрит не туда"


def test_ssh_blocks_exist() -> None:
    """Блоки должны найтись: ноль блоков — отдельный исход, не успех."""
    blocks = _blocks(WORKFLOW.read_text(encoding="utf-8"))
    assert blocks, (
        'в deploy-dev.yml не найдено ни одного блока `bash -lc "`. '
        "Либо способ передачи скрипта сменили, либо страж ослеп — "
        "оба случая требуют разбора, а не молчания."
    )


def test_no_bare_backticks_inside_ssh_blocks() -> None:
    """Голая ` внутри блока исполняется оболочкой РАННЕРА (11.09.2026)."""
    offenders: list[str] = []
    for start, body in _blocks(WORKFLOW.read_text(encoding="utf-8")):
        for offset, line in enumerate(body):
            bare = _bare_backticks(line)
            if bare:
                offenders.append(
                    f"  строка {start + offset}: голых ` = {bare} | {line.strip()[:80]}"
                )

    assert not offenders, (
        "В скрипте, уходящем по ssh, есть НЕЭКРАНИРОВАННЫЕ обратные кавычки.\n"
        "Внутри двойных кавычек это подстановка команды, и выполнит её\n"
        "оболочка раннера, а не хост. Комментарий перестаёт быть комментарием.\n"
        "Так упала выкладка 11.09.2026: `bash: line 35: path: No such file`.\n"
        "Ставьте \\` вместо `.\n" + "\n".join(offenders)
    )


@pytest.mark.parametrize(
    ("line", "expected"),
    [
        ("# обычный комментарий", 0),
        ("# с `голой` кавычкой", 2),
        ("# с \\`экранированной\\` кавычкой", 0),
        ("# смешанный: \\`ок\\` и `нет`", 2),
    ],
)
def test_counter_itself(line: str, expected: int) -> None:
    """Положительный контроль на сам счётчик.

    Без него страж, разучившийся видеть кавычки, зеленел бы на любом
    файле — и «нарушений нет» было бы неотличимо от «не проверялось».
    """
    assert _bare_backticks(line) == expected
