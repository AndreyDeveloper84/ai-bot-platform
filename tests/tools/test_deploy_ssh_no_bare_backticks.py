"""Страж: в шаге, уходящем по ssh, нет голых обратных кавычек.

# Что сломалось 11.09.2026

Выкладка пилота упала на ``bash: line 35: path: No such file or directory``.
Образы собрались, а ``migrate``, ``collectstatic`` и ``up -d`` не выполнились:
пилот остался на старых контейнерах при новом дереве.

Причина — обратные кавычки в КОММЕНТАРИЯХ внутри скрипта, который уходит по
ssh одной строкой в двойных кавычках. Внутри двойных кавычек обратная кавычка
это подстановка команды, и выполняет её оболочка раннера, ещё до отправки.
Пары кавычек пересекают строки, поэтому испорченной оказывается не та строка,
где ошибка видна глазом.

# Почему эта редакция, а не разбор текста построчно

Первая редакция стража искала блоки по литералу ``bash -lc "`` и закрывала
их на первой строке, равной ``"``. Обе привязки обходятся, и обход проверен
опытом:

```
bash -l -c "          → блоков 0, нарушений 0, ЗЕЛЕНО
одинокая " в теле     → блок закрыт рано, остаток не проверен
контроль bash -lc "   → 2 нарушения, страж работает
```

Первый обход опаснее второго: проверка «блоков не ноль» при нём остаётся
зелёной, потому что канонические блоки в файле есть. То есть защита от
слепоты подтверждалась чужими находками — «зелень из соседства» внутри
одного файла.

**Привязка к литералу — это привязка к написанию**, на каком бы уровне
обобщения автор ни думал, что стоит. Поэтому здесь нет ни литерала открытия,
ни границ тела: берётся ШАГ целиком по YAML, и если в его ``run`` есть
``ssh``, считаются все голые кавычки в нём.

# Границы, названные прямо

Ложное срабатывание возможно: шаг, где ssh есть, а скрипт передан в
одинарных кавычках, потребует экранирования без нужды. Это отказ в
безопасную сторону — он требует разбора, а не молчит.

Страж ловит написание, а не смысл: экранированная кавычка пройдёт, даже если
подстановка задумана ошибочно.
"""

from __future__ import annotations

from pathlib import Path

import pytest
import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
WORKFLOW = REPO_ROOT / ".github" / "workflows" / "deploy-dev.yml"


def bare_backticks(text: str) -> int:
    """Сколько обратных кавычек в тексте НЕ экранировано.

    Посимвольно, а не регулярным выражением: ``\\`` съедает следующий
    символ, и только так экранированная кавычка отличается от голой.
    Регулярка с look-behind на этом ошибается — ``\\\\`` (литеральный слэш)
    она считает экранированием следующей кавычки.
    """
    count = 0
    i = 0
    while i < len(text):
        if text[i] == "\\":
            i += 2
            continue
        if text[i] == "`":
            count += 1
        i += 1
    return count


def ssh_steps(doc: dict) -> list[tuple[str, str]]:
    """Шаги, чей ``run`` зовёт ssh, как (имя шага, тело run).

    Без привязки к форме вызова: ``bash -lc``, ``bash -l -c``,
    ``bash --login -c`` и всё прочее попадает одинаково.
    """
    out: list[tuple[str, str]] = []
    for job in (doc.get("jobs") or {}).values():
        for step in (job or {}).get("steps") or []:
            run = (step or {}).get("run") or ""
            if "ssh " in run:
                out.append((step.get("name") or "<без имени>", run))
    return out


def test_workflow_is_where_we_think_it_is() -> None:
    """Присутствие впереди отсутствия: переименованный файл дал бы зелень."""
    assert WORKFLOW.is_file(), f"{WORKFLOW} не найден — страж смотрит не туда"


def test_ssh_steps_exist() -> None:
    """Ноль ssh-шагов — отдельный исход, не успех."""
    doc = yaml.safe_load(WORKFLOW.read_text(encoding="utf-8"))
    steps = ssh_steps(doc)
    assert steps, (
        "в deploy-dev.yml не найдено ни одного шага с ssh. Либо способ "
        "выкладки сменили, либо страж ослеп — оба случая требуют разбора."
    )


def test_no_bare_backticks_in_ssh_steps() -> None:
    """Голая ` исполняется оболочкой РАННЕРА (падение 11.09.2026)."""
    doc = yaml.safe_load(WORKFLOW.read_text(encoding="utf-8"))
    offenders = []
    for name, run in ssh_steps(doc):
        for lineno, line in enumerate(run.splitlines(), 1):
            n = bare_backticks(line)
            if n:
                offenders.append(f"  шаг «{name}», строка {lineno}: {line.strip()[:80]}")

    assert not offenders, (
        "В скрипте, уходящем по ssh, есть НЕЭКРАНИРОВАННЫЕ обратные кавычки.\n"
        "Внутри двойных кавычек это подстановка команды, и выполнит её\n"
        "оболочка раннера, а не хост. Комментарий перестаёт быть комментарием.\n"
        "Ставьте \\` вместо `.\n" + "\n".join(offenders)
    )


