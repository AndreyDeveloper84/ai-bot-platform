#!/bin/bash
# Страж поздней выкладки (DRF-2073): проверенный SHA всё ещё голова dev?
#
# 17.09.2026: перезапущенный СТАРЫЙ ci-прогон на 41bc4514 завершился позже,
# чем выкладка 7e80fa98, его workflow_run запустил deploy-dev — и стенд
# откатился на коммит назад. Существовавший `::warning::голова dev ушла
# вперёд…` предупреждал и выкладывал; значит откат допускался по построению.
#
# Правило владельца 17.09: deploy по workflow_run ПРЕКРАЩАЕТСЯ, если его
# проверенный SHA уже не голова dev. «Голова ушла вперёд, но у неё нет своей
# зелени» — тоже прекращение: следующий зелёный прогон головы выложит её сам.
# Ручной workflow_dispatch берёт голову ветки, на которой нажали, — его это
# правило не касается.
#
# Вход — аргументами, а не сетью: скрипт НЕ ходит в git сам, чтобы его можно
# было прогнать unit-тестом с любыми SHA (tests/tools/test_deploy_sha_is_dev_head.py).
# Кто зовёт, тот и снимает голову: `git ls-remote origin refs/heads/dev`.
#
#   bash tools/ci/deploy_sha_is_dev_head.sh <event_name> <verified_sha> <dev_head_sha>
#
# Коды выхода — три исхода своим знаком, не двумя:
#   0  выкладывать: SHA = голова dev, либо это workflow_dispatch
#   3  superseded: SHA лежит позади головы — стенд не трогать, прогон отменить
#   1  отказ по форме: SHA или голова не 40 hex, событие неизвестно — сторож
#      слеп, выкладка запрещена (fail-closed)
set -euo pipefail

EVENT="${1:-}"
SHA="${2:-}"
DEV_HEAD="${3:-}"

is_sha() { printf '%s' "$1" | grep -Eq '^[0-9a-f]{40}$'; }

if ! is_sha "$SHA"; then
  echo "::error::проверенный SHA не 40 hex (event=${EVENT}, got='${SHA}') — выкладка запрещена"
  exit 1
fi

case "$EVENT" in
  workflow_dispatch)
    # Ручной запуск берёт голову той ветки, на которой нажали; правило
    # «не голова dev — прекратить» к нему не применяется по решению владельца.
    echo "::notice::workflow_dispatch: проверенный ${SHA} выкладывается как есть"
    exit 0
    ;;
  workflow_run)
    ;;
  *)
    echo "::error::неизвестное событие '${EVENT}' — сторож не знает, применять ли правило; выкладка запрещена"
    exit 1
    ;;
esac

if ! is_sha "$DEV_HEAD"; then
  echo "::error::голова dev не 40 hex (got='${DEV_HEAD}') — сторож слеп, выкладка запрещена"
  exit 1
fi

if [ "$SHA" != "$DEV_HEAD" ]; then
  # notice, не error: это не поломка, а поздний прогон, которому нечего
  # выкладывать. Красный здесь звал бы человека чинить то, что уже верно.
  echo "::notice::superseded: проверенный ${SHA} уже не голова dev (${DEV_HEAD}) — стенд не тронут, голову выложит её собственный зелёный прогон"
  exit 3
fi

echo "::notice::проверенный ${SHA} — голова dev, выкладывается"
exit 0
